def realify(M):
    """complex n x n -> real 2n x 2n: [[Re, -Im], [Im, Re]]."""
    n = M.shape[0]
    R = sp.zeros(2 * n)
    for i in range(n):
        for j in range(n):
            re, im = sp.re(M[i, j]), sp.im(M[i, j])
            R[i, j], R[i, j + n] = re, -im
            R[i + n, j], R[i + n, j + n] = im, re
    return R


def lie_dim(gens):
    basis = []

    def indep(ms):
        return sp.Matrix([list(m) for m in ms]).rank() == len(ms)

    for g in gens:
        if indep(basis + [g]):
            basis.append(g)
    grew = True
    while grew:
        grew = False
        for a_, b_ in itertools.combinations(list(basis), 2):
            c = a_ * b_ - b_ * a_
            if any(e != 0 for e in c) and indep(basis + [c]):
                basis.append(c)
                grew = True
    return len(basis)


