"""ASSESS-1059 r3: exact generic checks on where the exponent comes from (WIP / UNVERIFIED).

Label: X (exact computation on generic matrices and columns). No OI mechanism is computed.
Imports no earlier script (none of p1_*, p2_*, r2_*, rv_*, rv2_*). Run: python3 -I r3_exponent_source.py

Readout convention (unrenormalised H-RF_p): a column, or a Kraus family's outcome table on one input,
is p-admissible iff the unrenormalised values |amp|^p, summed over every outcome and output entry,
equal 1.

E1  The forced exponent is the column's own normalisation exponent.  For a column with >= 2
    nonzero entries, all of modulus in (0,1), h(p) = sum |c_i|^p is strictly decreasing in p, so
    h(p) = 1 has at most one root.  Exact instances: a rational unit (l^2) column -> p = 2 only;
    a stochastic (l^1) column -> p = 1 only; an l^3 column -> p = 3 only.  A non-monomial doubly
    stochastic matrix acting linearly on an amplitude vector is p-admissible on its columns only
    at p = 1.  Non-vacuity: each column fails at the other two exponents.
E2  Kraus operators of a complete family and dilation columns.  (a) Exhaustive over support
    patterns (n <= 3 inputs, m <= 3 Kraus operators, output dimension n): if every column of the
    stacked dilation V has exactly one nonzero entry, orthonormality of V's columns forces those
    entries to sit at distinct (operator, row) positions, and then every Kraus block has at most
    one nonzero entry per row and per column (a monomial pattern).  Contrapositive: a
    non-monomial Kraus operator of a complete family yields a dilation column with >= 2 nonzero
    entries.  (b) Instances: {|0><+|, |1><->|} and {|0><+|, |0><->|} are complete, non-monomial,
    and their outcome tables are p-admissible only at p = 2.  (c) Control: the unscaled
    K = [[1,1],[0,0]] is not a contraction (K^dag K has eigenvalue 2), so it lies in no complete
    family; K/sqrt2 = |0><+| is a contraction.
E3  Root insertion returns the inserted exponent.  The family {w^(1/q) P_s} over 2^k permutations,
    with counting weight w = 2^-k on each, is p-admissible iff p = q (q = 2, 3, 4; k = 1..4).  It is
    a complete family (sum K^dag K = I) iff q = 2.  So within quadratic Kraus completeness only the
    square root is consistent, and the exponent the table then returns is the one inserted.
E4  The complex driven transition carries a phase (generic 3x3 matrices).  With X = |0><1| + |1><0|
    and G(t) the one-parameter group of the transposition (0 1) that is the identity on its fixed
    state and e^(i pi t) on the antisymmetric vector, e^(-i th X) = e^(-i th) G(2 th / pi)
    diag(1, 1, e^(i th)) exactly (symbolic th).  At th = pi/2, e^(-i pi/2 X) swap(0 1) =
    -i diag(1, 1, i).  Control: the real rotation e^(th (E01 - E10)) is non-monomial and moves
    the all-ones vector; the Lie algebra generated by it and its permutation conjugates has real
    dimension 3 (so(3)), against 8 (su(3)) for iX and its conjugates.
"""
import itertools

import sympy as sp

p = sp.symbols('p', positive=True)
res = {}


def strictly_decreasing_root(col, q):
    """>= 2 entries, all moduli in (0,1); return True iff sum |c|^q == 1 exactly.

    Uniqueness of the root follows from strict decrease: d/dp |c|^p = |c|^p log|c| < 0 for
    |c| in (0,1); the derivative sign is also checked exactly at p = q.
    """
    a = [sp.nsimplify(sp.Abs(c)) for c in col if c != 0]
    if len(a) < 2 or not all(0 < x < 1 for x in a):
        return False
    deriv = sum(x ** q * sp.log(x) for x in a)
    return sp.simplify(sum(x ** q for x in a) - 1) == 0 and bool(deriv < 0)


def table_sum(cols):
    return sum(sp.Abs(x) ** p for x in cols if x != 0)


# E1
l2 = [sp.Rational(3, 13), sp.Rational(4, 13), sp.Rational(12, 13)]
l1 = [sp.Rational(1, 3), sp.Rational(2, 3)]
l3 = [2 ** sp.Rational(-1, 3), 2 ** sp.Rational(-1, 3)]
e1 = strictly_decreasing_root(l2, 2) and strictly_decreasing_root(l1, 1) and strictly_decreasing_root(l3, 3)
for col, q in ((l2, 2), (l1, 1), (l3, 3)):
    for other in (1, 2, 3):
        if other != q:
            e1 &= sp.simplify(sum(sp.Abs(x) ** other for x in col) - 1) != 0
DS = sp.Matrix([[sp.Rational(1, 3), sp.Rational(2, 3)], [sp.Rational(2, 3), sp.Rational(1, 3)]])
e1 &= any(sum(1 for x in DS.row(i) if x != 0) > 1 for i in range(2))
e1 &= all(strictly_decreasing_root(list(DS.col(j)), 1) for j in range(2))
e1 &= all(sp.simplify(sum(x ** 2 for x in DS.col(j)) - 1) != 0 for j in range(2))
res['E1'] = e1

# E2 (a): exhaustive support patterns
e2a = True
count = 0
for n in (1, 2, 3):
    for m in (1, 2, 3):
        positions = [(r, i) for r in range(m) for i in range(n)]
        for assign in itertools.product(positions, repeat=n):
            count += 1
            # single-entry unit columns: Gram entry (j, j') has modulus 1 iff same position, else 0
            orthonormal = all(assign[j] != assign[jj] for j in range(n) for jj in range(j + 1, n))
            injective = len(set(assign)) == n
            e2a &= orthonormal == injective
            if orthonormal:
                for r in range(m):
                    rows = [i for (rr, i) in assign if rr == r]
                    e2a &= len(rows) == len(set(rows))      # <= 1 nonzero per row of block r
                    # <= 1 nonzero per column of block r: column j contributes to one block only
e2a &= count == sum(((m * n) ** n) for n in (1, 2, 3) for m in (1, 2, 3))

# E2 (b): instances
s2 = sp.sqrt(2)
plus_bra = sp.Matrix([[1, 1]]) / s2
minus_bra = sp.Matrix([[1, -1]]) / s2
ket0 = sp.Matrix([[1], [0]])
ket1 = sp.Matrix([[0], [1]])
fams = {'0+,1-': [ket0 * plus_bra, ket1 * minus_bra], '0+,0-': [ket0 * plus_bra, ket0 * minus_bra]}
e2b = True
for name, Ks in fams.items():
    e2b &= sp.simplify(sum((K.H * K for K in Ks), sp.zeros(2, 2)) - sp.eye(2)) == sp.zeros(2, 2)
    e2b &= all(any(sum(1 for x in K.row(i) if x != 0) > 1 for i in range(2)) for K in Ks)
    V = sp.Matrix.vstack(*Ks)
    for j in range(2):
        col = list(V.col(j))
        e2b &= sum(1 for x in col if x != 0) >= 2
        e2b &= sp.simplify(table_sum(col) - 2 ** (1 - p / 2)) == 0
        e2b &= strictly_decreasing_root(col, 2)

# E2 (c): control
Kraw = sp.Matrix([[1, 1], [0, 0]])
e2c = sp.Integer(2) in (Kraw.H * Kraw).eigenvals()
e2c &= max((Kraw.H * Kraw / 2).eigenvals().keys()) == 1
e2c &= all(sum(1 for x in Kraw.col(j) if x != 0) == 1 for j in range(2))   # columns monomial
res['E2'] = e2a and e2b and e2c


# E3
def P(perm):
    M = sp.zeros(len(perm), len(perm))
    for j, i in enumerate(perm):
        M[i, j] = 1
    return M


perms3 = list(itertools.permutations(range(3)))
e3 = True
for k in (1, 2):
    chosen = perms3[: 2 ** k]
    w = sp.Rational(1, 2 ** k)
    for q in (2, 3, 4):
        amp = w ** sp.Rational(1, q)
        Ks = [amp * P(s) for s in chosen]
        V = sp.Matrix.vstack(*Ks)
        for j in range(3):
            col = [x for x in V.col(j) if x != 0]
            e3 &= len(col) == 2 ** k
            e3 &= strictly_decreasing_root(col, q)
            for other in (2, 3, 4):
                if other != q:
                    e3 &= sp.simplify(sum(sp.Abs(x) ** other for x in col) - 1) != 0
        complete = sp.simplify(sum((K.H * K for K in Ks), sp.zeros(3, 3)) - sp.eye(3)) == sp.zeros(3, 3)
        e3 &= complete == (q == 2)
# k = 3, 4 on the scalar level (2^k copies of one amplitude)
for k in (3, 4):
    for q in (2, 3, 4):
        amp = sp.Rational(1, 2 ** k) ** sp.Rational(1, q)
        e3 &= sp.solve(sp.Eq(2 ** k * amp ** p, 1), p) == [q]
        e3 &= (sp.simplify(2 ** k * amp ** 2 - 1) == 0) == (q == 2)
res['E3'] = e3

# E4
th = sp.symbols('theta', real=True)
X = sp.Matrix([[0, 1, 0], [1, 0, 0], [0, 0, 0]])
drive = sp.simplify((-sp.I * th * X).exp())
sym = sp.Matrix([1, 1, 0]) / sp.sqrt(2)
anti = sp.Matrix([1, -1, 0]) / sp.sqrt(2)
e2v = sp.Matrix([0, 0, 1])


def G(t):
    return sym * sym.T + sp.exp(sp.I * sp.pi * t) * anti * anti.T + e2v * e2v.T


rhs = sp.exp(-sp.I * th) * G(2 * th / sp.pi) * sp.diag(1, 1, sp.exp(sp.I * th))
e4 = sp.simplify((drive - rhs).rewrite(sp.exp)) == sp.zeros(3, 3)
swap = sp.Matrix([[0, 1, 0], [1, 0, 0], [0, 0, 1]])
e4 &= sp.simplify(drive.subs(th, sp.pi / 2) * swap - (-sp.I) * sp.diag(1, 1, sp.I)) == sp.zeros(3, 3)
A = sp.Matrix([[0, 1, 0], [-1, 0, 0], [0, 0, 0]])
rot = (sp.pi / 4 * A).exp()
e4 &= any(sum(1 for x in rot.row(i) if x != 0) > 1 for i in range(3))
ones = sp.Matrix([1, 1, 1])
e4 &= sp.Matrix.hstack(ones, sp.simplify(rot * ones)).rank() == 2       # moves the all-ones ray


def lie_dim(gens):
    def vec(M):
        return [sp.re(x) for x in M] + [sp.im(x) for x in M]
    basis = []

    def add(M):
        cand = basis + [vec(M)]
        if sp.Matrix(cand).rank() > len(basis):
            basis.append(vec(M))
            mats.append(M)
            return True
        return False
    mats = []
    for g in gens:
        add(g)
    changed = True
    while changed:
        changed = False
        for M1 in list(mats):
            for M2 in list(mats):
                if add(sp.expand(M1 * M2 - M2 * M1)):
                    changed = True
    return len(basis)


perms = [P(s) for s in itertools.permutations(range(3))]
real_gens = [Pm * A * Pm.T for Pm in perms]
cplx_gens = [Pm * (sp.I * X) * Pm.T for Pm in perms]
e4 &= lie_dim(real_gens) == 3 and lie_dim(cplx_gens) == 8
res['E4'] = e4

