def as_sp(f):
    perm, sign = [], []
    for k, b in enumerate(BASIS):
        img = f(b)
        nz = [(i, j) for i in range(4) for j in range(4) if img[i][j] != 0]
        assert len(nz) == 1 and img[nz[0][0]][nz[0][1]] in (1, -1), "not a signed permutation"
        i, j = nz[0]
        perm.append(4 * i + j)
        sign.append(int(img[i][j]))
    return (tuple(perm), tuple(sign))


def sp_mul(g, f):  # g o f
    pf, sf = f
