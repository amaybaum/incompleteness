import sys
from itertools import product

import sympy as sp

PASS, FAIL = [], []


def check(cid, ok, msg):
    print(f"{cid:4s} {'PASS' if ok else 'FAIL'}  {msg}")
    (PASS if ok else FAIL).append(cid)


I = sp.I
r2 = sp.sqrt(2)
s0 = sp.eye(2)
sx = sp.Matrix([[0, 1], [1, 0]])
sy = sp.Matrix([[0, -I], [I, 0]])
sz = sp.Matrix([[1, 0], [0, -1]])
SIG = [s0, sx, sy, sz]
kron = sp.kronecker_product
I2 = sp.eye(2)


def simp(M):
    return M.applyfunc(lambda z: sp.nsimplify(sp.expand(z)))


def dagger(M):
    return M.conjugate().T


def Mdict(w):
    out = sp.zeros(4, 4)
    for mu in range(4):
        for nu in range(4):
            if w[mu, nu] != 0:
                out += w[mu, nu] * kron(SIG[mu], SIG[nu])
    return out / 4


def bloch(U):
    B = sp.zeros(3, 3)
    for j in range(3):
        for k in range(3):
            B[j, k] = sp.nsimplify(sp.expand((SIG[j + 1] * U * SIG[k + 1] * dagger(U)).trace() / 2))
    return B


def hom(N):
    Nh = sp.zeros(4, 4)
    Nh[0, 0] = 1
    Nh[1:, 1:] = N
    return Nh


def E(mu, nu):
    w = sp.zeros(4, 4)
    w[mu, nu] = 1
    return w


# ---------------- X1 ----------------
P = sp.diag(1, sp.Rational(3, 5) + I * sp.Rational(4, 5))
S = sp.diag(1, I)
H = sp.Matrix([[1, 1], [1, -1]]) / r2
# the 24 one-qubit Cliffords modulo phase, generated by H and S
def canon(U):
    """representative modulo global phase: first nonzero entry made real positive"""
    for z in list(U):
        z = sp.nsimplify(sp.expand(z))
        if z != 0:
            ph = z / sp.sqrt(sp.expand(z * sp.conjugate(z)))
            return simp(U / ph)
    raise ValueError


def key(U):
    return tuple(sp.srepr(sp.nsimplify(z)) for z in canon(U))


cliff, keys, frontier = [], set(), [sp.eye(2)]
while frontier:
    nxt = []
    for U in frontier:
        k = key(U)
        if k in keys:
            continue
        keys.add(k)
        cliff.append(canon(U))
        for G in (H, S):
            nxt.append(simp(G * U))
    frontier = nxt
CYC = sp.Matrix([[0, 0, 1], [1, 0, 0], [0, 1, 0]])
V = next(U for U in cliff if bloch(U) == CYC)
x1 = True
for U in (P, S, H, V):
    Nh = hom(bloch(U))
    for mu in range(4):
        for nu in range(4):
            w = E(mu, nu)
            lhsC = simp(Mdict(Nh * w))
            rhsC = simp(kron(U, I2) * Mdict(w) * dagger(kron(U, I2)))
            lhsT = simp(Mdict(w * Nh.T))
            rhsT = simp(kron(I2, U) * Mdict(w) * dagger(kron(I2, U)))
            if lhsC != rhsC or lhsT != rhsT:
                x1 = False
check("X1", x1 and len(cliff) == 24,
      f"24 Cliffords generated; for U in {{drive step, S, H, cyc3 lift}} and all 16 basis tables, "
      f"M(actC B(U) w) = Ad(U(x)I) M(w) and M(actT B(U) w) = Ad(I(x)U) M(w); B(V) = cycEquiv")
print(f"     drive step B(P) = {bloch(P).tolist()}")

# ---------------- K(Z_F) data ----------------
SIGNS = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
PSI = [sp.Matrix([1, a * b, a, -b]) / 2 for (a, b) in SIGNS]
for i in range(4):
    for j in range(4):
        assert sp.nsimplify((dagger(PSI[i]) * PSI[j])[0]) == (1 if i == j else 0)


def ov2(u, v):
    a = sp.expand((dagger(u) * v)[0])
    return sp.nsimplify(sp.expand(a * sp.conjugate(a)))


def norm2(u):
    return sp.nsimplify(sp.expand((dagger(u) * u)[0]))


def certified_member(phi):
    """y = phi phi^*/|phi|^2 is PSD and tr(y D_t) = 1 - 2|<psi_t|phi>|^2/|phi|^2 >= 0 for all t."""
    n2 = norm2(phi)
    return all(sp.nsimplify(1 - 2 * ov2(p, phi) / n2) >= 0 for p in PSI)


def pair_with_defect_image(phi, psi_img):
    """tr(y X) for y = phi phi^*/|phi|^2 and X = I - 2 psi_img psi_img^* (unit psi_img)."""
    return sp.nsimplify(1 - 2 * ov2(psi_img, phi) / norm2(phi))


def find_witness(imgs):
    cands = list(imgs)
    for s_ in range(4):
        for t in range(4):
            for c in (1, -1, I, -I):
                cands.append(simp(imgs[s_] + c * PSI[t]))
    for phi in cands:
        if norm2(phi) == 0 or not certified_member(phi):
            continue
        for s_ in range(4):
            v = pair_with_defect_image(phi, imgs[s_])
            if v < 0:
                return phi, s_, v
    return None


def permutes_lines(imgs):
    for u in imgs:
        ovs = [ov2(p, u) for p in PSI]
        if sorted(ovs) != [0, 0, 0, 1]:
            return False
    return True


PAULI_KEYS = {key(M) for M in (s0, sx, sy, sz)}
x2, x4, n_ex = True, True, 0
stab_report = {}
for tok in ("A", "B"):
    stab = []
    for U in cliff:
        L = kron(U, I2) if tok == "A" else kron(I2, U)
        imgs = [simp(L * p) for p in PSI]
        if permutes_lines(imgs):
            stab.append(key(U))
            continue
        w = find_witness(imgs)
        if w is None:
            x2 = False
            continue
        phi, s_, v = w
        n_ex += 1
        # X4 control: the same witness on the image of every Bell projector (in Q3) is >= 0
        for p in PSI:
            if ov2(simp(L * p), phi) < 0:
                x4 = False
    stab_report[tok] = stab
    if set(stab) != PAULI_KEYS:
        x2 = False
check("X2", x2 and n_ex == 40,
      f"token A: {len(stab_report['A'])} stabilizing Cliffords = the Paulis "
      f"{set(stab_report['A']) == PAULI_KEYS}; token B: {len(stab_report['B'])} = Paulis "
      f"{set(stab_report['B']) == PAULI_KEYS}; {n_ex} exclusions certified by witnesses")

# ---------------- X3 ----------------
c, s = sp.symbols("c s", real=True)
Rz = sp.diag(1, c + I * s)
Rx = H * Rz * H
Wz, Wx = S, H * S * H
x3 = True
laws = []
for tok in ("A", "B"):
    for name, R, W in (("R_z", Rz, Wz), ("R_x", Rx, Wx)):
        for sgn in (1, -1):
            Wm = W if sgn == 1 else dagger(W)
            Lw = kron(Wm, I2) if tok == "A" else kron(I2, Wm)
            LR = kron(R, I2) if tok == "A" else kron(I2, R)
            for idx in range(4):
                phi = simp(Lw * PSI[idx])
                if not certified_member(phi):
                    x3 = False
                img = LR * PSI[idx]
                amp = (dagger(phi) * img)[0]
                val = sp.expand(1 - 2 * sp.expand(amp * sp.conjugate(amp)) / norm2(phi))
                val = sp.simplify(val.subs(c ** 2, 1 - s ** 2))
                val = sp.expand(val)
                laws.append((tok, name, sgn, idx, val))
                if sp.simplify(val - (-sgn * s)) != 0:
                    x3 = False
                # X4 control on Q3: the same witness against the image of the Bell projector psi_idx
                # (in Q3), evaluated exactly at rational points of the circle, is >= 0
                for (cc, ss) in ((sp.Rational(3, 5), sp.Rational(4, 5)), (sp.Rational(-3, 5), sp.Rational(4, 5)),
                                 (sp.Rational(3, 5), sp.Rational(-4, 5)), (0, 1), (1, 0)):
                    q = sp.nsimplify(sp.expand((amp * sp.conjugate(amp)).subs({c: cc, s: ss})))
                    if q < 0:
                        x4 = False
uniq = sorted({str(v) for (_, _, _, _, v) in laws})
check("X3", x3, f"{len(laws)} symbolic pairings (2 tokens x 2 flows x 2 witnesses x 4 defects); "
      f"values {uniq} (= -s for W, +s for W^-1); every witness certified in PSD n Z_F*")
check("X4", x4, "Q3 control: every X2 and X3 witness pairs >= 0 with the image of every Bell "
      "projector under the same local map")

print()
print(f"PASS {len(PASS)}  FAIL {len(FAIL)}")
print("VERDICT B8-EXACT" if not FAIL else "VERDICT B8-FAILED " + " ".join(FAIL))
sys.exit(0)
