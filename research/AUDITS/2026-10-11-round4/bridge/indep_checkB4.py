class Z8:
    """Q(zeta_8) as a0 + a1 z + a2 z^2 + a3 z^3 with z^4 = -1 (z = e^{i pi/4}, z^2 = i)."""
    __slots__ = ('a',)

    def __init__(self, a):
        self.a = tuple(Fr(x) for x in a)

    @staticmethod
    def fromG(g):
        return Z8((g.re, 0, g.im, 0))

    def __add__(self, o):
        return Z8(tuple(x + y for x, y in zip(self.a, o.a)))

    def __sub__(self, o):
        return Z8(tuple(x - y for x, y in zip(self.a, o.a)))

    def __mul__(self, o):
        c = [Fr(0)] * 7
        for i, x in enumerate(self.a):
            if x == 0:
                continue
            for j, y in enumerate(o.a):
                if y != 0:
                    c[i + j] += x * y
        # z^4 = -1: fold degrees 4..6
        return Z8((c[0] - c[4], c[1] - c[5], c[2] - c[6], c[3]))

    def conj(self):  # z -> z^7 = -z^3, z^2 -> -z^2, z^3 -> z^5 = -z
        a0, a1, a2, a3 = self.a
        return Z8((a0, -a3, -a2, -a1))

    def is_real(self):
        return self.a[2] == 0 and self.a[1] == -self.a[3]

    def real_pq(self):  # a real element as p + q sqrt2 (sqrt2 = z - z^3)
        assert self.is_real(), self.a
        return self.a[0], self.a[1]

    def __eq__(self, o):
        return self.a == o.a


