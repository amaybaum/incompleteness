def ray_equal(A, B):  # A = c B, c != 0
    c = None
    for i in range(len(A)):
        for j in range(len(A)):
            a, b = A[i][j], B[i][j]
            if a.iszero() != b.iszero():
                return False
            if not b.iszero():
                q = a * b.inv()
                if c is None:
                    c = q
                elif not (q == c):
                    return False
    return c is not None


