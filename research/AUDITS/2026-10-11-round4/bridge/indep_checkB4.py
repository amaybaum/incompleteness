def sign_p_q_sqrt2(p, q):  # exact sign of p + q sqrt2
    if q == 0:
        return (p > 0) - (p < 0)
    if p == 0:
        return (q > 0) - (q < 0)
    if (p > 0) == (q > 0):
        return 1 if p > 0 else -1
    # opposite signs: compare p^2 with 2 q^2
    if p * p > 2 * q * q:
        return 1 if p > 0 else -1
    if p * p < 2 * q * q:
        return 1 if q > 0 else -1
    return 0


