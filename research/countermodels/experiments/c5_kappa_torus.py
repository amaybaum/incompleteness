# K3: the torus node S2
def Rz(c, sn): return sp.Matrix([[c - iu * sn, 0], [0, c + iu * sn]])            # exp(-i theta Z/2) with (cos, sin) of theta/2
def Rx(c, sn): return sp.Matrix([[c, -iu * sn], [-iu * sn, c]])
Dt = kron(Rz(Rt(3, 5), Rt(4, 5)), Rx(Rt(5, 13), Rt(12, 13)))
ft = fixed_space(Dt)
