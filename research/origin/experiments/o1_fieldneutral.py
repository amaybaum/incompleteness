"""o1_fieldneutral.py -- research/origin, node O1, tier F (field-neutral protocol towers).

QUESTION. Without the matrix carrier: does a classical substratum read by the observer (states = distributions
on configurations, operations = configuration maps, preparations = conditioning on protocol records) admit the
owner's H-sandwich witness? What exactly must change for it to appear?

MODEL (the smallest one with a visible bit and a readback memory). Omega = {0,1}^2, omega = (z, x); z is the
visible value, x a hidden readback memory; mu = uniform (the counting measure). The native reversible menu is
generated by swap(z,x), flip z, flip x, cnot z->x, cnot x->z (it generates all 24 permutations of Omega, the
kernel's ExchangesAvailable on four configurations). A state is a distribution nu on Omega (exact Fractions).
  obs        passive readout of z (record v, condition on z = v); the native readout of OI-STAGE / localLuders.
  D_pass     observe-and-forget with obs: nu -> sum_v nu|_{z=v}.
  D_fresh    path record into a fresh blank register r (attach r = 0, copy z into r, discard r).
  D_mem      the kernel recorder written into the memory register x (x := z), InternalObserver.recordInstr.
  D_x        re-randomize x (uniform mixture of id and flip x): memory erasure.
  obsKB      knowledge-balance readout (KB-D): read z, then re-randomize x. Used ONLY in the modified tower F8,
             from whose menu the passive obs is removed.
  sandwich   seed nu0, mixers M1, M2 (permutations), P(z = 0) with and without the dephasing between them.

DECISION RULE (fixed before the first run; verdict text generated from the measurements):
  VERDICT ENVELOPE-F HOLDS iff all checks pass and all countercontrols return their expected-false value; else
  VERDICT VOID. Checks:
   F0  the menu generates exactly the permutations of Omega (group order measured; must be 4! = 24).
   F1  passivity: D_pass = id and D_fresh = id on every reachable posterior of the passive tower (L <= 4).
   F2  every point mass of Omega is a reachable posterior (conditioning through swap-read-swap).
   F3  outcome determinism: every reachable point mass gives z a deterministic value, and every reachable
       posterior is a convex combination of reachable point masses (so the body's extreme points are them).
   F4  no permutation maps a point mass to a state with balanced z statistics (no balanced pure mixer).
   F5  sandwich visibility 0 for every reachable seed and every pair (M1, M2) of the 24 permutations, with
       D_pass and with D_fresh.
   F6  the classical-memory numbers: seed (z=0, x uniform), M1 = M2 = swap: P_coh = 1 and with D_x 1/2, while
       the seed is NOT extreme (it is the midpoint of two reachable point masses) and D_x moves a point mass.
   F7  D_mem gives the same numbers 1 and 1/2, and D_mem is not the identity on reachable point masses.
   F8  the KB-D tower (passive obs removed, obsKB added), L <= 5: (a) no reachable point mass, every posterior
       has all probabilities <= 1/2; (b) the reachable posteriors are exactly uniform plus the six pair states;
       (c) the six pair states have affine rank 3 and each is exposed (an octahedron); (d) swap maps z+ to the
       balanced extreme state x+; (e) sandwich P_coh = 1, P_deph = 1/2 with D_KB = obsKB-and-forget; (f) D_KB is
       the frame dephasing r z+ + (1-r) z- on every reachable state and is not the identity (invasive); (g) the
       z = 0 face of the reachable states is the single state z+.
   F9  three-bit robustness: Omega = {0,1}^3 (z visible; x, y hidden), menu swap(z,x), swap(x,y), flip x,
       cnot z->y; D_pass = id on every reachable posterior (L <= 3) and V = 0 for all seeds reached, M1 in a fixed
       subsample (<= 96) of the generated group and M2 in a fixed list (<= 6).
  Countercontrols (each must return False):
   CCF1 "no reachable point mass" in the KB-D tower with the passive obs added back;
   CCF2 V = 0 for the KB-D sandwich;
   CCF3 D_mem is the identity on the reachable point masses;
   CCF4 the seed (z=0, x uniform) is extreme in the passive tower's body.

Run: python3 -I -B o1_fieldneutral.py > o1_fieldneutral.out 2> o1_fieldneutral.err; echo "exit $?" >> o1_fieldneutral.err
"""

from fractions import Fraction as Fr
import itertools
import sympy as sp

RESULTS = []


def check(cid, ok, msg=""):
    RESULTS.append((cid, bool(ok), "check"))
    print(f"{cid:6s} {'PASS' if ok else 'FAIL'}  {msg}")


def counter(cid, value, msg=""):
    RESULTS.append((cid, not bool(value), "counter"))
    print(f"{cid:6s} {'CC-OK (False as required)' if not value else 'CC-FAIL (True)'}  {msg}")


# ------------------------------------------------------------- two-bit model

OM = [(z, x) for z in (0, 1) for x in (0, 1)]
IDX = {w: i for i, w in enumerate(OM)}
h = Fr(1, 2)


def perm_of(f):  # f : Omega -> Omega as an index permutation
    return tuple(IDX[f(w)] for w in OM)


GENS = {
    "swap": perm_of(lambda w: (w[1], w[0])),
    "flipz": perm_of(lambda w: (1 - w[0], w[1])),
    "flipx": perm_of(lambda w: (w[0], 1 - w[1])),
    "cnot_zx": perm_of(lambda w: (w[0], w[1] ^ w[0])),
    "cnot_xz": perm_of(lambda w: (w[0] ^ w[1], w[1])),
}


def compose(p, q):  # first q then p
    return tuple(p[q[i]] for i in range(len(q)))


def closure(gens, n):
    ident = tuple(range(n))
    seen = {ident}
    frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for s in gens:
                c = compose(s, g)
                if c not in seen:
                    seen.add(c)
                    new.append(c)
        frontier = new
    return sorted(seen)


def push(p, nu):
    out = [Fr(0)] * len(nu)
    for i, m in enumerate(nu):
        out[p[i]] += m
    return tuple(out)


def zval(i, OMx):
    return OMx[i][0]


def cond_z(nu, v, OMx):
    return tuple(m if zval(i, OMx) == v else Fr(0) for i, m in enumerate(nu))


def normalize(nu):
    s = sum(nu)
    return tuple(m / s for m in nu)


def D_pass(nu, OMx):
    a = cond_z(nu, 0, OMx)
    b = cond_z(nu, 1, OMx)
    return tuple(a[i] + b[i] for i in range(len(nu)))


def D_fresh(nu):
    # attach r = 0: states (z, x, r); copy z into r; discard r -> marginal on (z, x)
    ext = {}
    for i, m in enumerate(nu):
        z, x = OM[i]
        r = 0 ^ z
        ext[(z, x, r)] = ext.get((z, x, r), Fr(0)) + m
    out = [Fr(0)] * 4
    for (z, x, r), m in ext.items():
        out[IDX[(z, x)]] += m
    return tuple(out)


def D_mem(nu):  # recorder writes z into the memory register x (overwrite)
    out = [Fr(0)] * 4
    for i, m in enumerate(nu):
        z, x = OM[i]
        out[IDX[(z, z)]] += m
    return tuple(out)


def D_x(nu):  # re-randomize x
    fx = GENS["flipx"]
    a = push(fx, nu)
    return tuple(h * nu[i] + h * a[i] for i in range(4))


def P0(nu, OMx=OM):
    return sum((m for i, m in enumerate(nu) if zval(i, OMx) == 0), Fr(0))


MU = tuple([Fr(1, 4)] * 4)


def reachable(menu, L, readout, start=MU):
    """menu: dict name -> perm; readout: 'pass' or 'kb' (or both). Returns the set of posteriors (normalized)
    after every protocol of length <= L and every positive-probability record."""
    states = {start}
    layer = {start}
    for _ in range(L):
        nxt = set()
        for nu in layer:
            for p in menu.values():
                nxt.add(push(p, nu))
            for ro in readout:
                for v in (0, 1):
                    c = cond_z(nu, v, OM)
                    if sum(c) == 0:
                        continue
                    c = normalize(c)
                    if ro == "kb":
                        c = D_x(c)
                    nxt.add(c)
        nxt -= states
        states |= nxt
        layer = nxt
    return states


print("== o1_fieldneutral: tier F (classical protocol towers) ==")
print()
GROUP = closure(list(GENS.values()), 4)
check("F0", len(GROUP) == 24, f"the menu generates {len(GROUP)} permutations of Omega")

PASSIVE = reachable(GENS, 4, ("pass",))
print(f"   passive tower, L <= 4: {len(PASSIVE)} distinct posteriors")
check("F1", all(D_pass(nu, OM) == nu and D_fresh(nu) == nu for nu in PASSIVE),
      "D_pass = id and D_fresh = id on every reachable posterior")
POINTS = [tuple(Fr(1) if j == i else Fr(0) for j in range(4)) for i in range(4)]
check("F2", all(p in PASSIVE for p in POINTS), "all four point masses are reachable posteriors")
det = all(P0(p) in (Fr(0), Fr(1)) for p in POINTS)
# every posterior is the convex combination sum_i nu_i * delta_i of point masses (trivially, with its own weights)
conv = all(all(m >= 0 for m in nu) and sum(nu) == 1 for nu in PASSIVE)
check("F3", det and conv, "point masses give z deterministically; every posterior is a mixture of point masses")
check("F4", all(P0(push(M, p)) in (Fr(0), Fr(1)) for M in GROUP for p in POINTS),
      "no permutation maps a point mass to a balanced state (24 x 4)")
v_ok = True
nrun = 0
for nu in PASSIVE:
    for M1 in GROUP:
        a = push(M1, nu)
        for M2 in GROUP:
            pc = P0(push(M2, a))
            v_ok &= (P0(push(M2, D_pass(a, OM))) == pc) and (P0(push(M2, D_fresh(a))) == pc)
            nrun += 1
check("F5", v_ok, f"visibility 0 with D_pass and D_fresh: {nrun} sandwiches")

SEED = (h, h, Fr(0), Fr(0))  # z = 0, x uniform  (indices (0,0),(0,1),(1,0),(1,1))
SW = GENS["swap"]
pc = P0(push(SW, push(SW, SEED)))
pdx = P0(push(SW, D_x(push(SW, SEED))))
seed_mid = SEED == tuple(h * POINTS[0][i] + h * POINTS[1][i] for i in range(4))
dx_moves = D_x(POINTS[0]) != POINTS[0]
check("F6", pc == 1 and pdx == h and seed_mid and dx_moves and SEED in PASSIVE,
      f"classical memory: P_coh = {pc}, with D_x {pdx}; the seed is the midpoint of two reachable point masses; "
      f"D_x moves a point mass")
pdm = P0(push(SW, D_mem(push(SW, SEED))))
dm_not_id = any(D_mem(p) != p for p in POINTS)
check("F7", pc == 1 and pdm == h and dm_not_id,
      f"recorder into the memory register: P_coh = {pc}, P_deph = {pdm}; D_mem is not the identity on point masses")

print()
print("-- F8: the knowledge-balance tower (passive obs removed, obsKB added)")
KB = reachable(GENS, 5, ("kb",))
print(f"   KB-D tower, L <= 5: {len(KB)} distinct posteriors")
nopoint = all(max(nu) <= h for nu in KB)
PAIRS = []
for a, b in itertools.combinations(range(4), 2):
    PAIRS.append(tuple(h if j in (a, b) else Fr(0) for j in range(4)))
expected = set(PAIRS) | {MU}
check("F8a", nopoint, "no reachable point mass; every posterior has all probabilities <= 1/2")
check("F8b", KB == expected, "reachable posteriors = uniform + the six pair states")
Mrank = sp.Matrix([[x - y for x, y in zip(p, PAIRS[0])] for p in PAIRS[1:]]).rank()
exposed = True
for k, (a, b) in enumerate(itertools.combinations(range(4), 2)):
    f = lambda nu, a=a, b=b: nu[a] + nu[b]
    others = [f(q) for j, q in enumerate(PAIRS) if j != k]
    exposed &= f(PAIRS[k]) == 1 and max(others) <= h
check("F8c", Mrank == 3 and exposed, f"six pair states: affine rank {Mrank}, each exposed (an octahedron)")
ZP = PAIRS[0]                                   # {(0,0),(0,1)} : z = 0
XP = push(SW, ZP)                               # {(0,0),(1,0)} : x = 0
check("F8d", XP in PAIRS and P0(XP) == h, f"swap maps z+ to the extreme state x+ with P(z=0) = {P0(XP)}")


def D_KB(nu):
    a = cond_z(nu, 0, OM)
    b = cond_z(nu, 1, OM)
    out = [Fr(0)] * 4
    for part in (a, b):
        if sum(part) == 0:
            continue
        d = D_x(part)
        for i in range(4):
            out[i] += d[i]
    return tuple(out)


pc_kb = P0(push(SW, push(SW, ZP)))
pd_kb = P0(push(SW, D_KB(push(SW, ZP))))
check("F8e", pc_kb == 1 and pd_kb == h, f"KB sandwich: P_coh = {pc_kb}, P_deph = {pd_kb}")
ZM = tuple(h if OM[i][0] == 1 else Fr(0) for i in range(4))
frame_ok = all(D_KB(nu) == tuple(P0(nu) * ZP[i] + (1 - P0(nu)) * ZM[i] for i in range(4)) for nu in KB)
check("F8f", frame_ok and D_KB(XP) != XP, "D_KB = r z+ + (1-r) z- on every reachable state, and D_KB(x+) != x+")
face = [nu for nu in KB if P0(nu) == 1]
check("F8g", face == [ZP], f"the z = 0 face of the reachable states: {len(face)} state(s), z+")

print()
print("-- F9: three-bit robustness of passivity")
OM3 = [(z, x, y) for z in (0, 1) for x in (0, 1) for y in (0, 1)]
IDX3 = {w: i for i, w in enumerate(OM3)}


def perm3(f):
    return tuple(IDX3[f(w)] for w in OM3)


G3 = {
    "swap_zx": perm3(lambda w: (w[1], w[0], w[2])),
    "swap_xy": perm3(lambda w: (w[0], w[2], w[1])),
    "flipx": perm3(lambda w: (w[0], 1 - w[1], w[2])),
    "cnot_zy": perm3(lambda w: (w[0], w[1], w[2] ^ w[0])),
}
GROUP3 = closure(list(G3.values()), 8)
MU3 = tuple([Fr(1, 8)] * 8)
st = {MU3}
lay = {MU3}
for _ in range(3):
    nx = set()
    for nu in lay:
        for p in G3.values():
            nx.add(push(p, nu))
        for v in (0, 1):
            c = cond_z(nu, v, OM3)
            if sum(c) > 0:
                nx.add(normalize(c))
    nx -= st
    st |= nx
    lay = nx
pas3 = all(D_pass(nu, OM3) == nu for nu in st)
M2LIST = GROUP3[:: max(1, len(GROUP3) // 6)][:6]
M1LIST = GROUP3[:: max(1, len(GROUP3) // 96)][:96]
v3 = True
n3 = 0
for nu in st:
    for M1 in M1LIST:
        a = push(M1, nu)
        for M2 in M2LIST:
            v3 &= P0(push(M2, D_pass(a, OM3)), OM3) == P0(push(M2, a), OM3)
            n3 += 1
check("F9", pas3 and v3, f"|group| = {len(GROUP3)}, {len(st)} posteriors (L <= 3): D_pass = id; V = 0 in {n3} sandwiches")

print()
print("-- countercontrols")
KB_plus = reachable(GENS, 5, ("kb", "pass"))
counter("CCF1", all(max(nu) <= h for nu in KB_plus),
        f"'no reachable point mass' with the passive obs added back ({len(KB_plus)} posteriors)")
counter("CCF2", pc_kb == pd_kb, "V = 0 for the KB-D sandwich")
counter("CCF3", all(D_mem(p) == p for p in POINTS), "D_mem is the identity on the point masses")
counter("CCF4", not seed_mid, "the seed (z=0, x uniform) is extreme in the passive body")

print()
nfail = sum(1 for r in RESULTS if not r[1])
nchk = sum(1 for r in RESULTS if r[2] == "check")
ncc = sum(1 for r in RESULTS if r[2] == "counter")
if nfail == 0:
    print(f"OK -- {nchk}/{nchk} checks, {ncc} countercontrols expected-false")
    print("VERDICT ENVELOPE-F HOLDS: in the passive classical tower the path dephasing (observe-and-forget, or a")
    print("  fresh-register record) is the identity on every reachable state, the extreme states are point masses")
    print("  with deterministic readout, no permutation is a balanced pure mixer, and every sandwich has visibility 0.")
    print(f"  The numbers 1 vs 1/2 appear classically only when the 'dephasing' erases the readback memory (D_x, or the")
    print(f"  recorder written into the memory) from a non-extreme seed, or when the passive readout is replaced by the")
    print(f"  knowledge-balance readout KB-D, which yields an octahedral body with a balanced extreme mixer (swap).")
else:
    print(f"VOID -- {nfail} failing item(s): " + ", ".join(r[0] for r in RESULTS if not r[1]))
    print("VERDICT VOID")
