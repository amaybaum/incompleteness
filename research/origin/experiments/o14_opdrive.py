class Q8:
    zero = (Fr(0),) * 4
    one = (Fr(1),) + (Fr(0),) * 3

    @staticmethod
    def add(a, b):
        return tuple(x + y for x, y in zip(a, b))

    @staticmethod
    def sub(a, b):
        return tuple(x - y for x, y in zip(a, b))

    @staticmethod
    def neg(a):
        return tuple(-x for x in a)

    @staticmethod
    def mul(a, b):
        r = [Fr(0)] * 4
        for i, x in enumerate(a):
            if x:
                for j, y in enumerate(b):
                    if y:
                        k = i + j
                        if k < 4:
                            r[k] += x * y
                        else:
                            r[k - 4] -= x * y
        return tuple(r)

    @staticmethod
    def conj(a):
        return (a[0], -a[3], -a[2], -a[1])


