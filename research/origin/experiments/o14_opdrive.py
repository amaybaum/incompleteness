def z_norm(c, e):
    c = list(c)
    while e > 0 and all(x % 2 == 0 for x in c):
        c = [x // 2 for x in c]
        e -= 1
    if all(x == 0 for x in c):
        e = 0
    return (tuple(c), e)


def z_add(a, b):
    (ca, ea), (cb, eb) = a, b
    e = max(ea, eb)
    return z_norm([x * (1 << (e - ea)) + y * (1 << (e - eb)) for x, y in zip(ca, cb)], e)


def z_shift(a, k):
    """multiply by zeta^k (zeta^8 = -1)."""
    c, e = a
    k %= 16
    r = [0] * D16
    for i, x in enumerate(c):
        if x:
            j = i + k
            s = 1
            while j >= D16:
                j -= D16
                s = -s
            r[j] += s * x
    return (tuple(r), e)


def z_mul(a, b):
    (ca, ea), (cb, eb) = a, b
    r = [0] * D16
    for i, x in enumerate(ca):
        if x:
            for j, y in enumerate(cb):
                if y:
                    k = i + j
                    if k < D16:
                        r[k] += x * y
                    else:
                        r[k - D16] -= x * y
    return z_norm(r, ea + eb)


