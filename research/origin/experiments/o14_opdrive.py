def sign_ab(a, b):
    """sign of a + b sqrt2 for rationals a, b."""
    if a >= 0 and b >= 0:
        return 0 if (a == 0 and b == 0) else 1
    if a <= 0 and b <= 0:
        return -1
    if a > 0:  # b < 0
        return 1 if a * a > 2 * b * b else (0 if a * a == 2 * b * b else -1)
    return 1 if 2 * b * b > a * a else (0 if a * a == 2 * b * b else -1)  # a < 0 < b


