def mmul(F, A, B):
    n, m, p = len(A), len(B), len(B[0])
    C = []
    for i in range(n):
        row = []
        for j in range(p):
            s = F.zero
            for k in range(m):
                if A[i][k] != F.zero and B[k][j] != F.zero:
                    s = F.add(s, F.mul(A[i][k], B[k][j]))
            row.append(s)
        C.append(row)
    return C


def mprod(F, *Ms):
    R = Ms[0]
    for M in Ms[1:]:
        R = mmul(F, R, M)
    return R


def mdag(F, A):
    return [[F.conj(A[j][i]) for j in range(len(A))] for i in range(len(A[0]))]


def madd(F, A, B):
    return [[F.add(a, b) for a, b in zip(ra, rb)] for ra, rb in zip(A, B)]


def mscale(F, c, A):
    return [[F.mul(c, a) for a in row] for row in A]


def mkron(F, A, B):
    n, m = len(A), len(B)
    return [[F.mul(A[i // m][j // m], B[i % m][j % m]) for j in range(n * m)] for i in range(n * m)]


def mdiag(F, entries):
    n = len(entries)
    M = mzero(F, n)
    for i, e in enumerate(entries):
        M[i][i] = e
    return M


