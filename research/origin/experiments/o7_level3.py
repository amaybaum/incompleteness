def zeros(n):
    return [[Z0 for _ in range(n)] for _ in range(n)]


def eye(n):
    return [[O1 if i == j else Z0 for j in range(n)] for i in range(n)]


def mul(A, B):
    n = len(A)
    return [[sum((A[i][k] * B[k][j] for k in range(n)), Z0) for j in range(n)] for i in range(n)]


def add(A, B, s=1):
    return [[A[i][j] + s * B[i][j] for j in range(len(A))] for i in range(len(A))]


def scal(c, A):
    return [[c * x for x in row] for row in A]


def T(A):
    return [[A[j][i] for j in range(len(A))] for i in range(len(A))]


def eqm(A, B):
    return all((A[i][j] - B[i][j]).iszero() for i in range(len(A)) for j in range(len(A)))


def mix_image(n):
    M = eye(2 * n)
    for k in range(n):
        a, b = k, n + k          # (0,k) -> k, (1,k) -> n + k
        M[a][a], M[a][b], M[b][a], M[b][b] = R, -R, R, R
    return M


def shift_perm(n):
    P = zeros(2 * n)
    for s in range(2):
        for k in range(n):
            P[s * n + (k + s) % n][s * n + k] = O1
    return P


def perm_matrix(p):
    n = len(p)
    P = zeros(n)
    for j in range(n):
        P[p[j]][j] = O1
    return P


def vecA(A):
    """antisymmetric matrix -> vector of its strict upper triangle"""
    n = len(A)
    return [A[i][j] for i in range(n) for j in range(i + 1, n)]


class Span:
    """incremental row-echelon basis over Q(sqrt2)"""

    def __init__(self):
        self.rows = []      # (pivot, row)

    def reduce(self, v):
        v = list(v)
        for piv, row in self.rows:
            if not v[piv].iszero():
                c = v[piv] / row[piv]
                v = [x - c * y for x, y in zip(v, row)]
        return v

    def add(self, v):
        v = self.reduce(v)
        for i, x in enumerate(v):
            if not x.iszero():
                self.rows.append((i, v))
                return True
        return False


def lie_closure(gens, n):
    S = Span()
    mats = []
    for G in gens:
        if S.add(vecA(G)):
            mats.append(G)
    changed = True
    while changed:
        changed = False
        cur = list(mats)
        for i in range(len(cur)):
            for j in range(i + 1, len(cur)):
                Br = add(mul(cur[i], cur[j]), mul(cur[j], cur[i]), -1)
                if S.add(vecA(Br)):
                    mats.append(Br)
                    changed = True
        if len(mats) >= n * (n - 1) // 2:
            break
    return len(S.rows)


