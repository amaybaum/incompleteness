from fractions import Fraction as Fr
from math import gcd

import sympy as sp

QMAX = 36
XS = sp.Symbol('x')


def lcm(a, b):
    return a * b // gcd(a, b)


class Ring:
    """Z[zeta_N][1/2], exact."""

    def __init__(self, N):
        self.N = N
        coeffs = sp.Poly(sp.cyclotomic_poly(N, XS), XS).all_coeffs()
        self.d = len(coeffs) - 1
        self.phi = [int(c) for c in reversed(coeffs)]
        assert self.phi[self.d] == 1
        self.pw = []
        v = [0] * self.d
        v[0] = 1
        for _ in range(N):
            self.pw.append(tuple(v))
            top = v[-1]
            w = [0] + v[:-1]
            if top:
                for i in range(self.d):
                    w[i] -= top * self.phi[i]
            v = w

    def norm(self, c, e):
        c = list(c)
        while e > 0 and all(x % 2 == 0 for x in c):
            c = [x // 2 for x in c]
            e -= 1
        if all(x == 0 for x in c):
            e = 0
        return (tuple(c), e)

    def zeta(self, j):
        return (self.pw[j % self.N], 0)

    def const(self, n):
        v = [0] * self.d
        v[0] = n
        return self.norm(v, 0)

    def frac(self, f):
        f = Fr(f)
        den = f.denominator
        e = den.bit_length() - 1
        assert den == 1 << e, 'denominator not a power of two'
        v = [0] * self.d
        v[0] = f.numerator
        return self.norm(v, e)

    def add(self, a, b):
        (ca, ea), (cb, eb) = a, b
        e = max(ea, eb)
        return self.norm([x * (1 << (e - ea)) + y * (1 << (e - eb)) for x, y in zip(ca, cb)], e)

    def neg(self, a):
        return (tuple(-x for x in a[0]), a[1])

    def sub(self, a, b):
        return self.add(a, self.neg(b))

    def half(self, a):
        return self.norm(a[0], a[1] + 1)

    def mul(self, a, b):
        (ca, ea), (cb, eb) = a, b
        d = self.d
        prod = [0] * (2 * d - 1)
        for i, x in enumerate(ca):
            if x:
                for j, y in enumerate(cb):
                    if y:
                        prod[i + j] += x * y
        res = [0] * d
        for k, cf in enumerate(prod):
            if cf:
                p = self.pw[k % self.N]
                for i in range(d):
                    if p[i]:
                        res[i] += cf * p[i]
        return self.norm(res, ea + eb)

    def conj(self, a):
        ca, e = a
        res = [0] * self.d
        for i, x in enumerate(ca):
            if x:
                p = self.pw[(-i) % self.N]
                for k in range(self.d):
                    if p[k]:
                        res[k] += x * p[k]
        return self.norm(res, e)

    def is_zero(self, a):
        return all(x == 0 for x in a[0])

    def integral(self, a):
        return a[1] == 0

    def I(self):
        return self.zeta(self.N // 4)

    def summ(self, xs):
        acc = self.const(0)
        for x in xs:
            acc = self.add(acc, x)
        return acc

    def mm(self, A, B):
        return [[self.summ([self.mul(A[i][k], B[k][j]) for k in range(len(B))]) for j in range(len(B[0]))]
                for i in range(len(A))]

    def dag(self, A):
        return [[self.conj(A[j][i]) for j in range(len(A))] for i in range(len(A[0]))]

    def eq(self, A, B):
        return all(A[i][j] == B[i][j] for i in range(len(A)) for j in range(len(A[0])))

    def eye(self, n):
        return [[self.const(1 if i == j else 0) for j in range(n)] for i in range(n)]


RINGS = {}


def ring(N):
    if N not in RINGS:
        RINGS[N] = Ring(N)
    return RINGS[N]


def angle(p, q):
    """The ring for the angle pi*p/q and the exponent k with e^{i pi p/q} = zeta_N^k."""
    N = lcm(2 * q, 4)
    return ring(N), p * (N // (2 * q))


def cos_(R, k):
    return R.half(R.add(R.zeta(k), R.zeta(-k)))


def sin_(R, k):
    return R.half(R.mul(R.neg(R.I()), R.sub(R.zeta(k), R.zeta(-k))))


def rot(R, k):
    c, s = cos_(R, k), sin_(R, k)
    return [[c, R.neg(s)], [s, c]]


def rx(R, k):
    c, s = cos_(R, k), sin_(R, k)
    i = R.I()
    return [[c, R.mul(i, s)], [R.mul(i, s), c]]


def S2(R):
    return [[R.const(1), R.const(0)], [R.const(0), R.I()]]


def X2(R):
    return [[R.const(0), R.const(1)], [R.const(1), R.const(0)]]


def Z2(R):
    return [[R.const(1), R.const(0)], [R.const(0), R.const(-1)]]


PAULI_CACHE = {}


def paulis(R):
    if R.N in PAULI_CACHE:
        return PAULI_CACHE[R.N]
    one, zero, i = R.const(1), R.const(0), R.I()
    base = [[[one, zero], [zero, one]], X2(R), [[zero, R.neg(i)], [i, zero]], Z2(R)]
    out = []
    for m in range(4):
        ph = R.zeta((m * R.N) // 4)
        for B in base:
            out.append([[R.mul(ph, B[a][b]) for b in range(2)] for a in range(2)])
    PAULI_CACHE[R.N] = out
    return out


def in_set(R, M, S):
    return any(R.eq(M, P) for P in S)


def rot_clifford(R, k):
    Rm = rot(R, k)
    Rd = R.dag(Rm)
    P = paulis(R)
    return (in_set(R, R.mm(R.mm(Rm, X2(R)), Rd), P) and in_set(R, R.mm(R.mm(Rm, Z2(R)), Rd), P))


def cls_key(R, G):
    Gd = R.dag(G)
    a = R.mm(R.mm(G, X2(R)), Gd)
    b = R.mm(R.mm(G, Z2(R)), Gd)
    return tuple(a[i][j] for i in range(2) for j in range(2)) + tuple(b[i][j] for i in range(2) for j in range(2))


def bfs_classes(R, gens, cap):
    one = R.eye(2)
    seen = {cls_key(R, one)}
    frontier = [one]
    while frontier:
        nxt = []
        for G in frontier:
            for g in gens:
                H = R.mm(G, g)
                kH = cls_key(R, H)
                if kH not in seen:
                    seen.add(kH)
                    nxt.append(H)
                    if len(seen) > cap:
                        return len(seen), False
        frontier = nxt
    return len(seen), True


def det2(R, M):
    return R.sub(R.mul(M[0][0], M[1][1]), R.mul(M[0][1], M[1][0]))


def tr2(R, M):
    return R.add(M[0][0], M[1][1])


MP_CACHE = {}


def integral_by_minpoly(p, q):
    """Is cos(2 pi p/q) an algebraic integer?  Via sympy's minimal polynomial (primitive integer form)."""
    r = Fr(p, q) % 1
    r = min(r, 1 - r) if r != 0 else r
    if r not in MP_CACHE:
        mp = sp.minimal_polynomial(sp.cos(2 * sp.pi * sp.Rational(r.numerator, r.denominator)), XS)
        cs = sp.Poly(mp, XS, domain='QQ').all_coeffs()
        den = 1
        for c in cs:
            den = lcm(den, int(sp.fraction(sp.Rational(c))[1]))
        ints = [int(sp.Rational(c) * den) for c in cs]
        g = 0
        for v in ints:
            g = gcd(g, v)
        MP_CACHE[r] = (abs(ints[0] // g) == 1, len(ints) - 1)
    return MP_CACHE[r]


def q2mul(u, v):
    return (u[0] * v[0] + 2 * u[1] * v[1], u[0] * v[1] + u[1] * v[0])


def q2sub(u, v):
    return (u[0] - v[0], u[1] - v[1])


def cheb(t, K):
    ps = [(Fr(0), Fr(0)), (Fr(1), Fr(0))]
    for _ in range(K):
        ps.append(q2sub(q2mul(t, ps[-1]), ps[-2]))
    return ps


