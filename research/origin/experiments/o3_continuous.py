class G:
    __slots__ = ("re", "im")

    def __init__(self, re=0, im=0):
        self.re = Fr(re)
        self.im = Fr(im)

    def __add__(self, o):
        o = gg(o)
        return G(self.re + o.re, self.im + o.im)

    __radd__ = __add__

    def __sub__(self, o):
        o = gg(o)
        return G(self.re - o.re, self.im - o.im)

    def __mul__(self, o):
        o = gg(o)
        return G(self.re * o.re - self.im * o.im, self.re * o.im + self.im * o.re)

    __rmul__ = __mul__

    def __neg__(self):
        return G(-self.re, -self.im)

    def conj(self):
        return G(self.re, -self.im)

    def norm2(self):
        return self.re * self.re + self.im * self.im

    def __eq__(self, o):
        o = gg(o)
        return self.re == o.re and self.im == o.im

    def __hash__(self):
        return hash((self.re, self.im))

    def iszero(self):
        return self.re == 0 and self.im == 0

    def __repr__(self):
        if self.im == 0:
            return str(self.re)
        if self.re == 0:
            return f"{self.im}i"
        return f"({self.re}{'+' if self.im >= 0 else '-'}{abs(self.im)}i)"


def gg(x):
    return x if isinstance(x, G) else G(x, 0)


def zeros(n):
    return [[G() for _ in range(n)] for _ in range(n)]


def eye(n):
    Z = zeros(n)
    for i in range(n):
        Z[i][i] = G(1)
    return Z


def mm(A, B):
    n = len(A)
    C = zeros(n)
    for i in range(n):
        for t in range(n):
            a = A[i][t]
            if a.iszero():
                continue
            for j in range(n):
                b = B[t][j]
                if not b.iszero():
                    C[i][j] = C[i][j] + a * b
    return C


def dag(A):
    n = len(A)
    return [[A[j][i].conj() for j in range(n)] for i in range(n)]


def msc(c, A):
    return [[gg(c) * x for x in row] for row in A]


def meq(A, B):
    return all(A[i][j] == B[i][j] for i in range(len(A)) for j in range(len(A)))


def kron(A, B):
    n, m = len(A), len(B)
    C = zeros(n * m)
    for i in range(n):
        for j in range(n):
            if A[i][j].iszero():
                continue
            for k in range(m):
                for l in range(m):
                    C[i * m + k][j * m + l] = A[i][j] * B[k][l]
    return C


def unit(n, i, j):
    E = zeros(n)
    E[i][j] = G(1)
    return E


def Delta(X):
    n = len(X)
    Y = zeros(n)
    for i in range(n):
        Y[i][i] = X[i][i]
    return Y


def is_monomial(K):
    n = len(K)
    return (all(sum(1 for j in range(n) if not K[i][j].iszero()) <= 1 for i in range(n))
            and all(sum(1 for i in range(n) if not K[i][j].iszero()) <= 1 for j in range(n)))


def conjK(K, w=Fr(1)):
    Kd = dag(K)
    return lambda X: msc(G(w), mm(mm(K, X), Kd))


def is_DC(Phi, n):
    for i in range(n):
        for j in range(n):
            E = unit(n, i, j)
            if not meq(Phi(Delta(E)), Delta(Phi(E))):
                return False
    return True


