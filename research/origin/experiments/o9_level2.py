# ---------------------------------------------------------------- scalars in Z[zeta_8] (numerators)
def padd(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2], a[3] + b[3])


def pneg(a):
    return (-a[0], -a[1], -a[2], -a[3])


def pmul(x, y):
    x0, x1, x2, x3 = x
    y0, y1, y2, y3 = y
    return (x0 * y0 - x1 * y3 - x2 * y2 - x3 * y1,
            x0 * y1 + x1 * y0 - x2 * y3 - x3 * y2,
            x0 * y2 + x1 * y1 + x2 * y0 - x3 * y3,
            x0 * y3 + x1 * y2 + x2 * y1 + x3 * y0)


def pconj(a):            # z -> z^7 = -z^3
    return (a[0], -a[3], -a[2], -a[1])


def psigma(a):           # z -> -z (fixes i, negates sqrt2)
    return (a[0], -a[1], a[2], -a[3])


def fmt(k, s):
    """(s0 + s1 z + s2 z^2 + s3 z^3)/2^k written as a + b i + c sqrt2 + d i sqrt2."""
    den = 2 ** k
    a = Fraction(s[0], den)
    b = Fraction(s[2], den)
    c = Fraction(s[1] - s[3], 2 * den)
    d = Fraction(s[1] + s[3], 2 * den)
    parts = []
    for coef, name in ((a, ''), (b, 'i'), (c, 'sqrt2'), (d, 'i sqrt2')):
        if coef != 0:
            parts.append(str(coef) + ((' ' + name) if name else ''))
    return ' + '.join(parts) if parts else '0'


# ---------------------------------------------------------------- matrices: (k, entries) = entries / 2^k
def mnorm(k, ents):
    ents = list(ents)
    while k > 0 and all(c % 2 == 0 for e in ents for c in e):
        ents = [(e[0] // 2, e[1] // 2, e[2] // 2, e[3] // 2) for e in ents]
        k -= 1
    return (k, tuple(ents))


def ident(N):
    return (0, tuple(ONE if i == j else Z0 for i in range(N) for j in range(N)))


def mmul(A, B, N):
    ka, ea = A
    kb, eb = B
    out = []
    for i in range(N):
        row = ea[i * N:(i + 1) * N]
        for j in range(N):
            a0 = a1 = a2 = a3 = 0
            for l in range(N):
                x = row[l]
                if x == Z0:
                    continue
                y = eb[l * N + j]
                if y == Z0:
                    continue
                x0, x1, x2, x3 = x
                y0, y1, y2, y3 = y
                a0 += x0 * y0 - x1 * y3 - x2 * y2 - x3 * y1
                a1 += x0 * y1 + x1 * y0 - x2 * y3 - x3 * y2
                a2 += x0 * y2 + x1 * y1 + x2 * y0 - x3 * y3
                a3 += x0 * y3 + x1 * y2 + x2 * y1 + x3 * y0
            out.append((a0, a1, a2, a3))
    return mnorm(ka + kb, out)


def mchain(mats, N):
    R = ident(N)
    for M in mats:
        R = mmul(R, M, N)
    return R


def mdag(A, N):
    k, e = A
    return (k, tuple(pconj(e[j * N + i]) for i in range(N) for j in range(N)))


def mnegate(A):
    k, e = A
    return (k, tuple(pneg(x) for x in e))


def mtrace(A, N):
    k, e = A
    s = Z0
    for i in range(N):
        s = padd(s, e[i * N + i])
    return k, s


def trace_integral(k, s):
    return all(c % (2 ** k) == 0 for c in s)


def perm_sign(p):
    p = list(p)
    sign = 1
    for i in range(len(p)):
        while p[i] != i:
            j = p[i]
            p[i], p[j] = p[j], p[i]
            sign = -sign
    return sign


def mdet(A, N):
    k, e = A
    total = Z0
    for p in permutations(range(N)):
        prod = ONE
        for i in range(N):
            prod = pmul(prod, e[i * N + p[i]])
            if prod == Z0:
                break
        if prod != Z0:
            total = padd(total, prod if perm_sign(p) > 0 else pneg(prod))
    kk, (t,) = mnorm(k * N, [total])
    return kk, t


def permmat(pi, N):
    """P e_x = e_{pi[x]}."""
    e = [Z0] * (N * N)
    for x in range(N):
        e[pi[x] * N + x] = ONE
    return (0, tuple(e))


def miximage(n):
    N = 2 * n
    e = [Z0] * (N * N)
    rot = [[SQ2, pneg(SQ2)], [SQ2, SQ2]]          # over 2^1: cos = sin = sqrt2/2
    for s in range(2):
        for t in range(2):
            for kk in range(n):
                e[(s * n + kk) * N + (t * n + kk)] = rot[s][t]
    return mnorm(1, e)


def phasegate(p, N):
    return (0, tuple((IU if i == p else ONE) if i == j else Z0 for i in range(N) for j in range(N)))


def cycle(N):
    return permmat([(x + 1) % N for x in range(N)], N)


def transp(a, b, N):
    pi = list(range(N))
    pi[a], pi[b] = b, a
    return permmat(pi, N)


def bfs(gens, N, cap):
    I = ident(N)
    seen = {I}
    order = [I]
    dq = deque([I])
    while dq:
        g = dq.popleft()
        for h in gens:
            x = mmul(h, g, N)
            if x not in seen:
                seen.add(x)
                order.append(x)
                if len(order) > cap:
                    return False, order
                dq.append(x)
    return True, order


# ---------------------------------------------------------------- modular linear algebra
def zeta_mod(p):
    for a in range(2, 1000):
        z = pow(a, (p - 1) // 8, p)
        if pow(z, 4, p) == p - 1:
            return z
    raise ValueError('no primitive 8th root')


def red(x, k, p, z):
    v = (x[0] + x[1] * z + x[2] * z * z + x[3] * z * z * z) % p
    return v * pow(pow(2, k, p), p - 2, p) % p


def modp(A, N, p, z):
    k, e = A
    M = np.zeros((N, N), dtype=np.int64)
    for i in range(N):
        for j in range(N):
            x = e[i * N + j]
            if x != Z0:
                M[i, j] = red(x, k, p, z)
    return M


def rank_mod_p(M, p):
    M = M.copy() % p
    rows, cols = M.shape
    r = 0
    for c in range(cols):
        if r == rows:
            break
        nz = np.nonzero(M[r:, c])[0]
        if len(nz) == 0:
            continue
        piv = r + int(nz[0])
        if piv != r:
            M[[r, piv]] = M[[piv, r]]
        inv = pow(int(M[r, c]), p - 2, p)
        M[r] = (M[r] * inv) % p
        col = M[r + 1:, c].copy()
        nzr = np.nonzero(col)[0]
        if len(nzr):
            idx = r + 1 + nzr
            M[idx] = (M[idx] - (col[nzr, None] * M[r]) % p) % p
        r += 1
    return r


def commutant_dim(reps, d, p):
    """dimension of {X in M_d : X A = A X for every A in reps}, computed mod p (reps: d x d int arrays mod p)."""
    I = np.eye(d, dtype=np.int64)
    blocks = []
    for A in reps:
        S = (np.kron(I, A.T) - np.kron(A, I)) % p          # row-major vec: vec(XA - AX)
        blocks.append(S)
    return d * d - rank_mod_p(np.vstack(blocks), p)


def ad_lambda2(A, N, p, z):
    """Y -> A Y A^T on antisymmetric matrices (A real orthogonal), basis E_ij - E_ji, i < j."""
    G = modp(A, N, p, z)
    pairs = [(i, j) for i in range(N) for j in range(i + 1, N)]
    d = len(pairs)
    R = np.zeros((d, d), dtype=np.int64)
    for col, (i, j) in enumerate(pairs):
        Y = (np.outer(G[:, i], G[:, j]) - np.outer(G[:, j], G[:, i])) % p
        for row, (a, b) in enumerate(pairs):
            R[row, col] = Y[a, b]
    return R, d


