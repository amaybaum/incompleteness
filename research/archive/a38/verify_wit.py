import sys, time, pickle; sys.path.insert(0, 'a38')
from lib38c import *
t0 = time.time()
found = pickle.load(open('a38/first_wit.pkl', 'rb'))
print('candidates', len(found))
def support(E): return sum(1 for r in gauge_normal(as_list(E)) for x in r if x)
found.sort(key=lambda E: (support(E), as_list(E)))
print('support sizes (gauge normal) smallest 10:', [support(E) for E in found[:10]])
for E in found[:int(sys.argv[1]) if len(sys.argv) > 1 else 2]:
    E = as_list(E)
    print('\n=== candidate, support', support(E), 'entries', sorted(set(x for r in E for x in r)))
    print(show(E))
    print('exact straight (direct Laurent identity):', straight_line_direct(E), '; table test:', straight_line(E))
    print('gauge normal form:'); print(show(gauge_normal(E)))
    nc = numeric_counts(E, U5); print('numeric at u5 (candidates, exact) by form/shape:', nc)
    gc = generic_counts(E); print('generic u (candidates, exact) by form/shape:', gc, '%.0fs' % (time.time() - t0))
    obs = obstruction_summary(E)
    for k, v in sorted(obs.items()): print('  %s %-6s' % k, v[0] if v[0] == 'identical' else ('admitted only at ' + str(v[0])), ' exponents', v[1])
    B = straight_lattice(E); print('dim L(Pi_E):', len(B), 'lattice classes strict', lattice_classes(B), 'relaxed', lattice_classes(B, True))
    print('%.0fs' % (time.time() - t0))
