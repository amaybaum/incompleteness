check(f"G3 spot check: W' >= 0 on {len(mins)} random exact generators across all 8 K_tau (min {min(mins)})", ok_spot)

# X_rho is PSD and the HS bound holds on the symbolic family: tr_k[(1 (x) rho) GHZ'] has trace 1/2 for every state rho
ok_x = True
for k in range(3):
    Xr = contract(ghzp * ghzp.T, k, rho)
    ok_x &= sp.simplify(Xr.trace() - rho.trace() / 2) == 0
check("G3 tr X_rho = tr(rho psi_k) = 1/2 for every one-copy state rho and every copy k (symbolic)", ok_x)

# G4: M_tw through the chart PT_1 (flips the bits of pairs (0,1) and (1,2): (0,1,0) -> (1,1,1))
Wtw = PT(Wp, 1, 3)
ghz_tw = PT(ghzp * ghzp.T, 1, 3)
check("G4 M_tw: PT_1 maps M_odd onto M_tw (T5) and GHZ' to PT_1(GHZ'), with PT_1(W') of value -1/2 on it",
      sp.simplify((Wtw * ghz_tw).trace()) == sp.Rational(-1, 2))
cnotp = lambda M: PT(kron(CNOT, s0) * PT(M, 1, 3) * kron(CNOT, s0).H, 1, 3)
check("G4 the twisted pair interaction cnot' = PT_1 . Ad CNOT . PT_1 idly extended sends PT_1(omega0) (a generator of "
      "M_tw) to PT_1(GHZ'), outside M_tw", zero(cnotp(PT(omega0, 1, 3)) - ghz_tw))

# ---------- B: M_bs has no chart for the triple ----------
ghz = (ket("000") + ket("111")) / sp.sqrt(2)
Wg = sp.eye(8) / 2 - ghz * ghz.T
check("B1 W_GHZ has value -1/2 on GHZ, GHZ is PSD (rank one), every one-copy marginal of GHZ is 1/2",
      sp.simplify((Wg * ghz * ghz.T).trace()) == sp.Rational(-1, 2)
      and all(zero(ptrace_keep(ghz * ghz.T, [q]) - s0 / 2) for q in range(3)))
ok_spot2 = True
