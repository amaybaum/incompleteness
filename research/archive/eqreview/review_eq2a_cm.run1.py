check("H3 twirl((1/9) sum_p (alpha_p + beta_p + delta_p)) = W_GHZ / 3 exactly, so W_GHZ is in B_tw "
      "(local Pauli conjugations preserve every generator family, T4)", zero(tw - Wg / 3))
Msum2 = sp.zeros(8, 8)
for p in PAIRS:
    for sig, st in ((Psim, plus * plus.H), ((Psim + Psip) / 2, s0 / 2)):
        Msum2 += place(PT(sig, 1, 2), p, st)
tw2 = sum((A * (Msum2 / 6) * A.H for A in Smats), sp.zeros(8, 8)) / 8
lin_dep = sp.Matrix([list(tw2), list(Wg)]).rank() == 1
check("H4 countercontrol: without the beta family the twirl is not a multiple of W_GHZ", not lin_dep)
check("H5 W_GHZ is not PSD (eigenvalue -1/2) and lies in B_tw* by the bound of B1 (B_tw = K_(1,1,1))",
      sp.Rational(-1, 2) in Wg.eigenvals())

