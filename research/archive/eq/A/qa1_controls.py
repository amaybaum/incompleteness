def check_pair(n, v, w, tag):
    v, w = vec(*v), vec(*w)
    xv, yw = proj(v), proj(w)
    m = madd(xv, yw, Fr(1, 2), Fr(1, 2))
    r = rank(m)
    ker = nullspace(m, z0, o1)
    chi = ker[0]
    mchi = hdot(chi, [sum((m[i][j] * chi[j] for j in range(n)), z0) for i in range(n)])
    cc = hdot(chi, chi)
    # <chi|(m + eps(m - z))|chi> = (1+eps)<chi|m|chi> - eps <chi|chi>  with z = |chi><chi|/<chi|chi>
    chk('%s.ELEM2_fails' % tag, r == 2 and mchi.is_zero() and cc.re > 0 and cc.im == 0 and xv != yw, 'witness',
        'rank m = 2 < %d; <chi|m|chi> = 0, <chi|chi> = %s > 0: <chi|(m + eps(m - z))|chi> = -eps*%s < 0' % (n, cc, cc))
    PK = span_projector([v, w])
    lam = interior_certificate(m, PK)
    chk('%s.pairface_relint' % tag, lam is not None, 'witness',
        'm >= %s P_K: the midpoint is not a boundary state of its pair face (the face is the Bloch ball of K)' % lam)
    # strict convexity of the pair face on sampled pairs of distinct states inside it (pure and mixed)
    samples = [xv, yw, proj([v[i] + w[i] for i in range(n)]), proj([v[i] + I * w[i] for i in range(n)]),
               madd(xv, yw, Fr(2, 3), Fr(1, 3)), madd(proj([v[i] - w[i] for i in range(n)]), xv, Fr(1, 2), Fr(1, 2))]
    good = True
    for a in range(len(samples)):
        for b in range(a + 1, len(samples)):
            if samples[a] == samples[b]:
                continue
            mid = madd(samples[a], samples[b], Fr(1, 2), Fr(1, 2))
            good = good and interior_certificate(mid, PK) is not None
    chk('%s.GEOM2_sampled' % tag, good, 'sample',
        'every midpoint of two distinct sampled states of the pair face dominates lam P_K, lam > 0: relatively interior')


