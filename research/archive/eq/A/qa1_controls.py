"""EQ-A, QA1 -- exact controls for the elementary-system predicate ELEM2 and the localized geometric principle GEOM2.

Definitions checked here (field-neutral; stated on a convex body Omega, read in Omega alone):
  boundary state   x in Om and some y in Om with x + eps (x - y) not in Om for every eps > 0      (KF:130)
  genFace(Om, m)   {z in Om : exists eps > 0, m + eps (m - z) in Om}   (the face of Om generated by m)
  ELEM2(Om)        two distinct extreme points x, y of Om whose midpoint is in Om and not a boundary state
  GEOM2(Om)        for all distinct extreme x, y: genFace(Om, (x+y)/2) is relatively strictly convex (KF:144)
  SF2 (effect form) for all distinct extreme x, y and every available effect e proper on F = genFace(Om,(x+y)/2),
                   the certain face of e inside F has at most one state

Exact arithmetic only: fractions.Fraction, Gaussian rationals GQ, Q(sqrt5).  Written arguments are printed as NOTE
lines and are not counted as checks.  Every check is tagged witness / identity / enumerate / sample.
Run:  PYTHONDONTWRITEBYTECODE=1 python3 -I qa1_controls.py
"""
from fractions import Fraction as Fr
