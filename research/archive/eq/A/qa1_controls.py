def certain_dim_in_face(E, K):
    """dim(K cap ker(I - E)): intersect span(K) with the kernel of I - E."""
    IE = madd(eye(len(E), o1), E, 1, -1)
    # vectors a*k1 + b*k2 with (I-E)(a k1 + b k2) = 0: solve for (a, b)
    cols = [[sum((IE[i][j] * kv[j] for j in range(len(E))), z0) for i in range(len(E))] for kv in K]
    Mab = [[cols[c][i] for c in range(len(K))] for i in range(len(E))]
    return len(K) - rank(Mab)


