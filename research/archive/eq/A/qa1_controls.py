N_CHECKS = {'witness': 0, 'identity': 0, 'enumerate': 0, 'sample': 0}
FAILED = []


def chk(name, ok, kind, detail=''):
    assert kind in N_CHECKS
    N_CHECKS[kind] += 1
    tag = 'PASS' if ok else 'FAIL'
    if not ok:
        FAILED.append(name)
    print('%s [%s] %s%s' % (tag, kind, name, ('  -- ' + detail) if detail else ''))


def note(name, detail):
    print('NOTE [written] %s  -- %s' % (name, detail))


def section(title):
    print('\n=== %s ===' % title)


# ------------------------------------------------------------------------------------------------ exact fields ---
class GQ:
    """Gaussian rational a + b i, a, b in Q."""
    __slots__ = ('re', 'im')

    def __init__(self, re, im=0):
        if isinstance(re, GQ):
            self.re, self.im = re.re, re.im
        else:
            self.re, self.im = Fr(re), Fr(im)

    def _c(self, o):
        return o if isinstance(o, GQ) else GQ(o)

    def __add__(self, o):
        o = self._c(o); return GQ(self.re + o.re, self.im + o.im)
    __radd__ = __add__

    def __sub__(self, o):
        o = self._c(o); return GQ(self.re - o.re, self.im - o.im)

    def __rsub__(self, o):
        return self._c(o) - self

    def __neg__(self):
        return GQ(-self.re, -self.im)

    def __mul__(self, o):
        o = self._c(o); return GQ(self.re * o.re - self.im * o.im, self.re * o.im + self.im * o.re)
    __rmul__ = __mul__

    def conj(self):
        return GQ(self.re, -self.im)

    def __truediv__(self, o):
        o = self._c(o)
        n = o.re * o.re + o.im * o.im
        if n == 0:
            raise ZeroDivisionError
        q = self * o.conj()
        return GQ(q.re / n, q.im / n)

    def __eq__(self, o):
        o = self._c(o); return self.re == o.re and self.im == o.im

    def __hash__(self):
        return hash((self.re, self.im))

    def is_zero(self):
        return self.re == 0 and self.im == 0

    def __repr__(self):
        return '%s%+si' % (self.re, self.im) if self.im else '%s' % self.re


class Q5:
    """a + b sqrt5 with a, b rational; exact sign."""
    __slots__ = ('a', 'b')

    def __init__(s, a, b=0):
        if isinstance(a, Q5):
            s.a, s.b = a.a, a.b
        else:
            s.a, s.b = Fr(a), Fr(b)

    def _c(s, o):
        return o if isinstance(o, Q5) else Q5(o)

    def __add__(s, o):
        o = s._c(o); return Q5(s.a + o.a, s.b + o.b)
    __radd__ = __add__

    def __neg__(s):
        return Q5(-s.a, -s.b)

    def __sub__(s, o):
        return s + (-s._c(o))

    def __rsub__(s, o):
        return s._c(o) - s

    def __mul__(s, o):
        o = s._c(o); return Q5(s.a * o.a + 5 * s.b * o.b, s.a * o.b + s.b * o.a)
    __rmul__ = __mul__

    def inv(s):
        n = s.a * s.a - 5 * s.b * s.b
        return Q5(s.a / n, -s.b / n)

    def __truediv__(s, o):
        return s * s._c(o).inv()

    def sign(s):
        # sign of a + b sqrt5 exactly
        if s.b == 0:
            return (s.a > 0) - (s.a < 0)
        if s.a == 0:
            return (s.b > 0) - (s.b < 0)
        if (s.a > 0) == (s.b > 0):
            return 1 if s.a > 0 else -1
        # opposite signs: compare a^2 with 5 b^2
        d = s.a * s.a - 5 * s.b * s.b
        if d == 0:
            return 0
        return ((1 if s.a > 0 else -1) if d > 0 else (1 if s.b > 0 else -1))

    def __eq__(s, o):
        o = s._c(o); return s.a == o.a and s.b == o.b

    def __hash__(s):
        return hash((s.a, s.b))

    def is_zero(s):
        return s.a == 0 and s.b == 0

    def __repr__(s):
        return '(%s%+s*sqrt5)' % (s.a, s.b)


def iszero(x):
    return x.is_zero() if hasattr(x, 'is_zero') else x == 0


# ----------------------------------------------------------------------------------- generic exact linear algebra ---
def mat_copy(M):
    return [list(r) for r in M]


def det(M):
    A = mat_copy(M); n = len(A); d = 1; one = 1
    for c in range(n):
        p = next((r for r in range(c, n) if not iszero(A[r][c])), None)
        if p is None:
            return A[0][0] * 0 if n else one
        if p != c:
            A[c], A[p] = A[p], A[c]; d = -d
        d = d * A[c][c]
        for r in range(c + 1, n):
            f = A[r][c] / A[c][c]
            A[r] = [A[r][k] - f * A[c][k] for k in range(n)]
    return d


def rref(M):
    A = mat_copy(M); rows = len(A); cols = len(A[0]) if rows else 0; piv = []; r = 0
    for c in range(cols):
        p = next((i for i in range(r, rows) if not iszero(A[i][c])), None)
        if p is None:
            continue
        A[r], A[p] = A[p], A[r]
        pv = A[r][c]
        A[r] = [v / pv for v in A[r]]
        for i in range(rows):
            if i != r and not iszero(A[i][c]):
                f = A[i][c]
                A[i] = [A[i][k] - f * A[r][k] for k in range(cols)]
        piv.append(c); r += 1
        if r == rows:
            break
    return A, piv


def rank(M):
    return len(rref(M)[1]) if M and M[0] else 0


def nullspace(M, zero, one):
    A, piv = rref(M); cols = len(M[0]); free = [c for c in range(cols) if c not in piv]; basis = []
    for f in free:
        v = [zero] * cols; v[f] = one
        for i, pc in enumerate(piv):
            v[pc] = -A[i][f]
        basis.append(v)
    return basis


def matmul(A, B):
    return [[sum((A[i][k] * B[k][j] for k in range(len(B))), A[0][0] * 0) for j in range(len(B[0]))]
            for i in range(len(A))]


def ctrans(A):
    return [[A[j][i].conj() for j in range(len(A))] for i in range(len(A[0]))]


def madd(A, B, a=1, b=1):
    return [[A[i][j] * a + B[i][j] * b for j in range(len(A[0]))] for i in range(len(A))]


def eye(n, one):
    return [[one if i == j else one * 0 for j in range(n)] for i in range(n)]


def principal_minors_nonneg(H):
    """Hermitian H (GQ entries) is PSD iff every principal minor is >= 0 (each is real)."""
    n = len(H)
    for mask in range(1, 1 << n):
        idx = [i for i in range(n) if mask >> i & 1]
        d = det([[H[i][j] for j in idx] for i in idx])
        d = GQ(d)
        if d.im != 0 or d.re < 0:
            return False
    return True


def proj(v):
    """Rank-one projector v v^dag / (v^dag v) over Q(i)."""
    n = sum((x.conj() * x for x in v), GQ(0))
    return [[v[i] * v[j].conj() / n for j in range(len(v))] for i in range(len(v))]


def span_projector(vs):
    """Orthogonal projector onto span(vs): B (B^dag B)^-1 B^dag, exact over Q(i)."""
    B = [[vs[j][i] for j in range(len(vs))] for i in range(len(vs[0]))]   # columns = vs
    G = matmul(ctrans(B), B)
    k = len(G)
    aug = [G[i] + eye(k, GQ(1))[i] for i in range(k)]
    R, piv = rref(aug)
    Ginv = [row[k:] for row in R]
    return matmul(matmul(B, Ginv), ctrans(B))


def hdot(u, v):
    return sum((u[i].conj() * v[i] for i in range(len(u))), GQ(0))


def interior_certificate(m, PK):
    """Find a rational lam > 0 with m - lam*PK PSD (exact).  Then m is not a boundary state of the face of states
    supported on range(PK): every state z of that face has z <= PK, and m + eps (m - z) >= ((1+eps) lam - eps) PK >= 0
    for 0 < eps <= lam/(1-lam).  Returns lam or None."""
    lam = Fr(1, 2)
    for _ in range(40):
        if principal_minors_nonneg(madd(m, PK, 1, -GQ(lam))):
            return lam
        lam /= 2
    return None


