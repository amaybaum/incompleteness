def in_H(H, p, strict=False):
    for (a, b) in H:
        s = sum((ai * pi for ai, pi in zip(a, p)), type(b)(0) if not isinstance(b, int) else 0) - b
        sg = s.sign() if hasattr(s, 'sign') else ((s > 0) - (s < 0))
        if sg > 0 or (strict and sg == 0):
            return False
    return True


def H_of_polygon(V, F=Fr):
    """facets a.x <= b of a convex polygon given in counterclockwise order"""
    H = []
    n = len(V)
    for i in range(n):
        p, q = V[i], V[(i + 1) % n]
        a = (q[1] - p[1], p[0] - q[0])            # outward normal for ccw order
        b = a[0] * p[0] + a[1] * p[1]
        H.append((a, b))
    return H


def boundary_witness_H(H, mpt, ypt):
    """m + eps(m - y) leaves Om for all eps > 0 iff some facet is tight at m and strictly separates y (a.y < b)."""
    for (a, b) in H:
        am = sum((ai * mi for ai, mi in zip(a, mpt)), a[0] * 0) - b
        ay = sum((ai * yi for ai, yi in zip(a, ypt)), a[0] * 0) - b
        sm = am.sign() if hasattr(am, 'sign') else ((am > 0) - (am < 0))
        sy = ay.sign() if hasattr(ay, 'sign') else ((ay > 0) - (ay < 0))
        if sm == 0 and sy < 0:
            return True
    return False


def half(p, q):
    return tuple((a + b) / 2 for a, b in zip(p, q))


