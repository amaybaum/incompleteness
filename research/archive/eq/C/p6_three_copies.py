"""P6 (QC2) -- three copies: idle extension of continuous pair dynamics.

6.1 Lie closure (layer [M], exact combinatorics on Pauli strings): the Lie algebra generated by the two-copy algebras
    su(4)_AB (x) 1 and 1 (x) su(4)_BC is su(8) (all 63 non-identity Pauli strings).  Control: su(4)_AB with local
    su(2)_C only (no BC interaction) closes at dimension 18.
6.2 The antiunitary pair map does not extend idly: (T_AB (x) id_C) sends the state |0><0| (x) Phi+_BC to an operator
    with a negative expectation (exact, Gaussian rationals); T_ABC (global transpose) is a control that does
    preserve positivity.
6.3 Quantum theory with n >= 3 copies: U_XY (x) id preserves the PSD cone (written: unitary congruence), so idle
    extension holds for every physical reversible pair map and fails exactly for the antiunitary symmetries.
Usage: python3 -I p6_three_copies.py
"""
import sys
import os
import itertools
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from eqclib import *  # noqa

rep = Report("P6 three copies")

# ------------------------------------------------------------------ 6.1 Pauli-string Lie closure
# multiplication table of single-qubit Paulis: s_a s_b = phase * s_c
def pmul(a, b):
    """index of the Pauli string factor s_a s_b up to phase (phases are irrelevant for the span)."""
    if a == 0:
        return b
    if b == 0:
        return a
    if a == b:
        return 0
    return 6 - a - b


def anticommute(P, Q):
    n = sum(1 for p, q in zip(P, Q) if p != 0 and q != 0 and p != q)
    return n % 2 == 1


def prod_string(P, Q):
    return tuple(pmul(p, q) for p, q in zip(P, Q))


def closure(gens):
    S = set(gens)
    frontier = list(gens)
    while frontier:
        new = []
        for P in frontier:
            for Q in list(S):
                if anticommute(P, Q):
                    R = prod_string(P, Q)
                    if R not in S:
                        S.add(R)
                        new.append(R)
        frontier = new
    return S


ab = [(p, q, 0) for p in range(4) for q in range(4) if (p, q) != (0, 0)]
bc = [(0, p, q) for p in range(4) for q in range(4) if (p, q) != (0, 0)]
S_full = closure(set(ab + bc))
rep.check("6.1a su(4)_AB + su(4)_BC generate all 63 non-identity Pauli strings (su(8), dim 63): the idle extensions "
          "of PU(4) on two overlapping pairs generate PU(8) [commutator of anticommuting strings = 2 x product]",
          len(S_full) == 63)
S_ctrl = closure(set(ab + [(0, 0, q) for q in (1, 2, 3)]))
rep.check("6.1b control: su(4)_AB with local su(2)_C only closes at dimension 18 (no interaction with C)",
          len(S_ctrl) == 18)


# ------------------------------------------------------------------ 6.2 T_AB (x) id_C is not positive
def basis_index(a, b, c):
    return 4 * a + 2 * b + c


rho = [[G(0)] * 8 for _ in range(8)]
# |0>_A (x) Phi+_BC, Phi+ = (|00> + |11>)/sqrt2  -> rho = |0><0| (x) (1/2)(|00>+|11>)(<00|+<11|)
vec_ = {}
for (b, c) in [(0, 0), (1, 1)]:
    vec_[basis_index(0, b, c)] = Fr(1)
for i in vec_:
    for j in vec_:
        rho[i][j] = G(Fr(1, 2))


def partial_transpose_AB(R):
    out = [[G(0)] * 8 for _ in range(8)]
    for a, b, c in itertools.product(range(2), repeat=3):
        for a2, b2, c2 in itertools.product(range(2), repeat=3):
            # (T_AB (x) id_C): |a b c><a2 b2 c2| -> |a2 b2 c><a b c2|
            out[basis_index(a2, b2, c)][basis_index(a, b, c2)] = R[basis_index(a, b, c)][basis_index(a2, b2, c2)]
    return out


def global_transpose(R):
    return [[R[j][i] for j in range(8)] for i in range(8)]


def expval(R, v):
    s = G(0)
    for i in range(8):
        for j in range(8):
            s = s + v[i].conj() * R[i][j] * v[j]
    return s


R1 = partial_transpose_AB(rho)
v = [G(0)] * 8
v[basis_index(0, 0, 1)] = G(1)
v[basis_index(0, 1, 0)] = G(-1)
val = expval(R1, v)
rep.check("6.2a (T_AB (x) id_C)(|0><0| (x) Phi+_BC) has expectation -1 on |0>(|01> - |10>) (norm^2 2): eigenvalue "
          "-1/2, so the idle extension of the antiunitary pair map leaves the three-copy PSD cone", val == G(-1), str(val))
R2 = global_transpose(rho)
rep.check("6.2b control: the global transpose T_ABC fixes this real symmetric state (it preserves positivity)", R2 == rho)
rep.check("6.2c control: rho itself has expectation 0 on that vector (rho is PSD; the sign comes from T_AB (x) id_C)",
          expval(rho, v) == G(0))
rep.note("6.3 [written] in quantum theory with n >= 3 copies, (U_XY (x) 1) rho (U_XY (x) 1)^dag is PSD for PSD rho, so "
         "idle extension holds for every unitary pair map; by 6.2 it fails for the antiunitary pair symmetries "
         "T_XY o Ad U, which preserve the two-copy cone Q3 but are not quantum operations. Idle extension is "
         "therefore satisfied by quantum theory exactly when it is stated for the physical (completely positive) "
         "reversible maps, not for all symmetries of the pair's state space.")
rep.verdict("THREE-COPY-INGREDIENTS-EXACT: overlapping pair dynamics generate PU(8); the antiunitary pair map has no "
            "idle extension; quantum theory satisfies idle extension for its unitary pair maps")
