import numpy as np
from scipy.optimize import minimize

rng = np.random.default_rng(2026100909)


def idx(x, y, z):
    return 4 * x + 2 * y + z


P = []
for b in range(4):
    b1, b2 = b >> 1, b & 1
    for t in range(2):
        v = np.zeros(8)
        v[idx(0, b1, b2)] = 1
        v[idx(1, 1 - b1, 1 - b2)] = 1 if t == 0 else -1
        P.append(np.outer(v, v) / 2)


def gd(vec):
    return sum(c * Pj for c, Pj in zip(vec, P))


# G as permutations of the 8 positions (generated by the seven generators of EQ4-P p11 H2)
gens = [(1, 0, 3, 2, 5, 4, 7, 6), (6, 7, 4, 5, 2, 3, 0, 1), (4, 5, 6, 7, 0, 1, 2, 3), (2, 3, 0, 1, 6, 7, 4, 5),
        (1, 0, 3, 2, 4, 5, 6, 7), (0, 1, 2, 3, 6, 7, 4, 5), (0, 1, 4, 5, 2, 3, 6, 7)]
group = {tuple(range(8))}
frontier = [tuple(range(8))]
while frontier:
    nf = []
    for g in frontier:
        for h in gens:
            c = tuple(g[h[i]] for i in range(8))
            if c not in group:
                group.add(c)
                nf.append(c)
    frontier = nf
print("|G| =", len(group), flush=True)


def orbit(vec):
    out = set()
    for g in group:
        out.add(tuple(vec[g[i]] for i in range(8)))
    return sorted(out)


p0 = (1, 1, 0, 0, 0, 0, 0, 0)
