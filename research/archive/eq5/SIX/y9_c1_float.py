def gl2(p):
    return (p[0:4] + 1j * p[4:8]).reshape(2, 2)


def kmat(p):
    return np.kron(np.kron(gl2(p[0:8]), gl2(p[8:16])), gl2(p[16:24]))


def val(p, g, gp):
    k = kmat(p)
    Y = k @ g @ k.conj().T
    return np.real(np.trace(gp @ Y)) / max(np.linalg.norm(gp) * np.linalg.norm(Y), 1e-300)


worst = (np.inf, None)
for (nm, g) in REPS.items():
    for j, gp in enumerate(GOPS):
        best = np.inf
        for _ in range(3):
            r = minimize(val, rng.normal(size=24), args=(g, gp), method="BFGS", options={"maxiter": 3000, "gtol": 1e-11})
            best = min(best, r.fun)
        if best < worst[0]:
            worst = (best, (nm, GEN[j]))
print("(1) Lift(K_tw) self-positivity: worst normalized min tr(g' Ad(k) g) = %.3e at %s" % worst, flush=True)


def t6(M):
    return M.reshape(2, 2, 2, 2, 2, 2)


SW = np.zeros((2, 2, 2, 2))
for a in range(2):
    for b in range(2):
        SW[a, b, b, a] = 0.5   # SWAP/2 [ket p, ket q; bra p, bra q]


def net_twin(x, y, e, f):
    # Glue_s[r1 r2 u1 u2; r1' r2' u1' u2'] = sum SW[p q; p' q'] x[p' r1 r2; p r1' r2'] y[q' u1 u2; q u1' u2']
    gs = np.einsum("pqPQ,PabpAB,QcdqCD->abcdABCD", SW, t6(x), t6(y))      # (r1 r2 u1 u2; ...)
    ge = np.einsum("stST,SacsAC,TbdtBD->acbdACBD", SW, t6(e), t6(f))      # (r1 u1 r2 u2; ...)
    ge = np.transpose(ge, (0, 2, 1, 3, 4, 6, 5, 7))                       # -> (r1 r2 u1 u2; ...)
    return np.real(np.einsum("abcdABCD,ABCDabcd->", ge, gs))


def gval(p, gs):
    nodes = [kmat(p[24 * i:24 * i + 24]) @ gs[i] @ kmat(p[24 * i:24 * i + 24]).conj().T for i in range(4)]
    return net_twin(*nodes) / np.prod([np.linalg.norm(X) for X in nodes])


