"""Two Bloch pairs sharing z: N = diag(u+, x+, y-, z-, w1+, w2-) (a reflection), native relations imposed exactly.
Quantum CNOT rules inside each pair; the 8 cross elements R (control in one pair, target in the other) are completed
by every signed involution allowed by the native parity relations. For each completion: involution, both native NOT
relations, the swap relation S = G (S G S) G, and positivity (block-coordinate min) of every element of the group
generated by G, N(x)I, I(x)N, S -- up to left multiplication by locals, which preserve max."""
import itertools, numpy as np
from ball5 import *
Nf = {Y, Z, W2}; Nsg = {i: (-1 if i in Nf else 1) for i in range(6)}
pair = {X: 1, Y: 1, W1: 2, W2: 2}
Jm = {X: (1, Y), Y: (-1, X), W1: (1, W2), W2: (-1, W1)}
plus = {1: X, 2: W1}; minus = {1: Y, 2: W2}
base = {}
for c in (X, Y, W1, W2):
    P = pair[c]
    base[(c, U)] = (1, c, plus[P])                       # c (x) u -> c (x) x_P
    s, k = Jm[c]; base[(c, Z)] = (-s, k, minus[P])       # c (x) z -> -J c (x) y_P
for (c, j), (s, k, l) in list(base.items()):             # involution partner
    base[(k, l)] = (s, c, j)
R = [(c, j) for c in (X, Y, W1, W2) for j in (X, Y, W1, W2) if (c, j) not in base]
print('R =', R)
def ok_pair(a, b):                                       # a -> b allowed by parity relations
    (i, j), (k, l) = a, b
    return Nsg[j] == Nsg[l] and Nsg[i] * Nsg[k] == Nsg[l]
def involutions(items):
    if not items: yield {}; return
    a = items[0]; rest = items[1:]
    if ok_pair(a, a):
        for s in (1, -1):
            for m in involutions(rest): m2 = dict(m); m2[a] = (s, a); yield m2
    for b in rest:
        if ok_pair(a, b) and ok_pair(b, a):
            r2 = [x for x in rest if x != b]
            for s in (1, -1):
                for m in involutions(r2): m2 = dict(m); m2[a] = (s, b); m2[b] = (s, a); yield m2
Nloc = diagN(Nf); NI = loc_pair(Nloc, ident); IN = loc_pair(ident, Nloc)
cands = list(involutions(R)); print('completions satisfying parity:', len(cands))
test = rng.normal(size=(400, 4, 5)); test /= np.linalg.norm(test, axis=2, keepdims=True)
tv = [np.concatenate([np.ones((400, 1)), test[:, b]], 1) for b in range(4)]
def quick(M):
    T = M.reshape(6, 6, 6, 6); return np.einsum('ijkl,ni,nj,nk,nl->n', T, *tv).min()
res = []
for m in cands:
    rules = dict(base); rules.update({a: (s, b[0], b[1]) for a, (s, b) in m.items()})
    G = controlled(Nf, rules)
    inv = (G * G).key() == SP(range(D), [1] * D).key()
    tr = ((IN * G) * IN).key() == G.key(); cr = ((NI * G) * NI).key() == (IN * G).key()
    sw = (G * (S * G * S) * G).key() == S.key()
    q = quick(G.mat())
    res.append((q, inv, tr, cr, sw, m, G))
res.sort(key=lambda r: -r[0])
print('best quick min over candidates: %+.3f; relations of best: inv %s target %s control %s swap %s' % res[0][:5])
print('number with quick min >= -1e-9:', sum(r[0] >= -1e-9 for r in res), ' with swap relation:', sum(r[4] for r in res))
for r in res[:3]:
    v, _ = min_value(r[6].mat(), starts=150); print('  candidate BCD min G: %+.3e  (inv %s tr %s cr %s sw %s)' % (v, *r[1:5]))
allv = []
for r in res:
    v, _ = min_value(r[6].mat(), starts=40, iters=40); allv.append(v)
print('BCD over all %d completions: max of min values %+.3f (all negative: %s)' % (len(allv), max(allv), max(allv) < -1e-6))
