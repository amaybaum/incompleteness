def rand_partition(tokens):
    toks = list(tokens)
    rng.shuffle(toks)
    blocks = []
    while toks:
        k = 2 if (len(toks) >= 2 and rng.random() < 0.6) else 1
        blocks.append(tuple(toks[:k]))
        toks = toks[k:]
    return blocks


def rand_pn(tokens):
    blocks = rand_partition(tokens)
    ops_ = [L.rand_psd(rng, b, rank=rng.choice([1, 2])) for b in blocks]
    return L.reorder(L.tensor(*ops_), tuple(tokens)), blocks


def predicted_partition(A, state_blocks, eff_blocks):
    """components of the contraction graph restricted to open tokens A."""
    nodes = [("s", b) for b in state_blocks] + [("e", b) for b in eff_blocks]
    parent = list(range(len(nodes)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    tok_nodes = {}
    for idx, (_, b) in enumerate(nodes):
        for tok in b:
            tok_nodes.setdefault(tok, []).append(idx)
    for tok, lst in tok_nodes.items():
        for j in lst[1:]:
            parent[find(j)] = find(lst[0])
    comps = {}
    for tok in A:
        comps.setdefault(find(tok_nodes[tok][0]), []).append(tok)
    return [tuple(v) for v in comps.values()]


def is_pn_product(Cop, blocks):
    tr = L.trace(Cop)
    if tr.is_zero():
        return Cop.is_zero(), True
    margs = [L.ptrace(Cop, b) for b in blocks]
    prod = L.reorder(L.tensor(*margs), Cop.qs)
    k = len(blocks)
    scale = L.ONE
    for _ in range(k - 1):
        scale = scale * tr
    ok_prod = prod == Cop.scale(scale)
    ok_psd = all(L.psd(m)[0] for m in margs) and all(len(b) <= 2 for b in blocks)
    return ok_prod, ok_psd


