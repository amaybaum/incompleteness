def rank_exact(rows):
    """rank of a matrix of G entries by exact Gaussian elimination."""
    M = [list(r) for r in rows]
    rk = 0
    ncol = len(M[0]) if M else 0
    for c in range(ncol):
        piv = next((r for r in range(rk, len(M)) if not M[r][c].is_zero()), None)
        if piv is None:
            continue
        M[rk], M[piv] = M[piv], M[rk]
        for r in range(len(M)):
            if r != rk and not M[r][c].is_zero():
                fct = M[r][c] / M[rk][c]
                M[r] = [M[r][j] - fct * M[rk][j] for j in range(ncol)]
        rk += 1
    return rk


def schmidt_rank(vec, n, part):
    rest = [k for k in range(n) if k not in part]
    rows = {}
    for idx, v in enumerate(vec):
        if L.G.of(v).is_zero():
            continue
        bits = [(idx >> (n - 1 - k)) & 1 for k in range(n)]
        r = L.bits_index([bits[k] for k in part])
        c = L.bits_index([bits[k] for k in rest])
        rows.setdefault(r, {})[c] = L.G.of(v)
    R_ = 2 ** len(part)
    C_ = 2 ** len(rest)
    mat = [[rows.get(r, {}).get(c, L.ZERO) for c in range(C_)] for r in range(R_)]
    return rank_exact(mat)


