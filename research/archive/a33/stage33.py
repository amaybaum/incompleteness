ORBIT = {'OrbitGeometryRigidity', 'OrbitGeometryIsometries', 'OrbitGeometrySelector', 'OrbitIsometryClassification', 'OrbitLawGaps', 'OrbitLawRigidityTwisted', 'GramTrajectorySelection', 'TwoSidedGauge'}
