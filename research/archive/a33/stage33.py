DOC = '''/-!
# Act 33 — the isometry group of the normalized single-carrier space

At the single-carrier configuration of acts 24–26 (`Γ₀ ≡ ¼`, the ancilla `Fin 1`, act 24's
distance), this module classifies the surjective isometries of act 26's normalized space, the
union of the nine relabelled Fourier circles.

Every such map carries each circle onto a circle, acts on it by `w ↦ λ w` or `w ↦ λ w̄` with
`λ ∈ {1, −1}`, and is determined by the automorphism it induces on the incidence graph `K₃,₃` of
the six shared points together with nine conjugation bits; every such pair is realized. The
automorphisms are generated by three relabellings and the transpose, and the finite parts — the
72 automorphisms, the shape words of act 25's family and the parity patterns of the kernel — are
decided by the kernel.

The module carries no definition. Every theorem prints its axioms.
-/
'''

src = open(sys.argv[1], encoding='utf-8').read()
head_end = src.index('namespace OIBridge\n')
head = src[:head_end]
assert head.startswith(C.IMPORT)
body = src[head_end:]
new_head = C.IMPORT + '\n' + DOC + '\n'

# cut the verdict and the corollary (each: theorem ... #print axioms NAME\n\n)
def cut(text, name):
    m = re.search(r'(?m)^theorem %s :\n' % re.escape(name), text)
    assert m, name
    e = re.search(r'(?m)^#print axioms %s\n\n' % re.escape(name), text[m.start():])
    assert e, name
    piece = text[m.start():m.start() + e.end()]
    return text[:m.start()] + text[m.start() + e.end():], piece

body1, verdict = cut(body, 'a33_classified')
body1, coroll = cut(body1, 'a33_c_exclusive')
tail = 'end OrbitIsometryGroup\nend OIBridge\n'
assert body1.endswith(tail)
stage1 = new_head + body1
stage2 = new_head + body1[:-len(tail)] + verdict + coroll + tail
open(S + 'stage1.lean', 'w', encoding='utf-8').write(stage1)
open(S + 'stage2.lean', 'w', encoding='utf-8').write(stage2)
for nm, txt in (('stage1', stage1), ('stage2', stage2)):
    lab, f = C.module_label(txt)
    print(nm, 'label', lab, 'findings', f, 'theorems', len(C.theorems(C.strip_comments(txt))))
    print(nm, 'blob', subprocess.run(['git', 'hash-object', S + nm + '.lean'], capture_output=True, text=True).stdout.strip())

