#!/usr/bin/env python3
"""Thread C (FOUR-COMP) -- c1: cone-level exact checks for the four-copy interface FCC.

Research only. Exact arithmetic (sympy Rationals and Gaussian rationals); no floating point, no randomness, no time in
stdout. Reads three landed Lean sources and two design sources read-only, to check the transcription of the tables and
of the statements the checks rest on. Usage:
    python3 -I -B c1_cone_level.py <base>/verification/lean-mathlib/OIBridge <inputs>/fourcopy

Conventions (transcribed; S0 checks them): tables W 3 = 4x4, index 0 the unit; hom x = (1, x); prodState x y =
hom x hom y^T; homMap R = diag(1, R); actC R w = homMap R . w; actT R w = w . homMap R^T; reflY = diag(1, -1, 1), so
D := homMap reflY = diag(1, 1, -1, 1); cnot w (m, n) = sgn(m, n) w(pc(m, n), pt(m, n)); ipW E X = sum E_mn X_mn;
fourVal X Y E F = sum X_ab Y_cd E_ac F_bd (X on tokens 01, Y on 23, E on 02, F on 13); the famII value
g2 e f L L' = sum e_ab f_cd L_ac L'_bd (L on 02, L' on 13, e on 01, f on 23); pauliW w = (1/4) sum w_mn s_m (x) s_n,
opW E = sum E_mn s_m (x) s_n with s = (I, X, Y, Z); Q3 = {w : pauliW w >= 0}; dualW Q3 = {E : opW E >= 0} (landed
probe note D.W); twin = actT reflY '' Q3.

FCC(K01, K23, K02, K13) (FourCopyDefs.lean): famI: fourVal X Y E F >= 0 for X in K01, Y in K23, E in dualW K02,
F in dualW K13; famII: g2 e f L L' >= 0 for L in K02, L' in K13, e in dualW K01, f in dualW K23.

DECISION RULE (fixed before the first run). Each check prints PASS or FAIL. A check of kind [countercontrol] PASSES
exactly when the mutated object gives the opposite verdict (it must fail the property the paired check certifies).
The script prints 'VERDICT C1-CONE-LEVEL-EXACT' if and only if every check passes; otherwise it prints
'VERDICT NOT RENDERED' with the failed ids and exits 1. Membership claims that rest on a standard fact (the Kronecker
product of PSD matrices is PSD; a dual cone is unchanged by an ipW-isometry applied to both sides; a cone generated by
a compact base not containing 0 is closed) are printed as NOTE [written] lines and are not checks.

Sections:
  S0  transcription of the landed tables and of the design statements used.
  S1  identities: the two contraction forms, the sign charts, the partial transposes, cnot as an ipW-isometric
      involution, and the reflection conjugates of cnot.
  S2  the mixed assignment (Q3, Q3, Q3, twin): famI and famII both fail, with memberships.
  S3  the sixteen twist patterns of {Q3, twin}^4: the per-token transport identity, the coboundary enumeration, an
      exact negative witness for every odd pattern.
  S4  the tree (sub-plaquette) obstruction: on every proper subset of the four pairs the mixed assignment is a chart
      transform of uniform Q3 with cnot gates.
  S5  the entangled core: famI and famII with any separable argument reduce to pairings of Lorentz vectors.
  S6  the uniform foil K_c = cone(SEP u cnot SEP): a cnot-invariant effect E0 outside dualW Q3, and FCC failures for
      uniform K_c, for (Q3, Q3, K_c, K_c) (famI) and for (K_c, K_c, Q3, Q3) (famII).
"""
