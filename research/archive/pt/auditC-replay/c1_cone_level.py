section('S5  the entangled core: one separable argument makes famI and famII automatic')

p, q, u, wv = [sp.Matrix(symvec(nm, 4)) for nm in ('p', 'q', 'u', 'v')]
ok_e = zero(fourVal(p * q.T, Yg, Eg, Fg) - (p.T * Eg * (Yg * Fg.T * q))[0, 0])
ok_e = ok_e and zero(fourVal(Xg, p * q.T, Eg, Fg) - ((Eg * p).T * Xg * (Fg * q))[0, 0])
ok_e = ok_e and zero(fourVal(Xg, Yg, u * wv.T, Fg) - ((Xg.T * u).T * Fg * (Yg.T * wv))[0, 0])
ok_e = ok_e and zero(fourVal(Xg, Yg, Eg, u * wv.T) - ((Xg * u).T * Eg * (Yg * wv))[0, 0])
chk('E1', 'famI with one rank-one argument: fourVal (p q^T) Y E F = p^T E (Y F^T q), fourVal X (p q^T) E F = '
    '(E p)^T X (F q), fourVal X Y (u v^T) F = (X^T u)^T F (Y^T v), fourVal X Y E (u v^T) = (X u)^T E (Y v), symbolic',
    ok_e, 'identity')
ok_e2 = zero(g2(p * q.T, Fg, Xg, Yg) - (p.T * Xg * (Fg * Yg.T * q))[0, 0])
ok_e2 = ok_e2 and zero(g2(Eg, p * q.T, Xg, Yg) - ((Xg * p).T * Eg * (Yg * q))[0, 0])
ok_e2 = ok_e2 and zero(g2(Eg, Fg, u * wv.T, Yg) - ((Eg.T * u).T * Yg * (Fg.T * wv))[0, 0])
