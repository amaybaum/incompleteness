section('S4  the tree obstruction (proper subsets of the 4-cycle)')

tau_tok = (0, 0, 0, 1)
ok_tree = True
for k in range(4):
    sub = [i for i in range(4) if i != k]
    ok_tree = ok_tree and any(all(cob(s)[i] == tau_tok[i] for i in sub) for s in product((0, 1), repeat=4))
chk('R1', 'on each of the four 3-pair subsets, the twist pattern of (Q3, Q3, Q3, twin) agrees with a coboundary',
    ok_tree, 'enumerate')
chk('R1c', 'countercontrol: on all four pairs no coboundary agrees with it', not any(
    cob(s) == tau_tok for s in product((0, 1), repeat=4)), 'countercontrol')


def chart(a, b, w):
    return Dpow(a) * w * Dpow(b)


ok_g = True
for a, b in product((0, 1), repeat=2):
    conj = chart(a, b, cnot(chart(a, b, Wg)))
    target = cnot(Wg) if a == b else cnotTw(Wg)
    ok_g = ok_g and mzero(conj - target)
chk('R2', 'gate transport: chart(a,b) . cnot . chart(a,b) is cnot for a = b and cnotTw for a != b, symbolic',
    ok_g, 'identity')
note('R.W', 'the obstruction (written). Let Pi be a conjunction of predicates Pi_k, each reading only the data (cones, '
     'gates, locals) of a proper subset S_k of the four pairs and each invariant under per-token reflection charts. '
     'If Pi holds at the quantum data (uniform Q3, cnot gates, identity locals), it holds at the data of M_tok '
     '(cones Q3, Q3, Q3, twin; gates cnot, cnot, cnot, cnotTw; B_13 = B\'_13 = reflY): by R1 there is s with '
     'cob(s) = tau on S_k, and by I4W and R2 the chart (reflY^{s_t}) maps the quantum data on S_k onto the M_tok data '
     'on S_k. FCC fails for M_tok (S2). So no such Pi implies FCC: a principle that excludes the mixed assignment '
     'must couple all four pairs or depend on the charts.')

