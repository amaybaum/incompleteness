section('S3  the sixteen twist patterns of {Q3, twin}^4 (pairs in the order 01, 23, 02, 13)')

ok_t = True
for s in product((0, 1), repeat=4):
    s0, s1, s2, s3 = s
    lhs1 = fourVal(Dpow(s0) * Xg * Dpow(s1), Dpow(s2) * Yg * Dpow(s3), Dpow(s0) * Eg * Dpow(s2),
                   Dpow(s1) * Fg * Dpow(s3))
    lhs2 = g2(Dpow(s0) * Eg * Dpow(s1), Dpow(s2) * Fg * Dpow(s3), Dpow(s0) * Xg * Dpow(s2), Dpow(s1) * Yg * Dpow(s3))
    ok_t = ok_t and zero(lhs1 - fourVal(Xg, Yg, Eg, Fg)) and zero(lhs2 - g2(Eg, Fg, Xg, Yg))
chk('T1', 'per-token transport: for all 16 s, fourVal and g2 are unchanged when the table of pair (i, j) is replaced by '
    'D^{s_i} . D^{s_j} (symbolic)', ok_t, 'identity')
chk('T1c', 'countercontrol: a sign chart applied to X alone changes fourVal', not zero(
    fourVal(Dg * Xg, Yg, Eg, Fg) - fourVal(Xg, Yg, Eg, Fg)), 'countercontrol')
EDGES = {'01': (0, 1), '23': (2, 3), '02': (0, 2), '13': (1, 3)}
ORDER = ['01', '23', '02', '13']


def cob(s):
    return tuple(s[EDGES[e][0]] ^ s[EDGES[e][1]] for e in ORDER)


cobs = {cob(s) for s in product((0, 1), repeat=4)}
pats = list(product((0, 1), repeat=4))
even = [t for t in pats if sum(t) % 2 == 0]
chk('T2', 'the coboundaries are exactly the 8 even patterns (enumeration over the 16 s)',
    cobs == set(even) and len(even) == 8, 'enumerate')
ok_odd = True
vals_odd = set()
for t in pats:
    if sum(t) % 2 == 0:
        continue
    # t = (0, 0, 0, 1) + cob(s): find s
    base = (0, 0, 0, 1)
    s = next(s for s in product((0, 1), repeat=4) if tuple(base[i] ^ cob(s)[i] for i in range(4)) == t)
    s0, s1, s2, s3 = s
    X_ = Dpow(s0) * phiW * Dpow(s1)
    Y_ = Dpow(s2) * phiW * Dpow(s3)
    E_ = Dpow(s0) * (phiW / 4) * Dpow(s2)
    F_ = Dpow(s1) * F_tw * Dpow(s3)
    w1 = fourVal(X_, Y_, E_, F_)
    e_ = Dpow(s0) * (phiW / 4) * Dpow(s1)
    f_ = Dpow(s2) * (phiW / 4) * Dpow(s3)
    L_ = Dpow(s0) * phiW * Dpow(s2)
    Lp_ = Dpow(s1) * Lp * Dpow(s3)
    w2 = g2(e_, f_, L_, Lp_)
    vals_odd.add((w1, w2))
    ok_odd = ok_odd and w1 < 0 and w2 < 0
chk('T3', 'every odd pattern has transported witnesses at which famI and famII are negative', ok_odd and len(vals_odd)
    == 1, 'enumerate', f'values {sorted(vals_odd)}')
note('T.W', 'membership of the transported witnesses: D^a Q3 D^b is Q3 for a = b and twin for a != b (I4W), and the '
     'transported witnesses sit in the cones of the transported pattern t = (0,0,0,1) + cob(s). Even patterns: FCC '
     'holds by T1 and FCC for uniform Q3 (landed F2, F3 with the Kronecker product of PSD matrices, note F.Q3). So on '
     '{Q3, twin}^4, FCC holds exactly for the 8 coboundary patterns: there are per-token reflection charts in which '
     'all four cones are Q3 (this is the design package\'s open fourCopyCoherent_chart, here by T1).')

