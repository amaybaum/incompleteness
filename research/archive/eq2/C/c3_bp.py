# ----------------------------------------------------------------------------- polygon machinery (2D, exact)

def outward_normals(V):
    """V: vertices in counterclockwise order. normal of edge k = [V[k], V[k+1]] is (dy, -dx)."""
    n = len(V)
    out = []
    for k in range(n):
        d = vsub(V[(k + 1) % n], V[k])
        out.append((d[1], -d[0]))
    return out


def in_cone(x, g1, g2):
    """x in cone(g1, g2) for g1 -> g2 counterclockwise with angle < pi."""
    return cross2(g1, x).sign() >= 0 and cross2(x, g2).sign() >= 0 if hasattr(cross2(g1, x), "sign") else \
        cross2(g1, x) >= 0 and cross2(x, g2) >= 0


def normal_cone(V, i):
    """normal cone of vertex i: generated by the outward normals of edges (i-1, i) and (i, i+1), ccw order."""
    nrm = outward_normals(V)
    n = len(V)
    return nrm[(i - 1) % n], nrm[i]


def cones_meet(A, B):
    a1, a2 = A
    b1, b2 = B
    return in_cone(a1, b1, b2) or in_cone(a2, b1, b2) or in_cone(b1, a1, a2) or in_cone(b2, a1, a2)


def neg(v):
    return tuple(-x for x in v)


def is_frame(V, i, j):
    """exists linear l maximal over V at V[i] and minimal at V[j]: N_i meets -N_j."""
    if i == j:
        return False
    b1, b2 = normal_cone(V, j)
    return cones_meet(normal_cone(V, i), (neg(b1), neg(b2)))


def frame_effect(V, i, j):
    """an explicit distinguishing effect: a common direction l, e = (l - min)/(max - min)."""
    A = normal_cone(V, i)
    b1, b2 = normal_cone(V, j)
    B = (neg(b1), neg(b2))
    for cand in (A[0], A[1], B[0], B[1]):
        if in_cone(cand, *A) and in_cone(cand, *B):
            l = cand
            break
    vals = [dot(l, v) for v in V]
    mx, mn = max(vals), min(vals)
    return [(x - mn) / (mx - mn) for x in vals]


def frames_of(V):
    n = len(V)
    return [(i, j) for i in range(n) for j in range(n) if is_frame(V, i, j)]


def on_segment_line(p, a, b):
    return cross2(vsub(b, a), vsub(p, a)) == 0


def in_polygon_strict(V, p):
    nrm = outward_normals(V)
    return all((dot(nrm[k], vsub(p, V[k]))).sign() < 0 if hasattr(dot(nrm[k], vsub(p, V[k])), "sign")
               else dot(nrm[k], vsub(p, V[k])) < 0 for k in range(len(V)))


def orbit_ordered_pairs(gens_perm, start):
    """orbit of an ordered vertex pair under the group generated by vertex permutations"""
    seen = {start}
    frontier = [start]
    while frontier:
        new = []
        for (i, j) in frontier:
            for g in gens_perm:
                q = (g[i], g[j])
                if q not in seen:
                    seen.add(q)
                    new.append(q)
        frontier = new
    return seen


def perm_of_linear(M, V):
    """the vertex permutation induced by a linear map M (must permute V)"""
    img = [mat_vec(M, v) for v in V]
    perm = []
    for w in img:
        hits = [k for k, v in enumerate(V) if v == w]
        if len(hits) != 1:
            return None
        perm.append(hits[0])
    return perm if sorted(perm) == list(range(len(V))) else None


