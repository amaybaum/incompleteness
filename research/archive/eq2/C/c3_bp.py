#   x2 = v, y2 = -v, p = (1+B)/2; x1, y1 unit with p x1 + (1-p) y1 = A u, <A u, x1> = mu = (A^2 + B)/(1 + B)
def rat_sqrt(q):
    q = Fr(q)
    if q < 0:
        return None
    from math import isqrt
    n, d = q.numerator, q.denominator
    rn, rd = isqrt(n), isqrt(d)
    return Fr(rn, rd) if rn * rn == n and rd * rd == d else None


