def zero(M):
    return M.applyfunc(sp.expand).is_zero_matrix


def twist(sig, t):
    return L.actT(RY, sig) if t else sig


def gen3(sig, pair, z):
    """sigma on `pair` (first index = pair[0]) times hom(z) on the remaining copy."""
    i, j = pair
    k = [c for c in range(3) if c not in pair][0]
    hz = L.hom(z)
    T = {}
    for idx in itertools.product(range(4), repeat=3):
        T[idx] = sig[idx[i], idx[j]] * hz[idx[k]]
    return T


def prod3(x, y, z):
    hx, hy, hz = L.hom(x), L.hom(y), L.hom(z)
    return {idx: hx[idx[0]] * hy[idx[1]] * hz[idx[2]] for idx in itertools.product(range(4), repeat=3)}


def tab_eq(A, B):
    return all(sp.expand(A[k] - B[k]) == 0 for k in A)


def marg(T, pair):
    i, j = pair
    k = [c for c in range(3) if c not in pair][0]
    def ent(m, n):
        idx = [0, 0, 0]
        idx[i], idx[j], idx[k] = m, n, 0
        return T[tuple(idx)]
    return Matrix(4, 4, ent)


def cond(T, pair, f):
    i, j = pair
    k = [c for c in range(3) if c not in pair][0]
    def ent(m, n):
        s = 0
        for c in range(4):
            idx = [0, 0, 0]
            idx[i], idx[j], idx[k] = m, n, c
            s += T[tuple(idx)] * f[c]
        return sp.expand(s)
    return Matrix(4, 4, ent)


def pair3(Tab, a, b, c):
    return sp.expand(sum(Tab[idx] * a[idx[0]] * b[idx[1]] * c[idx[2]] for idx in Tab))


def rand_rat_ball():
    while True:
        v = [R(rng.randint(-9, 9), 10) for _ in range(3)]
        if sum(t * t for t in v) <= 1:
            return v


def rand_lor():
    v = rand_rat_ball()
    a0 = R(rng.randint(1, 5), 2)
    return [a0] + [a0 * t for t in v]


def rand_density(d):
    A = Matrix(d, d, lambda i, j: R(rng.randint(-3, 3), rng.randint(1, 3)) + I * R(rng.randint(-3, 3), rng.randint(1, 3)))
    M = A * A.H
    return (M / M.trace()).applyfunc(sp.expand)


def rand_pair_table(t):
    return twist(L.coordsW(rand_density(4)), t)


