def even4(n, tau):
    for a_, b_, c_, d_ in itertools.permutations(range(n), 4):
        cyc = [(a_, b_), (b_, c_), (c_, d_), (d_, a_)]
        if sum(tau[tuple(sorted(p))] for p in cyc) % 2:
            return False
    return True


