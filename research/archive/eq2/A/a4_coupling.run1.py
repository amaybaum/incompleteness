def bell_tables():
    return [sp.diag(1, 1, -1, 1), sp.diag(1, -1, 1, 1), sp.diag(1, 1, 1, -1), sp.diag(1, -1, -1, -1)]


def val4(s01, s23, E12, F03):
    tot = 0
    for i0, i1, i2, i3 in itertools.product(range(4), repeat=4):
        sv = s01[i0, i1] * s23[i2, i3]
        if sv == 0:
            continue
        ev = E12[i1, i2] * F03[i0, i3]
        if ev != 0:
            tot += sv * ev
    return tot


