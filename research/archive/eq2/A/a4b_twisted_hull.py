"""EQ2-A probe A4b -- the all-twisted pairwise hull B_tw and the GHZ witness, exact.  Research only; base bcbc516f.
Usage: python3 -I -B a4b_twisted_hull.py

B_tw (three copies, operator form): the closed convex cone generated by PT_j(sigma_ij) (x) rho_k for every pair
(i, j) with i < j (partial transpose on the SECOND copy j), every two-qubit state sigma and every one-qubit state rho.
(In Pauli tables this is M_tw = K_(1,1,1) of a4_coupling.py, the twist on copy j being actT reflY = PT_j.)
W = 1/2 - |GHZ><GHZ| is in B_tw* (a4_coupling C9/C10, written Schmidt bound).

CLAIM checked here: W is ALSO in B_tw.  Construction (found by hand from the stabilizer coordinates; the float
exploration x2 pointed to it):
  alpha_p = PT_{p[1]}(Psi-)          (x) |+><+|   on the remaining copy
  beta_p  = PT_{p[1]}(Psi-_rot)      (x) |+i><+i| on the remaining copy,   Psi-_rot = (1 (x) U) Psi- (1 (x) U)^H
  delta_p = PT_{p[1]}((Psi- + Psi+)/2) (x) 1/2  on the remaining copy
  M = (1/9) sum_p (alpha_p + beta_p + delta_p),  twirl(M) = (1/8) sum_{s in Stab(GHZ)} s M s^H.
The twirl is an average of conjugations by local Pauli products, each a product of local pi-rotations, which preserve
every generator family (Tw is invariant under local SO(3)^2), so twirl(M) is in B_tw.

DECISION RULE (fixed before the first run): verdict `A4b-GHZ-WITNESS-IN-TWISTED-HULL` iff
  K1  every alpha/beta/delta has trace 1 and is PT_j of a PSD matrix (sigma PSD checked by exact eigen-decomposition)
  K2  the 8 stabilizer elements commute, square to 1, and fix GHZ (control: the twirl of GHZ is GHZ)
  K3  twirl(M) = W/3 exactly
  K4  countercontrol: without the beta family (alpha and delta only, renormalized) the twirl is NOT W/3
  K5  the stabilizer-coordinate vectors of the three families are as derived: (alpha) -1 on {ZZ_p, XXX, Y_p},
      (beta) -1 on ZZ_p and the two other Y-stabilizers, (delta) -1 on ZZ_p only
all pass.  Exact Gaussian-rational arithmetic only.
"""
import itertools
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sympy as sp  # noqa: E402
from sympy import I, Matrix, Rational as R, eye, zeros  # noqa: E402

import eq2a_lib as L  # noqa: E402

check = L.check
X, Y, Z, I2 = L.SX, L.SY, L.SZ, L.S0


def zero(M):
    return M.applyfunc(sp.expand).is_zero_matrix


def ket(bits):
    return Matrix([1 if i == int(bits, 2) else 0 for i in range(2 ** len(bits))])


def place(sig4, pair, rho2):
    """sigma on `pair` (sigma's tensor order = pair order) times rho on the remaining copy, as an 8x8 matrix."""
    i, j = pair
    k = [c for c in range(3) if c not in pair][0]
    M = zeros(8, 8)
    for a in itertools.product(range(2), repeat=3):
        for b in itertools.product(range(2), repeat=3):
            v = sig4[2 * a[i] + a[j], 2 * b[i] + b[j]] * rho2[a[k], b[k]]
            if v != 0:
                M[4 * a[0] + 2 * a[1] + a[2], 4 * b[0] + 2 * b[1] + b[2]] = v
    return M


def gen(sig4, pair, rho2):
    return L.pt(place(sig4, pair, rho2), pair[1], [2, 2, 2])


psim = Matrix([0, 1, -1, 0]) / 1
Psim = psim * psim.H / 2
psip = Matrix([0, 1, 1, 0])
Psip = psip * psip.H / 2
S = sp.diag(1, I)                      # Bloch rotation by +90 degrees about z
U_rot = L.kron(I2, S)
Psim_rot = (U_rot * Psim * U_rot.H).applyfunc(sp.expand)
Tc = Matrix(3, 3, lambda a, b: sp.expand((Psim_rot * L.kron([X, Y, Z][a], [X, Y, Z][b])).trace()))
plus = Matrix([1, 1]) / 1
plusi = Matrix([1, I]) / 1
rho_plus = plus * plus.H / 2
rho_plusi = plusi * plusi.H / 2
PAIRS = [(0, 1), (0, 2), (1, 2)]
alpha = [gen(Psim, p, rho_plus) for p in PAIRS]
beta = [gen(Psim_rot, p, rho_plusi) for p in PAIRS]
delta = [gen((Psim + Psip) / 2, p, eye(2) / 2) for p in PAIRS]
print(f"     correlation matrix of Psi-_rot: {Tc.tolist()}")

okK1 = all(sp.expand(g.trace()) == 1 for g in alpha + beta + delta)
for sig in (Psim, Psim_rot, (Psim + Psip) / 2):
    ev = sig.eigenvals()
    okK1 = okK1 and all(sp.re(e) >= 0 and sp.im(e) == 0 for e in ev) and (sig - sig.H).is_zero_matrix
check("K1 all nine generators have trace 1 and are PT_j(sigma) (x) rho with sigma, rho PSD", okK1)

stab_lbls = [(1, "III"), (1, "ZZI"), (1, "IZZ"), (1, "ZIZ"), (1, "XXX"), (-1, "YYX"), (-1, "XYY"), (-1, "YXY")]
PM = {"I": I2, "X": X, "Y": Y, "Z": Z}
stab = [sg * L.kron(PM[l[0]], PM[l[1]], PM[l[2]]) for sg, l in stab_lbls]
ghz = (ket("000") + ket("111"))
GHZ = ghz * ghz.H / 2
okK2 = all(zero(s1 * s2 - s2 * s1) for s1 in stab for s2 in stab) and all(zero(s * s - eye(8)) for s in stab) \
    and all(zero(s * ghz - ghz) for s in stab)
check("K2 the GHZ stabilizer group: 8 commuting involutions fixing GHZ", okK2)


def twirl(M):
    return (sum((s * M * s.H for s in stab), zeros(8, 8)) / 8).applyfunc(sp.expand)


check("K2 control: twirl(GHZ) = GHZ", zero(twirl(GHZ) - GHZ))
Wop = eye(8) / 2 - GHZ
Mmix = sum(alpha + beta + delta, zeros(8, 8)) / 9
check("K3 twirl((1/9) sum_p (alpha_p + beta_p + delta_p)) = W/3 exactly  =>  W is in B_tw", zero(twirl(Mmix) - Wop / 3))
Mbad = sum(alpha + delta, zeros(8, 8)) / 6
check("K4 countercontrol: the twirl without the beta family is not a multiple of W",
      not zero(twirl(Mbad) - (twirl(Mbad).trace() / Wop.trace()) * Wop))


def tvec(g):
    return [sp.expand((g * s).trace()) for s in stab[1:]]


names = ["ZZI", "IZZ", "ZIZ", "XXX", "YYX", "XYY", "YXY"]
zz_of = {(0, 1): "ZZI", (1, 2): "IZZ", (0, 2): "ZIZ"}
ylink = {(0, 1): "YYX", (0, 2): "YXY", (1, 2): "XYY"}
okK5 = True
for p_i, p in enumerate(PAIRS):
    ta, tb, td = (dict(zip(names, tvec(g))) for g in (alpha[p_i], beta[p_i], delta[p_i]))
    exp_a = {nm: (-1 if nm in (zz_of[p], "XXX", ylink[p]) else 0) for nm in names}
    exp_b = {nm: (-1 if (nm == zz_of[p] or nm in {"YYX", "XYY", "YXY"} - {ylink[p]}) else 0) for nm in names}
    exp_d = {nm: (-1 if nm == zz_of[p] else 0) for nm in names}
    okK5 = okK5 and ta == exp_a and tb == exp_b and td == exp_d
    print(f"     pair {p}: alpha {[ta[n] for n in names]}  beta {[tb[n] for n in names]}  delta {[td[n] for n in names]}")
check("K5 stabilizer coordinates of the three families match the derivation", okK5)

ok = L.summary("a4b_twisted_hull")
print("VERDICT " + ("A4b-GHZ-WITNESS-IN-TWISTED-HULL" if ok else "A4b-NOT-RENDERED"))
sys.exit(0 if ok else 1)
