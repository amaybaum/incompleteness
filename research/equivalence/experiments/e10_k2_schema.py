def perm_of_actT(M3):
    H = [[1, 0, 0, 0]] + [[0] + [int(M3[i][j]) for j in range(3)] for i in range(3)]
    out = []
    for m in range(4):
        for n in range(4):
            nz = [(k, H[n][k]) for k in range(4) if H[n][k] != 0]
            assert len(nz) == 1 and nz[0][1] in (1, -1)
            out.append((4 * m + nz[0][0], nz[0][1]))
    return tuple(out)


def compose(p, q):
    # (p o q)(w)[i] = sign_p(i) * (q w)[src_p(i)] = sign_p(i) * sign_q(src_p(i)) * w[src_q(src_p(i))]
    return tuple((q[s][0], sg * q[s][1]) for (s, sg) in p)


def apply_perm(p, w):
    return [sg * w[s] for (s, sg) in p]


