# Footer boundary check for automated GitHub text writes (section A.49 rule 2).
# Validated form: content, exactly one blank line, '---', the footer line, no trailing newline.
# GitHub stored a body sent with two blank lines before '---' with one (PR 1591, 2026-11-26),
# so the whole boundary is checked, not only the suffix.
F="\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
def footer_problem(body):
    if not body.endswith(F): return 'text does not end with the footer (no trailing newline allowed)'
    pre=body[:-len(F)]
    if pre=='' : return 'no content before the footer'
    if pre[-1].isspace(): return 'content before the footer ends with whitespace (it must be followed by exactly one blank line, then ---)'
    if body.count(F)!=1: return 'footer occurs more than once'
    return None
