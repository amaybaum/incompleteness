import json,sys,hashlib,re,subprocess
S='/tmp/claude-0/-home-user-incompleteness/8a0f23ba-ffa7-50df-a785-676e090e9917/scratchpad'
T='/tmp/claude-0/-home-user-incompleteness/8a0f23ba-ffa7-50df-a785-676e090e9917/tasks'
aid,target,label,head,reqdesc=sys.argv[1:6]
F="\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
best=None
for line in open(f'{T}/{aid}.output'):
    try:o=json.loads(line)
    except:continue
    c=o.get('message',{}).get('content')
    if isinstance(c,list):
        for b in c:
            if b.get('type')=='tool_use' and 'andback' in b.get('name',''): best=b['input']
t=next(v for v in best.values() if isinstance(v,str) and len(v)>1500)
open(f'{S}/rev/{label}-review.md','w').write(t)
h=hashlib.sha256(t.encode()).hexdigest()
pat=re.compile(re.escape(S)+r'(/[^\s`)]*)?')
n=len(pat.findall(t)); t2=pat.sub(lambda m:'<scratch>'+(m.group(1) or ''),t).rstrip()
red=f"{n} local scratch path(s) in the reviewer text are shortened to `<scratch>/...`" if n else "no redaction"
b=f'''**Independent review of {label} at `{head}`: reviewer text, verbatim.**

Reviewer: a Claude reviewer agent started with a fresh context, given only {reqdesc} and the commit; it wrote none of the reviewed work and made no GitHub or repository writes (owner decision at #1169 comment 7166418469). Redaction: {red}. SHA-256 of the unredacted review text: `{h}`. Writer responses, if any, are posted separately; acceptance is the owner's decision.

---- reviewer text begins ----

{t2}

---- reviewer text ends ----'''+F
open(f'{S}/w2/rev-{label}.md','w').write(b)
