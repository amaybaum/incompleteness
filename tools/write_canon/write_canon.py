#!/usr/bin/env python3
"""WRITE-CANON-1: check, and optionally post, one Issue comment on amaybaum/incompleteness.

  check SOURCE [--stored STORED] [--online]   writes nothing to GitHub
  post ISSUE SOURCE --receipt FILE            one gh api Issue-comment POST, verified afterwards

Three checks are reported separately: (a) integrity, (b) links, (c) constructs. A byte match
establishes (a) only. Exit codes: 0 ok, 1 check failed, 2 usage, 3 refused, 4 halted.
"""
import argparse, collections, fcntl, hashlib, json, os, pwd, re, shutil, stat, subprocess, sys, time, unicodedata
from pathlib import Path

REPO = "amaybaum/incompleteness"
F = "_Generated by [Claude Code](https://claude.ai/code)_"
TAIL = "\n\n\n---\n" + F
MAX_BODY = 65536
REPO_ROOT = Path(__file__).resolve().parents[2]
STATE_DIR = Path(pwd.getpwuid(os.getuid()).pw_dir) / ".write-canon"
SAFE_PATH = "/usr/local/bin:/usr/bin:/bin"
ALLOWED = {"bold", "bullet-list", "nested-list", "table", "code-span", "bare-blob-link",
           "issue-link", "bracket-code-literal", "paragraph"}
NOTE = ("A byte match establishes integrity (a) only; link validity (b) and the construct "
        "inventory (c) are separate checks and are not implied by it.")
POST_NOTE = ("Verification runs after the write: it detects a modified stored body, it does not "
             "prevent one from being stored.")


# ---------------------------------------------------------------- normalization
def core(s):
    """Strip trailing newlines, then one footer that is the whole body or follows a blank line."""
    s = s.rstrip("\n")
    if s == "---\n" + F:
        return ""
    if s.endswith("\n\n---\n" + F):
        s = s[: -(len(F) + 4)].rstrip("\n")
    return s


def normalize(s):
    return core(s) + TAIL


def char_problems(s):
    out = []
    for i, ch in enumerate(s):
        cat = unicodedata.category(ch)
        if (cat == "Cc" and ch not in "\n\t") or ((cat == "Zs" or ch.isspace()) and ch not in " \n\t"):
            out.append("forbidden control or non-ASCII whitespace character U+%04X at offset %d" % (ord(ch), i))
    return out[:5]


# ---------------------------------------------------------------- scanner
BLOB_FULL = re.compile(r"https://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)/blob/([0-9a-f]{40})/"
                       r"([A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*)", re.A)
ISSUE_LINK = re.compile(r"https://github\.com/amaybaum/incompleteness/(?:issues|pull)/[0-9]+"
                        r"(?:#issuecomment-[0-9]+)?", re.A)
BLOCK_START = re.compile(r"#{1,6}(\s|$)|>|[-*+](\s|$)|[0-9]{1,9}[.)](\s|$)|```|~~~|\||<|=+\s*$|"
                         r"-+\s*$|(\*\s*){3,}$|(_\s*){3,}$", re.A)
DELIM = re.compile(r"\|(\s*:?-+:?\s*\|)+")
ITEM = re.compile(r"((?:  )*)- (\S.*)")


class Scan:
    def __init__(self):
        self.inv, self.bad, self.links = collections.Counter(), [], []

    def no(self, ln, why):
        self.bad.append("line %d: %s" % (ln, why))


def code_spans(s):
    """Return (masked, spans) with equal-length backtick runs; None if any run is unmatched."""
    spans, i, n = [], 0, len(s)
    while i < n:
        if s[i] != "`":
            i += 1
            continue
        if i and s[i - 1] == "\\":
            return None, None                 # escaped backtick: not classified
        j = i
        while j < n and s[j] == "`":
            j += 1
        run, k = j - i, j
        while True:
            k = s.find("`" * run, k)
            if k < 0 or s[k - 1] == "\\":
                return None, None
            e = k + run
            if (k == 0 or s[k - 1] != "`") and (e == n or s[e] != "`"):
                break
            while k < n and s[k] == "`":
                k += 1
        spans.append((i, e, s[j:k]))
        i = e
    m = list(s)
    for a, b, _ in spans:
        m[a:b] = "\0" * (b - a)
    return "".join(m), spans


def inline(sc, ln, s, cell=False):
    m, spans = code_spans(s)
    if m is None:
        return sc.no(ln, "unmatched backtick run")
    sc.inv["code-span"] += len(spans)
    if cell and any("|" in c for _, _, c in spans):
        sc.no(ln, "pipe inside a code span in a table row")
    starts = {a: (b, c) for a, b, c in spans}
    m = list(m)

    def blank(a, b):
        m[a:b] = "\1" * (b - a)

    for mt in re.finditer(r"\[([^\[\]\0]*)\]\(", "".join(m)):
        a, p = mt.start(), mt.end()
        text = mt.group(1)
        if p in starts:                       # [text]( + code span + ) : the #1548 literal form
            b, c = starts[p]
            if (c[:1] == " " and c[1:2] not in "\"'(< " and b < len(s) and s[b] == ")"
                    and text.strip() and "http" not in text):
                sc.inv["bracket-code-literal"] += 1
                blank(a, a + 1), blank(p - 2, p), blank(b, b + 1)
            continue
        e = s.find(")", p)
        dest = s[p:e] if e >= 0 else ""
        if e < 0 or not dest or any(ch in dest for ch in " \t()<>`\0") or not text.strip() or "http" in text:
            continue
        if "/blob/" in dest:
            sc.no(ln, "blob URL as an inline-link destination: " + dest)
            sc.inv["inline-blob-link"] += 1
        elif ISSUE_LINK.fullmatch(dest):
            sc.inv["issue-link"] += 1
            num = re.match(r"#([0-9]+)", text.strip())
            if num and num.group(1) != re.search(r"/(?:issues|pull)/([0-9]+)", dest).group(1):
                sc.no(ln, "link text %s names a different number than its target" % num.group(0))
        else:
            sc.inv["inline-link-other"] += 1
        blank(a, a + 1), blank(p - 2, e + 1)
    t = "".join(m)
    for mt in re.finditer(r"(?i)(?:https?|ftp)://|www\.", t):
        a = mt.start()
        if a > 0 and t[a - 1] not in " \t":
            sc.no(ln, "URL not preceded by whitespace")
            continue
        e = a
        while e < len(t) and t[e] not in " \t<":        # GFM ends an autolink only here
            e += 1
        url = t[a:e]
        if url[-1] in ".,:;!?*_~'\")" or any(ch in url for ch in "()<>\0\1[]"):
            sc.no(ln, "URL with ambiguous boundary: " + url)
        elif BLOB_FULL.fullmatch(url) and not {".", ".."} & set(url.split("/")):
            sc.inv["bare-blob-link"] += 1
            sc.links.append(url)
        elif "/blob/" in url:
            sc.no(ln, "shortened or malformed blob URL outside code: " + url)
        else:
            sc.inv["bare-url-other"] += 1
        blank(a, e)
    t = "".join(m)
    for mt in re.finditer(r"\*\*(\S(?:[^*]*\S)?)\*\*", t):
        a, e = mt.span()
        if (a == 0 or t[a - 1] in " (") and (e == len(t) or t[e] in " .,;:)"):
            sc.inv["bold"] += 1
            blank(a, a + 2), blank(e - 2, e)
    t = "".join(m)
    checks = [(r"\\[!-/:-@\[-`{-~]|\\$", "backslash escape or hard break"), (r"<", "raw HTML or autolink"),
              (r"&#?[A-Za-z0-9]+;", "HTML entity"), (r"~", "tilde (strikethrough)"), (r"!\[", "image"),
              (r"@", "mention or e-mail autolink"), (r":[a-z_+-][a-z0-9_+-]*:", "emoji shortcode"),
              (r"\*", "emphasis or stray asterisk"), (r"(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])", "underscore emphasis"),
              (r"[\[\]]", "bracket outside a supported link (reference link, footnote or literal)"),
              (r"\|", "stray pipe outside a table"), (r"\$", "math delimiter"),
              (r"://", "URL scheme outside a recognised URL"),
              (r"(?<![A-Za-z0-9_./-])[A-Za-z0-9-]+/[A-Za-z0-9_.-]+[#@]", "cross-repository reference"),
              (r"(?i)\bgh-[0-9]+", "GH- reference")]
    for pat, why in checks:
        if re.search(pat, t):
            sc.no(ln, why)
    if s != s.rstrip(" \t"):
        sc.no(ln, "trailing whitespace")
    for ch in s:
        if unicodedata.category(ch) in ("Cf", "Zl", "Zp", "Co", "Cs", "Cn"):
            sc.no(ln, "invisible or unassigned character U+%04X" % ord(ch))
            break


def scan(text):
    sc, lines, i, depth = Scan(), text.split("\n"), 0, None
    prev_blank = True
    while i < len(lines):
        s, ln = lines[i], i + 1
        if s.strip() == "":
            if s:
                sc.no(ln, "whitespace-only line")
            prev_blank, depth, i = True, None, i + 1
            continue
        fence = re.match(r"(`{3,}|~{3,})", s)
        if fence:
            run = fence.group(1)
            j = i + 1
            while j < len(lines) and not re.fullmatch(re.escape(run[0]) * len(run) + run[0] + "*", lines[j]):
                j += 1
            sc.no(ln, "fenced code block" if j < len(lines) else "unclosed code fence")
            sc.inv["fenced-code"] += 1
            prev_blank, depth, i = False, None, j + 1
            continue
        item = ITEM.fullmatch(s)
        if item:
            d = len(item.group(1)) // 2
            if (depth is None and (d != 0)) or (depth is not None and d > depth + 1):
                sc.no(ln, "list indentation jump")
            if BLOCK_START.match(item.group(2)):
                sc.no(ln, "block construct inside a list item")
            sc.inv["nested-list" if d else "bullet-list"] += 1
            depth = d
            inline(sc, ln, item.group(2))
            prev_blank, i = False, i + 1
            continue
        if depth is not None:
            sc.no(ln, "list continuation line")
        depth = None
        if s[0] in " \t":
            sc.no(ln, "leading whitespace (indented code or continuation)")
        elif s.startswith("|"):
            if prev_blank and i + 1 < len(lines) and DELIM.fullmatch(lines[i + 1]):
                ncols = lines[i + 1].count("|") - 1
                sc.inv["table"] += 1
                j = i
                while j < len(lines) and lines[j].strip():
                    row = lines[j]
                    if j != i + 1:
                        table_row(sc, j + 1, row, ncols)
                    j += 1
                prev_blank, i = False, j
                continue
            sc.no(ln, "pipe-led line that is not a table")
        elif BLOCK_START.match(s):
            sc.no(ln, "unsupported block construct: " + s[:20])
        else:
            sc.inv["paragraph"] += 1
            inline(sc, ln, s)
        prev_blank, i = False, i + 1
    for k in sc.inv:
        if k not in ALLOWED:
            sc.bad.append("construct not on the tested allow-list: " + k)
    return sc


def table_row(sc, ln, row, ncols):
    m, spans = code_spans(row)
    if m is None or not (row.startswith("|") and row.endswith("|")) or row.endswith("\\|"):
        return sc.no(ln, "malformed table row")
    if any("|" in c for _, _, c in spans):
        return sc.no(ln, "pipe inside a code span in a table row")
    cells = row[1:-1].split("|")
    if len(cells) != ncols:
        return sc.no(ln, "table row has %d cells, header has %d" % (len(cells), ncols))
    for c in cells:
        if c.strip() and BLOCK_START.match(c.strip()):
            sc.no(ln, "block construct inside a table cell")
        if c.strip():
            inline(sc, ln, c.strip(), cell=True)


# ---------------------------------------------------------------- links
def executables():
    return {k: shutil.which(k, path=SAFE_PATH) for k in ("gh", "git")}


def _exec(argv, env, timeout):
    exe = shutil.which(argv[0], path=SAFE_PATH)
    if not exe:
        raise OSError("%s not found on %s" % (argv[0], SAFE_PATH))
    p = subprocess.run([exe] + argv[1:], capture_output=True, encoding="utf-8", timeout=timeout, env=env)
    return p.returncode, p.stdout, p.stderr


def default_runner(argv):
    env = {k: v for k, v in os.environ.items() if k not in ("GH_HOST", "GH_REPO")}
    return _exec(argv, env, 120)


def git(*args):
    """Read-only git in the repository this tool lives in, with no GIT_* from the environment."""
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_NO_REPLACE_OBJECTS="1", GIT_CONFIG_NOSYSTEM="1", GIT_TERMINAL_PROMPT="0")
    rc, gd, _ = _exec(["git", "-C", str(REPO_ROOT), "rev-parse", "--absolute-git-dir"], env, 30)
    if rc != 0:
        return None
    env.update(GIT_DIR=gd.strip(), GIT_WORK_TREE=str(REPO_ROOT))
    rc, out, _ = _exec(["git"] + list(args), env, 30)
    return out.strip() if rc == 0 else None


def local_status(sha, path):
    if git("cat-file", "-t", sha) != "commit" or git("cat-file", "-t", "%s:%s" % (sha, path)) != "blob":
        return "invalid"
    if not git("for-each-ref", "--contains", sha, "--format=%(refname)", "refs/remotes/origin/"):
        return "unverified (commit not reachable from a local origin remote-tracking ref)"
    return "verified-local"


def check_links(urls, online=False, runner=default_runner):
    out = []
    for url in urls:
        o, r, sha, path = BLOB_FULL.fullmatch(url).groups()
        if "%s/%s" % (o, r) == REPO and not online:
            status = local_status(sha, path)
        elif online:                          # GitHub itself settles existence, for any repository
            try:
                rc, so, _ = gh(runner, ["gh", "api", "repos/%s/%s/contents/%s?ref=%s" % (o, r, path, sha)])
                d = json.loads(so) if rc == 0 else None
            except Exception:
                rc, d = None, None
            if rc != 0 or d is None:              # failed call, gh error or non-JSON: nothing settled
                status = "unverified (GitHub did not answer the contents request)"
            else:
                status = "verified-online" if isinstance(d, dict) and d.get("type") == "file" else "invalid"
        else:
            status = "unverified (other repository; offline check cannot confirm it)"
        out.append({"url": url, "repository": "%s/%s" % (o, r), "status": status})
    return out


# ---------------------------------------------------------------- check
def sha(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def check(src, stored=None, online=False, runner=default_runner):
    integ = char_problems(src)
    if not core(src).strip():
        integ.append("empty body")
    exp = normalize(src)
    if len(exp) > MAX_BODY:
        integ.append("normalized body longer than %d characters" % MAX_BODY)
    a = {"source_sha256": sha(src), "expected_sha256": sha(exp),
         "core_is_prefix_of_source": src.startswith(core(src))}
    sc = scan(core(src))
    links = check_links(sc.links, online, runner) if not integ else []
    lprob = [l["url"] + ": " + l["status"] for l in links if not l["status"].startswith("verified")]
    lprob += [b for b in sc.bad if "blob URL" in b] + (["links not checked: integrity failed"] if integ else [])
    if stored is not None:
        integ += ["stored: " + p for p in char_problems(stored)]
        a["stored_sha256"] = sha(stored)
        a["stored_matches_expected"] = stored.encode("utf-8", "surrogatepass") == exp.encode("utf-8", "surrogatepass")
        if not a["stored_matches_expected"]:
            integ.append("stored body differs from the expected normalized body")
        st = scan(core(stored))
        if st.links != sc.links:
            lprob.append("blob links outside code differ between source and stored body")
    a.update(ok=not integ, problems=integ)
    cbad = [b for b in sc.bad if "blob URL" not in b]
    return {"ok": not integ and not lprob and not cbad, "integrity": a,
            "links": {"ok": not lprob, "links": links, "problems": lprob},
            "constructs": {"ok": not cbad, "inventory": dict(sorted(sc.inv.items())), "unsupported": cbad},
            "note": NOTE}


# ---------------------------------------------------------------- filesystem
def read_nofollow(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise OSError("not a regular file: %s" % path)
        with os.fdopen(fd, "rb", closefd=False) as f:
            return f.read().decode("utf-8")
    finally:
        os.close(fd)


def write_atomic(path, data, exclusive=False):
    """Write via a temporary file; exclusive=True never replaces an existing path."""
    path = Path(path)
    if path.is_symlink():
        raise OSError("refusing symlink: %s" % path)
    tmp = path.with_name(".%s.%d.tmp" % (path.name, os.getpid()))
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(data.encode("utf-8"))
        f.flush()
        os.fsync(f.fileno())
    if not exclusive:
        return os.replace(tmp, path)
    try:
        os.link(tmp, path)
    finally:
        os.unlink(tmp)


def create_excl(path, text):
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except FileExistsError:
        return False
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def state_paths(state_dir):
    os.makedirs(state_dir, mode=0o700, exist_ok=True)
    st = os.lstat(state_dir)
    if not stat.S_ISDIR(st.st_mode) or st.st_uid != os.getuid() or st.st_mode & 0o077:
        raise OSError("state directory is not a private directory owned by this user: %s" % state_dir)
    return {k: Path(state_dir) / k for k in ("lock", "HALT", "PENDING", "submit.md")}


# ---------------------------------------------------------------- post
def gh(runner, argv):
    """The only route to gh. Anything but these read or Issue-comment commands raises."""
    r = re.escape(REPO)
    ok = (len(argv) == 3 and argv[:2] == ["gh", "api"] and (
              re.fullmatch(r"repos/%s/issues/[1-9][0-9]*" % r, argv[2], re.A)
              or re.fullmatch(r"repos/%s/issues/comments/[1-9][0-9]*" % r, argv[2], re.A)
              or re.fullmatch(r"repos/%s/issues/[1-9][0-9]*/comments\?since=[0-9TZ:-]{20}&per_page=100" % r,
                              argv[2], re.A)
              or re.fullmatch(r"repos/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/contents/[A-Za-z0-9_./-]+\?ref=[0-9a-f]{40}",
                              argv[2], re.A))) or (
         len(argv) == 7 and argv[:4] == ["gh", "api", "-X", "POST"] and argv[5] == "-F"
         and re.fullmatch(r"repos/%s/issues/[1-9][0-9]*/comments" % r, argv[4], re.A)
         and argv[6].startswith("body=@") and argv[6].endswith("/submit.md"))
    if not ok:
        raise ValueError("command not permitted: %r" % (argv,))
    return runner(argv)


def post(issue, source, receipt, runner=default_runner, state_dir=STATE_DIR):
    if not re.fullmatch(r"[1-9][0-9]{0,8}", issue, re.A):
        return 2, "issue number must be a positive integer"
    try:
        p = state_paths(state_dir)
        lk = os.open(p["lock"], os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    except OSError as e:
        return 3, "unsafe state directory: %s" % e
    try:
        fcntl.flock(lk, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        os.close(lk)
        return 3, "another post holds the lock"
    try:
        return _post(issue, source, Path(receipt), runner, p)
    finally:
        os.close(lk)


def _post(issue, source, receipt, runner, p):
    for k in ("HALT", "PENDING"):
        if os.path.lexists(p[k]):
            return 3, "%s marker present at %s; a human must clear it" % (k, p[k])
    if os.path.lexists(receipt):
        return 3, "receipt path already exists: %s" % receipt
    try:
        src = read_nofollow(source)
    except (OSError, UnicodeDecodeError) as e:
        return 3, "cannot read source safely: %s" % e
    rep = check(src, runner=runner)
    if not rep["ok"] or any(l["status"] != "verified-local" for l in rep["links"]["links"]):
        return 1, "check failed; nothing posted\n" + json.dumps(rep, indent=1, ensure_ascii=False)
    try:
        rc, so, _ = gh(runner, ["gh", "api", "repos/%s/issues/%s" % (REPO, issue)])
        d = json.loads(so) if rc == 0 else None
    except Exception:
        d = None
    if not isinstance(d, dict) or d.get("number") != int(issue) or "pull_request" in d:
        return 3, "issue %s is not a readable Issue (pull requests are refused)" % issue
    exp = normalize(src)
    since = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(time.time() - 7 * 86400))
    try:
        rc, so, _ = gh(runner, ["gh", "api", "repos/%s/issues/%s/comments?since=%s&per_page=100" % (REPO, issue, since)])
        recent = json.loads(so) if rc == 0 else None
    except Exception:
        recent = None
    if not isinstance(recent, list) or len(recent) >= 100:
        return 3, "cannot list the Issue's recent comments completely; refusing"
    if any(isinstance(c, dict) and c.get("body") == exp for c in recent):
        return 3, "an identical comment was posted in the last seven days; refusing"
    write_atomic(p["submit.md"], src)
    rec = {"issue": int(issue), "source_sha256": sha(src), "expected_sha256": sha(exp), "check": rep,
           "note": POST_NOTE, "executables": executables(),
           "time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    if not create_excl(p["PENDING"], json.dumps(rec["source_sha256"]) + "\n"):
        return 3, "pending marker appeared; refusing"
    why = verify_post(issue, src, exp, rec, runner, p)
    if why:
        create_excl(p["HALT"], why + "\n")
        try:
            write_atomic(receipt, json.dumps(rec, indent=1, ensure_ascii=False) + "\n", exclusive=True)
        except OSError:
            pass
        return 4, "HALTED, no retry: " + why
    try:
        write_atomic(receipt, json.dumps(rec, indent=1, ensure_ascii=False) + "\n", exclusive=True)
    except OSError as e:
        create_excl(p["HALT"], "receipt not written: %s\n" % e)
        return 4, "HALTED: posted and verified, but the receipt was not written: %s" % e
    os.unlink(p["PENDING"])
    return 0, "posted and verified: comment %s" % rec["comment_id"]


def verify_post(issue, src, exp, rec, runner, p):
    """Return a halt reason, or '' when the stored comment is exactly as expected."""
    try:
        rc, so, _ = gh(runner, ["gh", "api", "-X", "POST", "repos/%s/issues/%s/comments" % (REPO, issue),
                                "-F", "body=@%s" % p["submit.md"]])
        r = json.loads(so)
        cid = r["id"]
        if rc != 0 or type(cid) is not int or cid <= 0:
            return "ambiguous POST result (rc=%s)" % rc
        rec["comment_id"] = cid
        rc, so, _ = gh(runner, ["gh", "api", "repos/%s/issues/comments/%d" % (REPO, cid)])
        g = json.loads(so)
        stored = g["body"]
        if rc != 0 or not isinstance(stored, str):
            return "ambiguous verification response (rc=%s)" % rc
    except Exception as e:  # network error, timeout, non-JSON, missing field: the comment may exist
        return "no usable response after submission: %s: %s" % (type(e).__name__, e)
    v = check(src, stored=stored, runner=runner)
    rec.update(stored_sha256=sha(stored), verification=v,
               created_equals_updated=g.get("created_at") is not None and g.get("created_at") == g.get("updated_at"),
               issue_url_matches=str(g.get("issue_url", "")).endswith("/repos/%s/issues/%s" % (REPO, issue)),
               id_matches=g.get("id") == cid)
    rec["match"] = v["integrity"].get("stored_matches_expected") is True
    rec["links_survived"] = v["links"]["ok"]
    bad = [k for k in ("match", "links_survived", "created_equals_updated", "issue_url_matches", "id_matches")
           if not rec[k]]
    return ("verification failed: " + ", ".join(bad)) if bad else ""


# ---------------------------------------------------------------- cli
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="mode", required=True)
    c = sub.add_parser("check")
    c.add_argument("source")
    c.add_argument("--stored")
    c.add_argument("--online", action="store_true")
    q = sub.add_parser("post")
    q.add_argument("issue")
    q.add_argument("source")
    q.add_argument("--receipt", required=True)
    a = ap.parse_args(argv)
    if a.mode == "check":
        try:
            src = read_nofollow(a.source)
            stored = read_nofollow(a.stored) if a.stored else None
        except (OSError, UnicodeDecodeError) as e:
            print("cannot read: %s" % e, file=sys.stderr)
            return 1
        rep = check(src, stored, a.online)
        print(json.dumps(rep, indent=1, ensure_ascii=False))
        return 0 if rep["ok"] else 1
    code, msg = post(a.issue, a.source, a.receipt)
    print(msg, file=sys.stderr if code else sys.stdout)
    return code


if __name__ == "__main__":
    sys.exit(main())
