# ---------------------------------------------------------------- Gaussian rationals
def gadd(x, y): return (x[0] + y[0], x[1] + y[1])
def gsub(x, y): return (x[0] - y[0], x[1] - y[1])
def gmul(x, y): return (x[0]*y[0] - x[1]*y[1], x[0]*y[1] + x[1]*y[0])
def gscale(c, x): return (c * x[0], c * x[1])
GZ, GO = (F(0), F(0)), (F(1), F(0))

# ---------------------------------------------------------------- truncated eps-polynomials
def padd(a, b): return [gadd(x, y) for x, y in zip(a, b)]
def pmul(a, b):
    out = [GZ] * DEG
    for i, x in enumerate(a):
        if x == GZ:
            continue
        for j, y in enumerate(b):
            if i + j < DEG and y != GZ:
                out[i + j] = gadd(out[i + j], gmul(x, y))
    return out
def pscale(c, a): return [gscale(c, x) for x in a]
def pconst(g): return [g] + [GZ] * (DEG - 1)
PZ, PO = pconst(GZ), pconst(GO)
def pzero(a): return all(x == GZ for x in a)

def meye(n): return [[PO if r == c else PZ for c in range(n)] for r in range(n)]
def madd(A, B): return [[padd(x, y) for x, y in zip(ra, rb)] for ra, rb in zip(A, B)]
def mscale(c, A): return [[pscale(c, x) for x in row] for row in A]
def mzero(A): return all(pzero(p) for row in A for p in row)
def mmul(A, B):
    n = len(A)
    out = [[PZ] * n for _ in range(n)]
    for r in range(n):
        for c in range(n):
            tot = PZ
            for k in range(n):
                tot = padd(tot, pmul(A[r][k], B[k][c]))
            out[r][c] = tot
    return out
def mexp(A):
    """exp(A) truncated at eps^DEG. A must have zero constant term."""
    assert all(p[0] == GZ for row in A for p in row), 'A must be O(eps)'
    n = len(A)
    out, term = meye(n), meye(n)
    for k in range(1, DEG + 1):
        term = mscale(F(1, k), mmul(term, A))
        out = madd(out, term)
    return out

# su(2): the anti-Hermitian generators i*sigma_a, with Gaussian-INTEGER entries
ISIG = ([[GZ, (F(0), F(1))], [(F(0), F(1)), GZ]],
        [[GZ, (F(1), F(0))], [(F(-1), F(0)), GZ]],
        [[(F(0), F(1)), GZ], [GZ, (F(0), F(-1))]])

def lie_eps(vec):
    """eps * sum_a vec[a] (i sigma_a): the induced link exponent, linear in the matter difference."""
    M = [[PZ] * 2 for _ in range(2)]
    for a, v in enumerate(vec):
        for r in range(2):
            for c in range(2):
                p = [GZ] * DEG
                p[1] = gscale(F(v), ISIG[a][r][c])      # the eps^1 slot
                M[r][c] = padd(M[r][c], p)
    return M

