print("IS5  b405 §2's uniqueness lemma, both halves and the reducible countercontrol")
def commutant_dim(gens, n):
    """dim_C { X : X g = g X for all g }, by exact rank over Q(i) treated as 2n^2 real unknowns."""
    rows = []
    for g in gens:
        for r in range(n):
            for c in range(n):
                # (Xg - gX)[r][c] = sum_k X[r][k] g[k][c] - g[r][k] X[k][c]
                re_row = [F(0)] * (2 * n * n); im_row = [F(0)] * (2 * n * n)
                def bump(i, j, coef):
                    idx = 2 * (i * n + j)
                    re_row[idx] += coef[0]; re_row[idx + 1] -= coef[1]
                    im_row[idx] += coef[1]; im_row[idx + 1] += coef[0]
                for k in range(n):
                    bump(r, k, g[k][c])
                    bump(k, c, (-g[r][k][0], -g[r][k][1]))
                rows.append(re_row); rows.append(im_row)
    # exact rank over Q
    m = [r[:] for r in rows]; rank = 0
    for col in range(2 * n * n):
        piv = next((i for i in range(rank, len(m)) if m[i][col] != 0), None)
        if piv is None:
            continue
        m[rank], m[piv] = m[piv], m[rank]
        pv = m[rank][col]
        m[rank] = [x / pv for x in m[rank]]
        for i in range(len(m)):
            if i != rank and m[i][col] != 0:
                f = m[i][col]
                m[i] = [x - f * y for x, y in zip(m[i], m[rank])]
        rank += 1
    return (2 * n * n - rank) // 2                     # complex dimension

