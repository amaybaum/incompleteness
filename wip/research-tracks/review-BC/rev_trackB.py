import itertools
import sys
from fractions import Fraction as Fr

import sympy as sp

OUT = []


def rec(ok, cid, text):
    OUT.append((bool(ok), cid, text))


I = sp.I
t = sp.symbols('t', real=True)
P0 = sp.Matrix([[1, 0], [0, 0]])
P1 = sp.Matrix([[0, 0], [0, 1]])
X = sp.Matrix([[0, 1], [1, 0]])
Y = sp.Matrix([[0, -I], [I, 0]])
Z = sp.Matrix([[1, 0], [0, -1]])
E2 = sp.eye(2)
CYC = sp.Matrix([[(1 - I) / 2, (-1 - I) / 2], [(1 - I) / 2, (1 + I) / 2]])  # EqvK2Converse.lean:106
ROTZ = sp.Matrix([[1, 0], [0, sp.exp(I * t)]])
RY = sp.Matrix([[sp.Rational(3, 5), -sp.Rational(4, 5)], [sp.Rational(4, 5), sp.Rational(3, 5)]])


def kron_list(ms):
    out = ms[0]
    for m in ms[1:]:
        out = sp.kronecker_product(out, m)
    return out


def local(g, j, k):
    return kron_list([g if i == j else E2 for i in range(k)])


def cnot(c, tg, k):
    n = 2 ** k
    M = sp.zeros(n, n)
    for idx in range(n):
        bits = [(idx >> (k - 1 - i)) & 1 for i in range(k)]
        if bits[c]:
            bits[tg] ^= 1
        M[sum(b << (k - 1 - i) for i, b in enumerate(bits)), idx] = 1
    return M


def gens(k):
    G = {}
    for i, j in itertools.combinations(range(k), 2):
        G[f"CNOT{i}{j}"] = cnot(i, j, k)
    for j in range(1, k):
        G[f"ROTZ{j}(t)"] = local(ROTZ, j, k)
        G[f"CYC{j}"] = local(CYC, j, k)
    return G


def check_lemma1():
    for k in (3, 4):
        Pi0 = local(P0, 0, k)
        G = gens(k)
        ok = all(sp.simplify(U * Pi0 - Pi0 * U) == sp.zeros(2 ** k, 2 ** k) for U in G.values())
        ok &= all(sp.simplify(U.H * U - sp.eye(2 ** k)) == sp.zeros(2 ** k, 2 ** k) for U in G.values())
        # cyclic map acts on Bloch vectors as x -> y -> z -> x (kernel cycEquiv (x,y,z) |-> (z,x,y))
        ok &= (sp.expand(CYC * X * CYC.H) == Y) and (sp.expand(CYC * Y * CYC.H) == Z) and (sp.expand(CYC * Z * CYC.H) == X)
        neg = {"CNOT10": cnot(1, 0, k), "CYC0": local(CYC, 0, k), "RY0": local(RY, 0, k)}
        negok = all(sp.simplify(U * Pi0 - Pi0 * U) != sp.zeros(2 ** k, 2 ** k) for U in neg.values())
        rec(ok, f"L1-k{k}", f"k={k}: all {len(G)} #829 generators (symbolic angle t) are unitary and commute with Pi0")
        rec(negok, f"L1NEG-k{k}", f"k={k}: CNOT(1->0), cycMat on token 0, a y-rotation on token 0 do not commute with Pi0")


# ---------------------------------------------------------------- exact Lie algebra dimension
# Matrices are dicts {(row, col): (re, im)} over the integers.  Seeds i*P_j and CNOTs are monomial
# matrices, so every product below is exact integer arithmetic.  Independence is tested mod a prime p:
# vectors independent mod p are independent over Q (an integer relation with gcd 1 survives mod p),
# so the count is a certified LOWER bound for the Q-dimension.  The UPPER bound is structural: every
# seed is anti-Hermitian, token-0 block-diagonal with traceless blocks, and that subalgebra
# su(n/2)+su(n/2) is closed under brackets and under Ad_CNOT(i<j) (CNOTs are token-0 block-diagonal).
PR = 2_147_483_647


def imul(z, ph):
    re, im = z
    return {0: (re, im), 1: (-im, re), 2: (-re, -im), 3: (im, -re)}[ph]


def monomial_pauli(P, j, k):
    """i * (I (x) .. P_j .. (x) I) as (perm, phase-exponent) with M[perm[c], c] = i**ph[c]."""
    n = 2 ** k
    perm, ph = [0] * n, [0] * n
    for c in range(n):
        bit = (c >> (k - 1 - j)) & 1
        if P == 'X':
            r, e = c ^ (1 << (k - 1 - j)), 1           # i * 1
        elif P == 'Y':
            r = c ^ (1 << (k - 1 - j))
            e = 2 if bit == 0 else 0                    # Y|0>=i|1>, Y|1>=-i|0>; times i: -1, +1
        else:
            r, e = c, (1 if bit == 0 else 3)            # i*Z: +i, -i
        perm[c], ph[c] = r, e
    return perm, ph


def monomial_cnot(c0, t0, k):
    n = 2 ** k
    perm = []
    for c in range(n):
        if (c >> (k - 1 - c0)) & 1:
            perm.append(c ^ (1 << (k - 1 - t0)))
        else:
            perm.append(c)
    return perm, [0] * n


def mono_dense(M, n):
    perm, ph = M
    return {(perm[c], c): imul((1, 0), ph[c]) for c in range(n)}


def left(M, A):            # M A
    perm, ph = M
    return {(perm[r], c): imul(z, ph[r]) for (r, c), z in A.items()}


def right(A, M):           # A M : (A M)[a, c] = A[a, perm[c]] * i**ph[c]
    perm, ph = M
    inv = {perm[c]: c for c in range(len(perm))}
    return {(a, inv[b]): imul(z, ph[inv[b]]) for (a, b), z in A.items()}


def dag_mono(M):
    perm, ph = M
    n = len(perm)
    iperm, iph = [0] * n, [0] * n
    for c in range(n):
        iperm[perm[c]] = c
        iph[perm[c]] = (-ph[c]) % 4
    return iperm, iph


def msub(A, B):
    out = dict(A)
    for key, (u, v) in B.items():
        x, y = out.get(key, (0, 0))
        out[key] = (x - u, y - v)
    return {k2: z for k2, z in out.items() if z != (0, 0)}


def bracket_seed(S, A):    # [S, A] = S A - A S
    return msub(left(S, A), right(A, S))


def conj_mono(M, A):       # M A M^dag
    return right(left(M, A), dag_mono(M))


class ModSpan:
    def __init__(self, n):
        self.n = n
        self.piv = {}      # pivot index -> normalized row (list mod p)

    def add(self, A):
        v = [0] * (2 * self.n * self.n)
        for (r, c), (x, y) in A.items():
            v[2 * (r * self.n + c)] = x % PR
            v[2 * (r * self.n + c) + 1] = y % PR
        for i in range(len(v)):
            if v[i]:
                if i in self.piv:
                    row = self.piv[i]
                    f = v[i]
                    v = [(a - f * b) % PR for a, b in zip(v, row)]
                else:
                    invf = pow(v[i], PR - 2, PR)
                    self.piv[i] = [(a * invf) % PR for a in v]
                    return True
        return False


def structural_ok(A, n):
    h = n // 2
    if any((r < h) != (c < h) for (r, c) in A):
        return False
    for blk in (range(h), range(h, n)):
        if (sum(A.get((r, r), (0, 0))[0] for r in blk), sum(A.get((r, r), (0, 0))[1] for r in blk)) != (0, 0):
            return False
    for (r, c), (x, y) in A.items():          # anti-Hermitian: A[c,r] = -conj(A[r,c])
        if A.get((c, r), (0, 0)) != (-x, y):
            return False
    return True


def lie_dim(k, use_cnots=True):
    n = 2 ** k
    seeds = [monomial_pauli(P, j, k) for j in range(1, k) for P in 'XYZ']
    cnots = [monomial_cnot(i, j, k) for i, j in itertools.combinations(range(k), 2)] if use_cnots else []
    span = ModSpan(n)
    count = 0
    struct = True
    queue = [mono_dense(S, n) for S in seeds]
    while queue:
        A = queue.pop()
        if not A:
            continue
        if span.add(A):
            count += 1
            struct &= structural_ok(A, n)
            queue.extend(bracket_seed(S, A) for S in seeds)
            queue.extend(conj_mono(C, A) for C in cnots)
    return count, struct


def check_lie():
    for k in (3, 4):
        d, struct = lie_dim(k)
        target = 2 * ((2 ** (k - 1)) ** 2 - 1)
        rec(d == target and struct, f"LIE-k{k}",
            f"k={k}: smallest space containing i{{X,Y,Z}}_j (j>=1), closed under ad_seed and Ad_CNOT(i<j), has dimension {d} "
            f"(mod-p lower bound) and lies in su({2**(k-1)})+su({2**(k-1)}) of dimension {target}: equality, so SU x SU (token-0 blocks) is inside G")
    d0, _ = lie_dim(3, use_cnots=False)
    rec(d0 == 6, "LIE-NEG", f"control: without CNOTs the generated algebra has dimension {d0} (local su(2)+su(2) on tokens 1, 2)")


# ---------------------------------------------------------------- countermodel
def check_cm():
    lam = sp.Rational(626, 625)
    w = sp.Matrix([sp.Rational(3, 5), sp.Rational(4, 5)])
    S = sp.eye(2) - lam * w * w.T
    H = sp.kronecker_product(S, sp.eye(4))
    xs = sp.kronecker_product(sp.Matrix([3, 4]), sp.Matrix([1, 0, 0, 0]))
    v = (xs.T * H * xs)[0]
    ev = sorted(S.eigenvals().keys())
    rec(v == sp.Rational(-1, 25) and ev == [sp.Rational(-1, 625), 1], "CM-a",
        f"x*^T H x* = {v} on (3,4)(x)|00>; eig(S) = {ev}")
    r = sp.symbols('r', real=True)  # ray (1, r), r = n/m
    f = sp.expand((sp.Matrix([1, r]).T * S * sp.Matrix([1, r]))[0])
    roots = sorted(sp.solve(sp.Eq(f, 0), r), key=lambda z: float(z))
    lo, hi = roots
    lead = sp.Poly(f, r).LC()
    # negative exactly on (lo, hi) because the leading coefficient is positive
    ok = lead > 0 and sp.Rational(6, 5) < lo < sp.Rational(4, 3) < hi < sp.Rational(3, 2)
    F = [(1, 0), (0, 1), (1, 1), (1, 2), (2, 1), (1, 3), (3, 1)]
    vals = [sp.Rational(m * m) * S[0, 0] + 2 * m * n * S[0, 1] + n * n * S[1, 1] for m, n in F]
    ok &= all(val > 0 for val in vals)
    ok &= all(not (lo < sp.Rational(n, m) < hi) for m, n in F if m != 0)
    gapvals = [m * m * S[0, 0] + 2 * m * n * S[0, 1] + n * n * S[1, 1] for m, n in ((5, 6), (2, 3))]
    ok &= all(gv > 0 for gv in gapvals)
    rec(ok, "CM-b",
        f"S-form on ray (1,r) is {f}; negative exactly for r in ({lo}, {hi}) ~ ({float(lo):.6f}, {float(hi):.6f}), "
        f"strictly inside the gap (6/5, 3/2); F values {vals}; gap endpoint values {gapvals}")
    # symbolic block identity for generic block-diagonal U = diag(U0, U1)
    a = sp.symbols('a0:16')
    b = sp.symbols('b0:16')
    U0 = sp.Matrix(4, 4, a)
    U1 = sp.Matrix(4, 4, b)
    U = sp.diag(U0, U1)
    s00, s01, s11 = sp.symbols('s00 s01 s11')
    Ss = sp.Matrix([[s00, s01], [s01, s11]])
    Hs = sp.kronecker_product(Ss, sp.eye(4))
    lhs = U * Hs * U.T  # transpose stands in for dagger: identity is polynomial in entries
    rhs = sp.Matrix(sp.BlockMatrix([[s00 * U0 * U0.T, s01 * U0 * U1.T], [s01 * U1 * U0.T, s11 * U1 * U1.T]]))
    rec(sp.expand(lhs - rhs) == sp.zeros(8, 8), "CM-c",
        "generic block-diagonal U: U (S(x)I) U^* = [[S00 U0U0^*, S01 U0U1^*],[S01 U1U0^*, S11 U1U1^*]] (polynomial identity)")


