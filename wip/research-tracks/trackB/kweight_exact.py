#!/usr/bin/env python3
"""Track B exact checks: which joint tests the k-token reconstruction (#829) consumes.

Standard library only; arithmetic in Q(i) with fractions.Fraction.  Nothing is imported from
the kernel, from #829's design checker or from the thread-A checker.  Run:
    python3 -I kweight_exact.py

Claim under test (written argument in report.md, section B2):
  Let G_k be the group generated by #829's gates (CNOT(i->j), i<j; third-axis rotations and the
  cyclic map on tokens j>0).  For a set T of rank-one product tests, validity on T can replace
  the maxCone bound in #829's theorem (all other hypotheses unchanged) iff the token-0 weights
  q(t) = |<0|_0 t|^2 / |t|^2 of T are dense in [0,1].  The mechanism of the 'only if' half is
  that every generator is block-diagonal in token 0's computational basis, so q is invariant.

This script checks, at k = 3 and exactly:
  GEN   every generator is unitary and commutes with the token-0 projector; three operations
        outside the gate set do not (negative controls: the check can fail).
  ORB   one weight level set is reached from the seed by a block-diagonal unitary (instance).
  CM    the countermodel H = S (x) I_4: not PSD, outside maxCone (product witness), yet
        nonnegative on every test whose token-0 ray lies in a finite family F, after any
        sampled gate word; the same for an infinite but gapped family (endpoint certificates).
  POS   positive controls: exact PSD states are nonnegative on every test used, and the
        consumed seed test (the bad ray) excludes H, so a dense family excludes it.
  ST    stage-level validity (records in [0,1]) holds for the non-quantum K(Z_F) defect state
        on 64 rational sharp product tests: record validity does not exclude it.
A mutation self-test runs first; the verdict prints only if every mutation is detected and
every unmutated check passes.  Finite checks support written arguments; they are not
universal proofs.
"""
from fractions import Fraction as Fr
import itertools
import random
import sys

MUT = set()
RESULTS = []


def check(ok, cid, text):
    RESULTS.append((bool(ok), cid, text))


# ------------------------------------------------------------------ Q(i)
class G:
    __slots__ = ("re", "im")

    def __init__(self, re=0, im=0):
        self.re = Fr(re)
        self.im = Fr(im)

    def __add__(self, o):
        o = g(o)
        return G(self.re + o.re, self.im + o.im)

    __radd__ = __add__

    def __sub__(self, o):
        o = g(o)
        return G(self.re - o.re, self.im - o.im)

    def __rsub__(self, o):
        return g(o) - self

    def __neg__(self):
        return G(-self.re, -self.im)

    def __mul__(self, o):
        o = g(o)
        return G(self.re * o.re - self.im * o.im, self.re * o.im + self.im * o.re)

    __rmul__ = __mul__

    def __truediv__(self, o):
        o = g(o)
        d = o.re * o.re + o.im * o.im
        return self * G(o.re / d, -o.im / d)

    def conj(self):
        return G(self.re, -self.im)

    def __eq__(self, o):
        o = g(o)
        return self.re == o.re and self.im == o.im

    def __hash__(self):
        return hash((self.re, self.im))


def g(x):
    return x if isinstance(x, G) else G(x, 0)


def zeros(n, m=None):
    m = n if m is None else m
    return [[G() for _ in range(m)] for _ in range(n)]


def eye(n):
    M = zeros(n)
    for i in range(n):
        M[i][i] = G(1)
    return M


def mm(A, B):
    return [[sum((A[i][l] * B[l][j] for l in range(len(B))), G()) for j in range(len(B[0]))]
            for i in range(len(A))]


def mv(A, v):
    return [sum((A[i][j] * v[j] for j in range(len(v))), G()) for i in range(len(A))]


def madd(*Ms):
    return [[sum((M[i][j] for M in Ms), G()) for j in range(len(Ms[0][0]))] for i in range(len(Ms[0]))]


def msc(c, M):
    return [[g(c) * x for x in r] for r in M]


def dag(M):
    return [[M[j][i].conj() for j in range(len(M))] for i in range(len(M[0]))]


def meq(A, B):
    return all(A[i][j] == B[i][j] for i in range(len(A)) for j in range(len(A[0])))


def kron(A, B):
    n, m = len(A), len(B)
    return [[A[i // m][j // m] * B[i % m][j % m] for j in range(n * m)] for i in range(n * m)]


def kronv(u, v):
    return [a * b for a in u for b in v]


def tr(M):
    return sum((M[i][i] for i in range(len(M))), G())


def quad(M, x):
    return sum((x[i].conj() * M[i][j] * x[j] for i in range(len(x)) for j in range(len(x))), G())


def outer(u, v=None):
    v = u if v is None else v
    return [[a * b.conj() for b in v] for a in u]


def is_psd(M):
    """Exact LDL^H test over Q(i) with the zero-pivot rule."""
    n = len(M)
    if not meq(M, dag(M)):
        return False
    A = [r[:] for r in M]
    for k in range(n):
        d = A[k][k]
        if d.im != 0 or d.re < 0:
            return False
        if d.re == 0:
            if any(not (A[i][k] == 0) for i in range(k + 1, n)):
                return False
            continue
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                A[i][j] = A[i][j] - A[i][k] * A[k][j] / d
    return True


def gm(rows):
    return [[g(x) for x in r] for r in rows]


I2 = eye(2)
SX = gm([[0, 1], [1, 0]])
SY = [[G(), G(0, -1)], [G(0, 1), G()]]
SZ = gm([[1, 0], [0, -1]])
P0 = gm([[1, 0], [0, 0]])
P1 = gm([[0, 0], [0, 1]])
LAM = G(Fr(3, 5), Fr(4, 5))                     # unit modulus, not a root of unity
PH = [[G(1), G()], [G(), LAM]]                   # third-axis rotation, up to global phase
CYC = [[G(Fr(1, 2), Fr(-1, 2)), G(Fr(-1, 2), Fr(-1, 2))],
       [G(Fr(1, 2), Fr(-1, 2)), G(Fr(1, 2), Fr(1, 2))]]
ROT0 = gm([[Fr(3, 5), Fr(-4, 5)], [Fr(4, 5), Fr(3, 5)]])   # real rotation (not in the gate set)
K = 3
N = 2 ** K


def local(gate, j):
    out = [[G(1)]]
    for t in range(K):
        out = kron(out, gate if t == j else I2)
    return out


def cnot(c, t):
    """Permutation matrix of CNOT(c -> t) on K tokens, index sum_i b_i 2^(K-1-i)."""
    M = zeros(N)
    for idx in range(N):
        bits = [(idx >> (K - 1 - i)) & 1 for i in range(K)]
        if bits[c]:
            bits[t] ^= 1
        out = sum(b << (K - 1 - i) for i, b in enumerate(bits))
        M[out][idx] = G(1)
    return M


def generators():
    gens = {
        "CNOT01": cnot(0, 1), "CNOT02": cnot(0, 2),
        "CNOT12": cnot(2, 0) if "cnot_into_token0" in MUT else cnot(1, 2),
        "PH1": local(PH, 1), "PH2": local(PH, 2),
        "CYC1": local(CYC, 1), "CYC2": local(CYC, 2),
    }
    return gens


PI0 = local(P0, 0)


def block_diag_token0(U):
    return meq(mm(U, PI0), mm(PI0, U))


# ================================================================== GEN
def sec_gen():
    gens = generators()
    ok = all(meq(mm(dag(U), U), eye(N)) for U in gens.values())
    check(ok, "GEN1", "the seven k=3 generators (CNOT01, CNOT02, CNOT12, third-axis phase and cyclic map on tokens 1, 2) are unitary")
    ok = all(block_diag_token0(U) for U in gens.values())
    check(ok, "GEN2", "every generator commutes with the token-0 projector P0 (x) I (x) I: token-0 weight is invariant")
    neg = {"CNOT10": cnot(1, 0), "CYC0": local(CYC, 0), "ROT0": local(ROT0, 0)}
    ok = all(not block_diag_token0(U) for U in neg.values())
    check(ok, "GEN-NEG", "negative controls: CNOT(1->0), the cyclic map on token 0 and a real rotation on token 0 do not commute with it")
    # the phase and cyclic conjugations are the intended Bloch actions (implementation control)
    ok = meq(mm(mm(PH, SX), dag(PH)), madd(msc(Fr(3, 5), SX), msc(Fr(4, 5), SY)))
    ok &= meq(mm(mm(PH, SZ), dag(PH)), SZ)
    cx, cy, cz = (mm(mm(CYC, s), dag(CYC)) for s in (SX, SY, SZ))
    ok &= meq(cx, SY) and meq(cy, SZ) and meq(cz, SX)
    check(ok, "GEN3", "conjugation by the phase gate rotates sigma_x to (3/5)sigma_x+(4/5)sigma_y and fixes sigma_z; the cyclic map sends x->y->z->x")


# ================================================================== ORB
def householder(v):
    """Unitary with first column v (unit, v[0] real < 1): I - 2 w w^dag/(w^dag w), w = e0 - v."""
    n = len(v)
    e0 = [G(1)] + [G() for _ in range(n - 1)]
    w = [e0[i] + v[i] if "householder_sign" in MUT else e0[i] - v[i] for i in range(n)]
    ww = sum((x.conj() * x for x in w), G())
    return madd(eye(n), msc(G(-2) / ww, outer(w)))


def sec_orb():
    a = [G(Fr(1, 3)), G(0, Fr(2, 3)), G(Fr(2, 3)), G()]      # unit, a0 real
    b = [G(Fr(2, 3)), G(Fr(1, 3)), G(0, Fr(2, 3)), G()]      # unit, b0 real
    U0, U1 = householder(a), householder(b)
    ok = all(meq(mm(dag(U), U), eye(4)) for U in (U0, U1))
    U = madd(kron(P0, U0), kron(P1, U1))
    seed = [G(Fr(3, 5))] + [G()] * 3 + [G(Fr(4, 5))] + [G()] * 3     # (3,4)/5 (x) |00>
    x = [Fr(3, 5) * c for c in a] + [Fr(4, 5) * c for c in b]
    ok &= meq([mv(U, seed)], [x]) and block_diag_token0(U)
    wt = sum((c.conj() * c for c in x[:4]), G())
    ok &= (wt == Fr(9, 25))
    check(ok, "ORB1", "a weight-9/25 Gaussian-rational vector is diag(U0,U1) applied to the seed (3,4)/5 (x) |00>, U0, U1 unitary (instance of level-set transitivity)")


# ================================================================== CM
W2 = (Fr(3, 5), Fr(4, 5))          # S = I - LAMBDA w w^T, bad ray (3,4)
BASE_F = [(1, 0), (0, 1), (1, 1), (1, 2), (2, 1), (1, 3), (3, 1)]


def smat():
    """Evaluated at call time so that the self-test mutations take effect."""
    lam = Fr(1) if "psd_S" in MUT else Fr(626, 625)
    return [[1 - lam * W2[0] * W2[0], -lam * W2[0] * W2[1]],
            [-lam * W2[1] * W2[0], 1 - lam * W2[1] * W2[1]]]


def f_rays():
    return BASE_F + ([(3, 4)] if "bad_ray_in_F" in MUT else [])


def gap():
    return ((5, 6), (4, 5)) if "gap_endpoint" in MUT else ((5, 6), (2, 3))


def sform(m, n):
    """(m,n) S (m,n)^T, sign equal to that of the S-form on the unit ray (m,n)/r."""
    S = smat()
    return S[0][0] * m * m + 2 * S[0][1] * m * n + S[1][1] * n * n


def H_c():
    return kron(gm(smat()), eye(4))


def random_word(rnd, gens, length):
    U = eye(N)
    names = sorted(gens)
    for _ in range(length):
        U = mm(gens[names[rnd.randrange(len(names))]], U)
    return U


def gauss_unit4(rnd):
    """Gaussian-rational unit vectors of C^4 from a small fixed pool, with a random phase."""
    pool = [
        [G(Fr(1, 3)), G(0, Fr(2, 3)), G(Fr(2, 3)), G()],
        [G(Fr(2, 3)), G(Fr(1, 3)), G(0, Fr(2, 3)), G()],
        [G(Fr(1, 2)), G(Fr(1, 2)), G(0, Fr(1, 2)), G(0, Fr(-1, 2))],
        [G(Fr(3, 5)), G(), G(), G(0, Fr(4, 5))],
        [G(), G(Fr(5, 13)), G(Fr(-12, 13)), G()],
        [G(Fr(2, 7)), G(Fr(3, 7)), G(0, Fr(6, 7)), G()],
    ]
    ph = [G(1), G(-1), G(0, 1), G(0, -1), G(Fr(3, 5), Fr(4, 5))][rnd.randrange(5)]
    return [ph * c for c in pool[rnd.randrange(len(pool))]]


def sec_cm():
    S = smat()
    F_RAYS = f_rays()
    GAP = gap()
    H = H_c()
    xstar = kronv([G(3), G(4)], [G(1), G(), G(), G()])            # product vector (3,4) (x) |00>
    v = quad(H, xstar)
    ok = meq(H, dag(H)) and v.im == 0 and v.re < 0
    check(ok, "CM1", f"H = S (x) I_4 is Hermitian and x*^dag H x* = {v.re} < 0 on the product vector (3,4)(x)|00>: H is neither PSD nor in maxConeK")
    ok = all(sform(m, n) >= 0 for (m, n) in F_RAYS)
    check(ok, "CM2", f"S-form >= 0 on every token-0 ray of F = {F_RAYS[:7]} (exact)")
    # structural lemma, on sampled gate words: U block-diagonal and U H U^dag = [[S00 I, S01 V],[S01 V^dag, S11 I]]
    rnd = random.Random(836)
    gens = generators()
    if "nonblock_word" in MUT:
        gens = dict(gens, ROT0=local(ROT0, 0))
    ok = True
    words = []
    for _ in range(12):
        U = random_word(rnd, gens, rnd.randrange(1, 6))
        words.append(U)
        if not block_diag_token0(U):
            ok = False
            continue
        C = mm(mm(U, H), dag(U))
        top = [r[:4] for r in C[:4]]
        bot = [r[4:] for r in C[4:]]
        off = [r[4:] for r in C[:4]]
        V = msc(G(1) / S[0][1], off)
        ok &= meq(top, msc(S[0][0], eye(4))) and meq(bot, msc(S[1][1], eye(4)))
        ok &= meq(mm(V, dag(V)), eye(4))
    check(ok, "CM3", "12 seeded gate words (length 1-5): each is token-0 block-diagonal and conjugates H to [[S00 I, S01 V],[S01 V^dag, S11 I]] with V unitary")
    # [sample] nonnegativity on tests whose token-0 ray is in F, after gate words
    ok = True
    cnt = 0
    for U in words:
        C = mm(mm(U, H), dag(U))
        for (m, n) in F_RAYS:
            for _ in range(4):
                a, b = gauss_unit4(rnd), gauss_unit4(rnd)
                x = [m * c for c in a] + [n * c for c in b]
                val = quad(C, x)
                ok &= (val.im == 0 and val.re >= 0)
                cnt += 1
    check(ok, "CM4", f"[sample] x^dag (U H U^dag) x >= 0 for {cnt} Gaussian-rational vectors with token-0 ray in F (bound proved in report B2)")
    # gapped infinite family: endpoint certificates; the written monotonicity covers the rest
    (m1, n1), (m2, n2) = GAP
    ok = sform(m1, n1) >= 0 and sform(m2, n2) >= 0 and sform(1, 0) >= 0 and sform(0, 1) >= 0
    ok &= (Fr(n1, m1) < Fr(4, 3) < Fr(n2, m2))                   # the bad ray lies inside the gap
    check(ok, "CM5", f"gapped family: S-form >= 0 at the gap endpoints {GAP} and at q = 0, 1, with the bad ray (3,4) strictly inside the gap")


# ================================================================== POS
def sec_pos():
    H = H_c()
    xstar = kronv([G(3), G(4)], [G(1), G(), G(), G()])
    ok = quad(H, xstar).re < 0
    check(ok, "POS1", "the consumed seed test (token-0 ray (3,4), tokens 1, 2 along +z) excludes H: a family with dense weights excludes it")
    ghz = [G(1)] + [G()] * 6 + [G(1)]
    wst = [G(), G(1), G(1), G(), G(1), G(), G(), G()]
    ent = [G(1), G(0, 2), G(-1), G(), G(3, 1), G(), G(0, -1), G(2)]
    prod = kronv(kronv([G(3), G(4)], [G(1), G(0, 1)]), [G(5), G(-12)])
    states = [outer(v) for v in (ghz, wst, ent, prod)]
    ok = all(is_psd(r) for r in states)
    rnd = random.Random(829)
    gens = generators()
    cnt = 0
    for r in states:
        for _ in range(3):
            U = random_word(rnd, gens, 4)
            rr = mm(mm(U, r), dag(U))
            ok &= is_psd(rr)
            for (m, n) in BASE_F + [(3, 4)]:
                t = kronv([G(m), G(n)], [G(1), G(), G(), G()])
                ok &= quad(rr, t).re >= 0
                cnt += 1
    check(ok, "POS2", f"positive control: 4 exact PSD states and 12 gate-word images are PSD (LDL) and nonnegative on all {cnt} seed tests used")


# ================================================================== ST
def zf_defect(s, t):
    M = madd(eye(4), msc(s, kron(SX, SZ)), msc(t, kron(SY, SY)), msc(-s * t, kron(SZ, SX)))
    return msc(Fr(1, 16), M)


RAT_UNIT = [(1, 0, 0), (0, 1, 0), (0, 0, 1), (0, 0, -1), (Fr(3, 5), 0, Fr(4, 5)),
            (Fr(2, 3), Fr(1, 3), Fr(2, 3)), (Fr(-2, 7), Fr(3, 7), Fr(6, 7)), (Fr(1, 9), Fr(-4, 9), Fr(8, 9))]


def proj(b):
    return msc(Fr(1, 2), madd(I2, msc(b[0], SX), msc(b[1], SY), msc(b[2], SZ)))


def sec_st():
    scale = 8 if "zf_scale" in MUT else 4
    z = msc(scale, zf_defect(1, 1))
    ok = tr(z) == 1
    vals = []
    for a in RAT_UNIT:
        for c in RAT_UNIT:
            vals.append(tr(mm(kron(proj(a), proj(c)), z)))
    ok &= all(v.im == 0 and 0 <= v.re <= 1 for v in vals)
    Pp = msc(Fr(1, 2), madd(eye(4), msc(-8, zf_defect(1, 1))))
    ok &= meq(mm(Pp, Pp), Pp) and tr(mm(Pp, z)) == Fr(-1, 2)
    check(ok, "ST1", f"K(Z_F) defect, trace 1: its {len(vals)} coincidence records on rational sharp product tests lie in [0,1] (a valid stage table), yet the PSD projector P_+ gives -1/2")


SECTIONS = [sec_gen, sec_orb, sec_cm, sec_pos, sec_st]
MUTATIONS = {
    "cnot_into_token0": "GEN2",
    "householder_sign": "ORB1",
    "psd_S": "CM1",
    "bad_ray_in_F": "CM2",
    "nonblock_word": "CM3",
    "gap_endpoint": "CM5",
    "zf_scale": "ST1",
}


def run():
    RESULTS.clear()
    for s in SECTIONS:
        s()
    return list(RESULTS)


def main():
    selftest = []
    for mut, target in MUTATIONS.items():
        MUT.clear()
        MUT.add(mut)
        res = run()
        failed = sorted({cid for ok, cid, _ in res if not ok})
        selftest.append((mut, target, target in failed, failed))
    MUT.clear()
    res = run()
    for ok, cid, text in res:
        print(("PASS " if ok else "FAIL ") + cid + "  " + text)
    print()
    for mut, target, hit, failed in selftest:
        print(("MUTATION-REJECTED " if hit else "MUTATION-MISSED ") + f"{mut}: target {target}; failing {','.join(failed)}")
    n_fail = sum(1 for ok, _, _ in res if not ok)
    n_miss = sum(1 for _, _, hit, _ in selftest if not hit)
    print()
    print(f"checks: {len(res)}, failures: {n_fail}; mutations: {len(selftest)}, missed: {n_miss}")
    if n_fail == 0 and n_miss == 0:
        print("VERDICT KWEIGHT-EXACT: PASS (exact k=3 certificates and labelled samples; not universal proofs)")
        return 0
    print("VERDICT KWEIGHT-EXACT: NOT ESTABLISHED (a control failed or a mutation was missed; no reading is drawn)")
    return 1


if __name__ == "__main__":
    sys.exit(main())
