"""Registry of explicitly permitted transport transformations (closed by default).

Prototype for the bounded transport-difference policy (owner decision, amaybaum, 2026-11-25).
This module decides only whether a stored text differs from the text sent by a transformation
the owner has explicitly permitted. It does not verify content integrity on its own and it never
learns: REGISTRY is a frozen tuple written in source, and nothing in this module or in the gate
adds, changes or removes a rule at run time. A new rule enters only by owner decision, independent
review and its own regression controls (PROTOCOL-v2.md section 6).

Every rule decides by exact construction: string slicing and byte-for-byte equality. There is no
whitespace normalization, no case folding, no Unicode normalization and no similarity measure.
"""
from dataclasses import dataclass
from typing import Callable, Tuple

# The attribution footer core: the "---" line and the attribution line, exact bytes, no newline
# at either end. Kept here and only here (the gate never mentions it).
FOOTER_CORE = "---\n_Generated by [Claude Code](https://claude.ai/code)_"
# The send form used by validated footer-form operations: exactly two newlines, then the core.
FOOTER_SEND_FORM = "\n\n" + FOOTER_CORE

NL = "\n"    # the only character whose count may differ under footer-attribution-1


@dataclass(frozen=True)
class Rule:
    id: str                                   # stable identifier; never reused for another rule
    version: str
    description: str
    fields: Tuple[str, ...]                   # the text fields the rule may apply to
    permits: Callable[[str, str], bool]       # pure: permits(sent, stored) -> bool


def split_footer_tail(text):
    """Split text into (content, footer_count).

    The tail is the maximal trailing segment of the form  N1 + FOOTER_CORE + N2  or  N2, where N1
    and N2 are runs of the newline character U+000A only. The footer core is recognised as part
    of the tail only when all of the following hold; otherwise it stays in the content:
      * N1 has at least two newlines (the footer is its own Markdown block: with one newline the
        last content line would become a setext heading, and an indented "---" would be code);
      * the content before N1 is not empty;
      * the content does not itself end with FOOTER_CORE (no doubled footer).
    content is everything before the tail. footer_count is 1 when the core was recognised, else 0.
    """
    t1 = text.rstrip(NL)
    if t1.endswith(FOOTER_CORE):
        before = t1[: -len(FOOTER_CORE)]
        content = before.rstrip(NL)
        sep = before[len(content):]
        if content and len(sep) >= 2 and not content.endswith(FOOTER_CORE):
            return content, 1
    return t1, 0


def _footer_attribution_1(sent, stored):
    """Permit iff, byte for byte, the stored text is the sent text with the attribution footer at
    its very end, where the sent text either lacks the footer or has it at its very end too.

    Exactly which characters may differ between sent and stored:
      * the presence of FOOTER_CORE at the very end (absent or present in sent; present exactly
        once in stored);
      * the number of newline characters U+000A in the run between the last character of the
        content and FOOTER_CORE, provided each text that carries the footer has at least two
        there;
      * the number of newline characters U+000A after the last character of the content (when
        sent has no footer) or after FOOTER_CORE, up to the end of the text.
    Nothing else. In particular spaces, tabs and every other character are content, wherever they
    are, including spaces or tabs at the end of the last content line (a Markdown hard line break
    is two trailing spaces), a trailing backslash, indentation of any line, space-only lines, and
    any character after the footer other than a newline. Non-ASCII spaces, carriage returns, form
    feeds and vertical tabs are content. A footer removed, doubled, altered by any character,
    preceded by fewer than two newlines, indented, or not at the very end is not permitted.
    """
    if not (isinstance(sent, str) and isinstance(stored, str)):
        return False
    c_sent, n_sent = split_footer_tail(sent)
    c_stored, n_stored = split_footer_tail(stored)
    return n_stored == 1 and n_sent <= 1 and c_sent == c_stored


FOOTER_ATTRIBUTION_1 = Rule(
    id="footer-attribution-1",
    version="1",
    description=("Attribution footer '---' / '_Generated by [Claude Code](https://claude.ai/code)_'"
                 " present once at the very end of the stored body, absent from or at the very end"
                 " of the sent body; only the number of newlines before (at least two) and after"
                 " it may differ. Bodies only."),
    fields=("body",),
    permits=_footer_attribution_1,
)

# The allowlist. A frozen tuple: closed by default, changed only by editing this source under an
# owner decision with independent review and regression controls.
REGISTRY = (FOOTER_ATTRIBUTION_1,)


def validate_registry(rules):
    if not isinstance(rules, tuple):
        raise TypeError("rule registry must be a tuple")
    ids = set()
    for r in rules:
        if not isinstance(r, Rule):
            raise TypeError("registry entry is not a Rule: %r" % (r,))
        if r.id in ids:
            raise ValueError("duplicate rule id %r" % r.id)
        ids.add(r.id)


def classify(sent, stored, rules=None, field="body"):
    """Return ("exact", None), ("permitted", rule_id) or ("rejected", None).

    "exact": stored == sent. "permitted": exactly one rule that applies to this field permits the
    difference. Zero permitting rules, or more than one (ambiguity), is "rejected"."""
    rules = REGISTRY if rules is None else rules
    validate_registry(rules)
    if isinstance(sent, str) and isinstance(stored, str) and sent == stored:
        return ("exact", None)
    hits = [r for r in rules if field in r.fields and r.permits(sent, stored) is True]
    if len(hits) == 1:
        return ("permitted", hits[0].id)
    return ("rejected", None)


def footer_shaped_tail(sent, stored):
    """Containment only, never acceptance (AGENTS.md section A.49 rule 3, third condition).

    True iff the sent content (the text sent less its tail as split_footer_tail delimits it: the
    newlines and any attribution footer at its very end) is not empty, the stored text begins with
    it byte for byte, and everything after it in the stored text is made only of newline
    characters U+000A and at most one exact copy of FOOTER_CORE. Any other appended character (a
    space, a link, a signature, an altered or look-alike footer) or a second copy of the footer
    makes it false. A true result decides only
    that a stop may be confined to the failed operation; whether a difference is accepted is
    decided by classify and the exact rule alone."""
    if not (isinstance(sent, str) and isinstance(stored, str)):
        return False
    content, _ = split_footer_tail(sent)
    if content == "" or not stored.startswith(content):
        return False
    rest = stored[len(content):]
    return rest.count(FOOTER_CORE) <= 1 and set(rest.replace(FOOTER_CORE, "")) <= {NL}


def rule_by_id(rule_id, rules=None):
    for r in (REGISTRY if rules is None else rules):
        if r.id == rule_id:
            return r
    raise KeyError(rule_id)


# -- send forms (what the gate sends; read-back then compares exactly or via the allowlist) -----
def canonical_footer_body(body):
    """Content with trailing ASCII whitespace and any trailing footer removed, then exactly one
    FOOTER_SEND_FORM. Same definition as gate.canonical_footer_body."""
    t = body.rstrip()
    while t.endswith(FOOTER_CORE):
        t = t[: -len(FOOTER_CORE)].rstrip()
    return t + FOOTER_SEND_FORM


def send_form_violations(form, text, field):
    """Violations of an operation's validated send form for one field (empty list: none)."""
    if field != "body" or form is None:
        return []
    if form == "footer":
        if not text.endswith(FOOTER_SEND_FORM):
            return ["send form requires the footer at the end"]
        if text != canonical_footer_body(text):
            return ["footer separator is not canonical (exactly two newlines before ---)"]
        return []
    if form == "nofooter":
        return ["send form forbids the footer"] if text.rstrip().endswith(FOOTER_CORE) else []
    return ["unknown send form %r" % (form,)]
