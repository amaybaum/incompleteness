"""Write gate prototype: every automated GitHub text write and every git push passes here.

Prototype only. It talks to the network solely through an injected transport and an injected
git runner; the tests use mocks. Nothing here changes AGENTS.md section A.49 or resumes writing.

Fail-closed rules:
  * a persistent halt marker blocks every write, in this and every later process, until removed
    by hand on a recorded owner decision; the gate never removes it;
  * pre-checks of A.49 rule 1 and rule 4 run before any write;
  * the expected stored text is the text sent, fixed (copied and hashed) before the write; the
    operation's validated send form decides whether that text carries the footer; there is no
    normalization of any kind;
  * any mismatch, failed read-back, unexpected status, exception or refusal writes the marker and
    raises Halted; the CLI exits nonzero; there is no API that continues past a failure;
  * a push needs a 40-hex lowercase commit id and a plain refspec to an allowed branch: no empty
    source, no deletion, no force, no flags.
"""
import hashlib, json, os, re, sys, time, unicodedata

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
FOOTER_CORE = FOOTER[2:]   # "---" line and attribution line, without the separator


def canonical_footer_body(body):
    """The outgoing text in the footer send form: the content with trailing whitespace removed
    and any footer already at its end taken off, then exactly one FOOTER (two newlines before
    "---"). This fixes the text before sending; read-back still compares it byte for byte."""
    t = body.rstrip()
    while t.endswith(FOOTER_CORE):
        t = t[: -len(FOOTER_CORE)].rstrip()
    return t + FOOTER
SHA40 = re.compile(r"[0-9a-f]{40}")
LINK = re.compile(r"https?://(?:www\.)?github\.com/[^\s)\]>`'\"]+")
BRANCH = re.compile(r"refs/heads/[A-Za-z0-9][A-Za-z0-9._/-]*")


class Halted(Exception):
    """Raised after the halt marker is written (or found). Nothing further may be written."""


# Operations. send_form: "footer" (text fields must end exactly with FOOTER), "nofooter" (must
# not), or None (no text fields). validated: set only by owner decision after a single
# owner-granted write passed exact read-back (A.51 item 2). Default: nothing validated.
OPERATIONS = {
    "comment.create": dict(method="POST", path="issues/{n}/comments", text=("body",), ok=(201,),
                           created="id"),
    "issue.edit_body": dict(method="PATCH", path="issues/{n}", text=("body",), ok=(200,)),
    "issue.create": dict(method="POST", path="issues", text=("title", "body"), ok=(201,),
                         created="number"),
    "issue.close": dict(method="PATCH", path="issues/{n}", text=(), ok=(200,)),
    "pr.create": dict(method="POST", path="pulls", text=("title", "body"), ok=(201,),
                      created="number"),
    "pr.edit": dict(method="PATCH", path="pulls/{n}", text=("body",), ok=(200,)),
    "labels.add": dict(method="POST", path="issues/{n}/labels", text=(), ok=(200,)),
    "labels.remove": dict(method="DELETE", path="issues/{n}/labels/{label}", text=(), ok=(200,)),
}


def precheck_text(t):
    """A.49 rule 1 and rule 4. Returns a list of violations (empty when the text may be sent)."""
    bad = []
    if not isinstance(t, str):
        return ["not a string"]
    if "\r" in t:
        bad.append("carriage return")
    for c in t:
        if unicodedata.category(c) == "Cf":
            bad.append("format character U+%04X" % ord(c))
        elif c.isspace() and ord(c) > 127:
            bad.append("non-ASCII space U+%04X" % ord(c))
    for m in LINK.finditer(t):
        u = m.group(0)
        if re.search(r"/(blob|tree)/", u) and len(u) > 101 and "#" not in u:
            bad.append("long repository link without fragment: %d chars" % len(u))
    first = t.split("\n", 1)[0]
    if first.lstrip().lower().startswith("oi-"):
        bad.append("first line begins with oi-")
    return bad


def check_refspec(refspec, allowed):
    """Refuse anything but '<40-hex>:refs/heads/<allowed branch>'. Returns violations."""
    bad = []
    if not isinstance(refspec, str) or refspec.count(":") != 1:
        return ["refspec must be exactly <sha>:<ref>"]
    src, dst = refspec.split(":")
    if src.startswith("+"):
        bad.append("force refspec")
    if src == "":
        bad.append("empty source: this refspec deletes the remote ref")
    elif not SHA40.fullmatch(src):
        bad.append("source is not a 40-hex lowercase commit id")
    if not BRANCH.fullmatch(dst) or ".." in dst or dst.endswith((".lock", "/")):
        bad.append("destination is not a plain refs/heads/ branch")
    elif dst in ("refs/heads/main", "refs/heads/master"):
        bad.append("destination is main")
    elif dst not in allowed:
        bad.append("destination branch is not designated")
    return bad


class Gate:
    def __init__(self, transport, git, halt_path, repo, registry, allowed_branches=(),
                 evidence_dir=None, log=None):
        self.t, self.git, self.halt_path, self.repo = transport, git, halt_path, repo
        self.registry = registry          # op -> {"validated": bool, "send_form": str|None}
        self.allowed = frozenset(allowed_branches)
        self.evidence_dir = evidence_dir or os.path.dirname(os.path.abspath(halt_path))
        self.grants = set()               # single-write grants: (op, target) tuples
        self.log = log if log is not None else []

    # -- halt --------------------------------------------------------------------------------
    def _check_clear(self):
        if os.path.lexists(self.halt_path):
            raise Halted("halt marker present: %s" % self.halt_path)

    def _halt(self, reason, **evidence):
        rec = {"reason": reason, "time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
               "pid": os.getpid()}
        ev = {}
        for k, v in evidence.items():
            if isinstance(v, str):
                path = os.path.join(self.evidence_dir, "halt-%d-%s.txt" % (os.getpid(), k))
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(v)
                ev[k] = {"file": os.path.basename(path),
                         "sha256": hashlib.sha256(v.encode("utf-8")).hexdigest()}
            else:
                ev[k] = v
        rec["evidence"] = ev
        try:   # O_EXCL: never overwrite an earlier marker, which records the first failure
            fd = os.open(self.halt_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
            with os.fdopen(fd, "w") as f:
                json.dump(rec, f, indent=1, sort_keys=True)
                f.flush()
                os.fsync(f.fileno())
        except FileExistsError:
            pass
        raise Halted(reason)

    # -- grants ------------------------------------------------------------------------------
    def grant_single_write(self, op, target):
        """Record an owner grant for one write of an unvalidated operation (A.51 item 2)."""
        self.grants.add((op, str(target)))

    # -- text writes -------------------------------------------------------------------------
    def write(self, op, target=None, fields=None, labels=None, label=None):
        """Perform exactly one write. Returns the stored object; raises Halted on any failure."""
        self._check_clear()
        fields = dict(fields or {})
        spec = OPERATIONS.get(op)
        reg = self.registry.get(op)
        if spec is None or reg is None:
            self._halt("unknown operation %r" % (op,))
        key = (op, str(target))
        if not reg.get("validated"):
            if key not in self.grants:
                self._halt("operation %s is not validated and has no single-write grant" % op)
            self.grants.discard(key)      # consumed before the write: one grant, one attempt
        if set(fields) != set(spec["text"]):
            self._halt("fields %s do not match operation %s" % (sorted(fields), op))
        for k, v in fields.items():
            bad = precheck_text(v)
            form = reg.get("send_form")
            if k == "body" and form == "footer" and not v.endswith(FOOTER):
                bad.append("send form requires the footer at the end")
            elif k == "body" and form == "footer" and v != canonical_footer_body(v):
                bad.append("footer separator is not canonical (exactly two newlines before ---)")
            if k == "body" and form == "nofooter" and v.endswith(FOOTER):
                bad.append("send form forbids the footer")
            if bad:
                self._halt("pre-check refused field %s: %s" % (k, "; ".join(bad)), sent=v)
        # Expected stored text: the text sent, frozen now. No normalization.
        expected = {k: bytes(v.encode("utf-8")) for k, v in fields.items()}
        digests = {k: hashlib.sha256(b).hexdigest() for k, b in expected.items()}
        path = "repos/%s/%s" % (self.repo, spec["path"].format(n=target, label=label))
        payload = dict(fields)
        if op == "issue.close":
            payload = {"state": "closed", "state_reason": "completed"}
        if op == "labels.add":
            payload = {"labels": list(labels or [])}
        before = None
        if spec["method"] in ("PATCH", "DELETE") or op == "labels.add":
            before = self._get(self._readback_path(op, target))  # untouched fields must stay
        self.log.append(("write", op, str(target), digests))
        try:
            status, resp = self.t.request(spec["method"], path, payload)
        except BaseException as e:      # unknown outcome: the write may or may not have landed
            self._halt("unknown outcome: %s: %s" % (type(e).__name__, e))
        if status not in spec["ok"]:
            self._halt("unexpected status %r for %s" % (status, op))
        # A created object is read back by the id the response names, never by the target.
        rb_target = (resp or {}).get(spec["created"]) if "created" in spec else target
        if "created" in spec and not (isinstance(rb_target, int) and rb_target > 0):
            rb_target = None
        if rb_target is None:
            self._halt("unknown outcome: no created object id in response")
        stored = self._get(self._readback_path(op, rb_target))
        for k, b in expected.items():
            got = stored.get(k)
            if not isinstance(got, str) or got.encode("utf-8") != b:
                self._halt("read-back mismatch in %s of %s %s" % (k, op, rb_target),
                           sent=fields[k], stored=got if isinstance(got, str) else repr(got))
        if before is not None:          # fields the write did not send must be byte-identical
            for k in ("title", "body"):
                if k not in expected and before.get(k) != stored.get(k):
                    self._halt("unsent field %s changed by %s %s" % (k, op, rb_target),
                               sent=str(before.get(k)), stored=str(stored.get(k)))
        if op == "issue.close" and stored.get("state") != "closed":
            self._halt("state read-back is not closed")
        if op in ("labels.add", "labels.remove"):
            names = sorted(x["name"] for x in stored.get("labels", []))
            want = set(x["name"] for x in before.get("labels", []))
            want = want | set(labels or []) if op == "labels.add" else want - {label}
            if names != sorted(want):
                self._halt("label read-back mismatch: %s != %s" % (names, sorted(want)))
        return stored

    def _readback_path(self, op, n):
        kind = {"pr.create": "pulls", "pr.edit": "pulls",
                "comment.create": "issues/comments"}.get(op, "issues")
        return "repos/%s/%s/%s" % (self.repo, kind, n)

    def _get(self, path):
        try:
            status, obj = self.t.request("GET", path, None)
        except BaseException as e:
            self._halt("read-back failed: %s: %s" % (type(e).__name__, e))
        if status != 200 or not isinstance(obj, dict):
            self._halt("read-back failed: status %r" % (status,))
        return obj

    # -- pushes ------------------------------------------------------------------------------
    def push(self, remote, sha, branch_ref):
        """Push one commit to one designated branch: create or fast-forward, then read back."""
        self._check_clear()
        refspec = "%s:%s" % (sha, branch_ref)
        bad = check_refspec(refspec, self.allowed)
        if not isinstance(remote, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", remote):
            bad.append("remote must be a plain remote name")
        if bad:
            self._halt("push refused: %s" % "; ".join(bad), refspec=refspec)
        try:
            old = self.git.remote_sha(remote, branch_ref)          # None when absent
            if old is not None and not self.git.is_ancestor(old, sha):
                self._halt("push refused: not a fast-forward of %s" % old)
        except Halted:
            raise
        except BaseException as e:
            self._halt("push preflight failed: %s: %s" % (type(e).__name__, e))
        argv = ["git", "push", "--porcelain", "--", remote, refspec]   # no flags after --
        self.log.append(("push", argv))
        try:
            rc = self.git.run(argv)
        except BaseException as e:
            self._halt("unknown push outcome: %s: %s" % (type(e).__name__, e))
        if rc != 0:
            self._halt("push exited %r: outcome unknown" % (rc,))
        try:
            now = self.git.remote_sha(remote, branch_ref)
        except BaseException as e:
            self._halt("push read-back failed: %s: %s" % (type(e).__name__, e))
        if now != sha:
            self._halt("push read-back mismatch: remote %r != %s" % (now, sha))
        return now


def run_plan(gate, steps):
    """Run steps in order. No step is wrapped: the first failure ends the plan."""
    done = []
    for s in steps:
        if s[0] == "push":
            gate.push(*s[1:])
        else:
            op, target, fields = s[1], s[2], s[3]
            gate.write(op, target, fields, **(s[4] if len(s) > 4 else {}))
        done.append(s)
    return done


def main(argv):
    """CLI shape: exits 3 on Halted, 0 on success. Real transports are out of scope here."""
    try:
        argv[0]()
    except Halted as e:
        sys.stderr.write("HALTED: %s\n" % e)
        return 3
    return 0
