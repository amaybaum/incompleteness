#!/usr/bin/env python3
"""Preservation checker for the A1 deletion, independent of the transformation. Standard library only; it imports
nothing from edits_check.py, guards_check.py or any script that applies the edits.

The frozen exact-edit ledger (ledger.json) records every edit as a splice of the base: the file, the byte span of
the old text at the base, the SHA-256 of the old text, the new text, its SHA-256 and the reason. The ledger is the
authorization: nothing outside it may change.

Usage (from the repository root):
  python3 -I -B .../preserve_check.py --build-ledger          write ledger.json from edits.json at its drafting base
  python3 -I -B .../preserve_check.py --verify-ledger         re-derive ledger.json and compare (spans, hashes, ids)
  python3 -I -B .../preserve_check.py --commit REV | --tree DIR
                                                              check a candidate post-deletion tree
  python3 -I -B .../preserve_check.py --self-test             mutation tests in both directions on the real ledger
  --base REV  with --commit/--tree: compare against REV (a later main) instead of the ledger base; refused unless every
              ledgered file is byte-identical at REV and at the ledger base

A candidate passes when, against the ledger's base:
  1. every file the ledger names equals, byte for byte, the base with exactly the ledger's splices applied;
  2. every other tracked file equals the base, apart from the derived paths (regenerated by a named recipe and
     checked by that recipe in CI) and new files under the round's own record directory;
  3. no file is added or deleted elsewhere; no file of the record directory present at the base changes;
  4. structurally: a Python file changes only in string constants and comments (its AST with string constants
     blanked is unchanged), a Lean file only inside comments, a JSON file only in string values.
A failure names the splice that is missing or altered, or the byte and line of a change outside every splice.
"""
import argparse, ast, hashlib, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
REC = os.path.relpath(HERE, ROOT).replace(os.sep, '/') + '/'
EDITS = os.path.join(HERE, 'edits.json')
LEDGER = os.path.join(HERE, 'ledger.json')
# Paths the execution regenerates rather than splices, each with the recipe that checks it.
DERIVED = [
    (r'^papers/[^/]+\.(tex|pdf)$', 'sh ./build.sh <papers>; the regenerated file is compared with the committed one in CI'),
    (r'^book/The-Incompleteness-of-Observation-FULL\.(tex|pdf)$', 'sh ./build.sh --book; compared in CI'),
]
COVERAGE = 'verification/coverage/LEDGER.json'  # spliced (D295) and then re-affirmed: fingerprint values only


def sha(b):
    return hashlib.sha256(b).hexdigest()


def git(*a):
    return subprocess.run(['git', '-C', ROOT] + list(a), capture_output=True, check=True).stdout


def tree_of(rev):
    """{path: bytes} of every blob of rev, read from the object store."""
    ents = []
    for rec in git('ls-tree', '-r', '-z', rev).split(b'\0'):
        if rec:
            meta, path = rec.split(b'\t', 1)
            mode, typ, oid = meta.split()
            if typ == b'blob':
                ents.append((oid, path.decode('utf-8')))
    p = subprocess.Popen(['git', '-C', ROOT, 'cat-file', '--batch'], stdin=subprocess.PIPE, stdout=subprocess.PIPE)
    out = {}
    for oid, path in ents:
        p.stdin.write(oid + b'\n'); p.stdin.flush()
        n = int(p.stdout.readline().split()[2])
        out[path] = p.stdout.read(n); p.stdout.read(1)
    p.stdin.close(); p.wait()
    return out


def tree_dir(d):
    out = {}
    for dp, dns, fns in os.walk(d):
        dns[:] = [x for x in dns if x != '.git']
        for n in fns:
            fp = os.path.join(dp, n)
            rel = os.path.relpath(fp, d).replace(os.sep, '/')
            if rel == '.git':
                continue
            out[rel] = os.readlink(fp).encode('utf-8') if os.path.islink(fp) else open(fp, 'rb').read()
    return out


# ---- ledger -------------------------------------------------------------------------------------------------

def build_ledger(edits, base_files):
    spl = []
    for e in edits['edits']:
        b = base_files[e['file']]
        o = e['old'].encode('utf-8')
        if b.count(o) != 1:
            raise SystemExit('%s: old text occurs %d times in %s at the base' % (e['id'], b.count(o), e['file']))
        s = b.index(o)
        nb = e['new'].encode('utf-8')
        spl.append({'id': e['id'], 'file': e['file'], 'start': s, 'end': s + len(o), 'old_sha256': sha(o),
                    'new': e['new'], 'new_sha256': sha(nb), 'reason': e['reason']})
    spl.sort(key=lambda x: (x['file'], x['start']))
    led = {'schema': 'a1exit deletion exact-edit ledger v1', 'base': edits['drafting_base'],
           'edits_sha256': sha(open(EDITS, 'rb').read()), 'splices': spl, 'files': {}}
    for f in sorted({x['file'] for x in spl}):
        exp = expected(led, base_files, f)
        led['files'][f] = {'base_sha256': sha(base_files[f]), 'expected_sha256': sha(exp)}
    return led


def validate_ledger(led, base_files):
    bad = []
    by = {}
    for x in led['splices']:
        b = base_files.get(x['file'])
        if b is None:
            bad.append('%s: file %s absent at the base' % (x['id'], x['file'])); continue
        if sha(b[x['start']:x['end']]) != x['old_sha256']:
            bad.append('%s: old-text hash does not match the base span %d-%d of %s' % (x['id'], x['start'], x['end'], x['file']))
        if sha(x['new'].encode('utf-8')) != x['new_sha256']:
            bad.append('%s: new-text hash does not match the new text' % x['id'])
        by.setdefault(x['file'], []).append(x)
    for f, xs in by.items():
        xs = sorted(xs, key=lambda y: y['start'])
        for a, c in zip(xs, xs[1:]):
            if a['end'] > c['start']:
                bad.append('%s and %s overlap in %s' % (a['id'], c['id'], f))
        if f in led['files'] and sha(base_files[f]) != led['files'][f]['base_sha256']:
            bad.append('%s: base hash differs from the ledger' % f)
    return bad


def expected(led, base_files, f, skip=()):
    b = base_files[f]
    out, pos = [], 0
    for x in sorted((y for y in led['splices'] if y['file'] == f), key=lambda y: y['start']):
        out.append(b[pos:x['start']])
        out.append(b[x['start']:x['end']] if x['id'] in skip else x['new'].encode('utf-8'))
        pos = x['end']
    out.append(b[pos:])
    return b''.join(out)


# ---- structural checks (independent re-implementation) ------------------------------------------------------

def lean_code(t):
    out, i, depth, n = [], 0, 0, len(t)
    while i < n:
        if t.startswith('/-', i):
            depth += 1; i += 2; continue
        if depth and t.startswith('-/', i):
            depth -= 1; i += 2; continue
        if depth:
            i += 1; continue
        if t.startswith('--', i):
            j = t.find('\n', i); i = n if j < 0 else j; continue
        out.append(t[i]); i += 1
    return re.sub(r'\s+', ' ', ''.join(out)).strip()


class _Blank(ast.NodeTransformer):
    def visit_Constant(self, node):
        return ast.copy_location(ast.Constant(value=''), node) if isinstance(node.value, str) else node


def py_shape(t):
    import warnings
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        return ast.dump(_Blank().visit(ast.parse(t)), include_attributes=False)


def json_shape(v):
    if isinstance(v, dict):
        return {k: json_shape(w) for k, w in v.items()}
    if isinstance(v, list):
        return [json_shape(w) for w in v]
    return '' if isinstance(v, str) else v


def structural(f, old, new):
    try:
        o, n = old.decode('utf-8'), new.decode('utf-8')
        if f.endswith('.py'):
            return py_shape(o) == py_shape(n)
        if f.endswith('.lean'):
            return lean_code(o) == lean_code(n)
        if f.endswith('.json'):
            return json_shape(json.loads(o)) == json_shape(json.loads(n))
    except (SyntaxError, ValueError):
        return False
    return True


def mask_fingerprints(b):
    return re.sub(rb'"fingerprint": "[0-9a-f]+"', b'"fingerprint": ""', b)


# ---- comparison ---------------------------------------------------------------------------------------------

def locate(led, base_files, f, cand):
    """Name the splice that is missing or altered, or the change outside every splice."""
    for x in led['splices']:
        if x['file'] == f and expected(led, base_files, f, skip=(x['id'],)) == cand:
            return 'missing ledgered change %s (the old text is still there)' % x['id']
    exp = expected(led, base_files, f)
    p = 0
    while p < min(len(exp), len(cand)) and exp[p] == cand[p]:
        p += 1
    q = 0
    while q < min(len(exp), len(cand)) - p and exp[-1 - q] == cand[-1 - q]:
        q += 1
    # map expected coordinates of each splice
    shift, spans = 0, []
    for x in sorted((y for y in led['splices'] if y['file'] == f), key=lambda y: y['start']):
        s = x['start'] + shift
        nl = len(x['new'].encode('utf-8'))
        spans.append((s, s + nl, x['id']))
        shift += nl - (x['end'] - x['start'])
    hit = [i for s, e, i in spans if s <= len(exp) - q and p <= e]
    line = exp[:p].count(b'\n') + 1
    if hit:
        return 'ledgered change %s altered (first difference at byte %d, line %d)' % (','.join(hit), p, line)
    return 'unauthorized change outside every splice at byte %d, line %d' % (p, line)


def compare(led, base_files, cand):
    bad, derived = [], []
    files = led['files']
    for f in sorted(set(base_files) | set(cand)):
        b, c = base_files.get(f), cand.get(f)
        if f.startswith(REC):
            if b is not None and c != b:
                bad.append('%s: a record file present at the base is changed or deleted' % f)
            continue
        if any(re.match(p, f) for p, _ in DERIVED):
            if b != c:
                derived.append(f)
            continue
        if b is None:
            bad.append('%s: file added outside the record directory' % f); continue
        if c is None:
            bad.append('%s: file deleted' % f); continue
        if f in files:
            exp = expected(led, base_files, f)
            cc, ee = (mask_fingerprints(c), mask_fingerprints(exp)) if f == COVERAGE else (c, exp)
            if cc != ee:
                bad.append('%s: %s' % (f, locate(led, base_files, f, c)))
            if not structural(f, b, c):
                bad.append('%s: structural change outside string constants or comments' % f)
        elif c != b:
            bad.append('%s: unauthorized change in a file the ledger does not touch' % f)
    return bad, derived


def self_test(led, base_files):
    ok = True

    def expect(cond, msg):
        nonlocal ok
        print('  %s %s' % ('ok ' if cond else 'BAD', msg))
        ok = ok and cond
    good = dict(base_files)
    for f in led['files']:
        good[f] = expected(led, base_files, f)
    bad, _ = compare(led, base_files, good)
    expect(not bad, 'positive control: base plus exactly the ledger passes (%d files, %d splices)' % (len(led['files']), len(led['splices'])))
    ids = {x['id']: x for x in led['splices']}

    def mut(name, change, want):
        c = dict(good); change(c)
        b, _ = compare(led, base_files, c)
        expect(any(want in x for x in b), '%s: fails with "%s"' % (name, want))
    for i in ('D224', 'D121', 'D302', 'D262'):
        f = ids[i]['file']
        mut('MT-missing-%s (one ledgered change not made)' % i,
            lambda c, f=f, i=i: c.__setitem__(f, expected(led, base_files, f, skip=(i,))), 'missing ledgered change %s' % i)
    mut('MT-altered-D229 (a replacement differs by one word)',
        lambda c: c.__setitem__('papers/Main.md', c['papers/Main.md'].replace(ids['D229']['new'].encode()[:60], ids['D229']['new'].encode()[:60].replace(b' ', b'  ', 1), 1)),
        'ledgered change D229 altered')
    mut('MT-extra-in-ledgered-file (a word added to papers/Main.md outside every splice)',
        lambda c: c.__setitem__('papers/Main.md', c['papers/Main.md'].replace(b'\n', b' extra\n', 1)), 'unauthorized change outside every splice')
    mut('MT-extra-in-untouched-file (a comment added to tools/release_gate.py)',
        lambda c: c.__setitem__('tools/release_gate.py', c['tools/release_gate.py'] + b'\n# extra\n'), 'unauthorized change in a file the ledger does not touch')
    mut('MT-guard-code (a guard operator changed outside its literals)',
        lambda c: c.__setitem__('verification/lean/edge_rigidity_probe.py', c['verification/lean/edge_rigidity_probe.py'].replace(b'ok6 &= ', b'ok6 |= ', 1)),
        'structural change outside string constants or comments')
    mut('MT-lean-code (a Lean definition changed)',
        lambda c: c.__setitem__('verification/lean-mathlib/OIBridge/HexLatticeGas.lean',
                                c['verification/lean-mathlib/OIBridge/HexLatticeGas.lean'].replace(b'def hexGas', b'def hexGas2', 1)),
        'structural change outside string constants or comments')
    mut('MT-added-file', lambda c: c.__setitem__('papers/New.md', b'x'), 'file added outside the record directory')
    mut('MT-deleted-file', lambda c: c.pop('papers/SM.md'), 'file deleted')
    b2 = dict(base_files); b2[REC + 'PREREG.md'] = b'frozen'
    c = dict(good); c[REC + 'PREREG.md'] = b'frozen, edited'
    expect(any('record file present at the base is changed' in x for x in compare(led, b2, c)[0]),
           'MT-record-edited (a record file present at the base changed): fails')
    c = dict(good); c[REC + 'RESULT.md'] = b'execution record'
    expect(not compare(led, base_files, c)[0], 'a new execution record under the round directory passes')
    mut('MT-coverage-beyond-fingerprints (a coverage-ledger field other than a fingerprint changed)',
        lambda c: c.__setitem__(COVERAGE, c[COVERAGE].replace(b'"kernel": "GAP"', b'"kernel": "K3"', 1)), COVERAGE)
    c = dict(good); c[COVERAGE] = re.sub(rb'"fingerprint": "[0-9a-f]+"', b'"fingerprint": "0000000000000000"', c[COVERAGE], count=1)
    expect(not compare(led, base_files, c)[0], 'a re-affirmed coverage fingerprint alone passes')
    c = dict(good); c['papers/Main.tex'] = b'regenerated'
    b, d = compare(led, base_files, c)
    expect(not b and d == ['papers/Main.tex'], 'a derived path is reported for its recipe, not as a splice failure')
    t = json.loads(json.dumps(led)); t['splices'][0]['old_sha256'] = '0' * 64
    expect(bool(validate_ledger(t, base_files)), 'a ledger whose old-text hash does not match the base is rejected')
    t = json.loads(json.dumps(led)); t['splices'][1]['start'] = t['splices'][0]['start']
    expect(bool(validate_ledger(t, base_files)), 'a ledger with a moved or overlapping span is rejected')
    print('self-test %s' % ('PASS' if ok else 'FAIL'))
    return ok


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--build-ledger', action='store_true')
    g.add_argument('--verify-ledger', action='store_true')
    g.add_argument('--commit')
    g.add_argument('--tree')
    g.add_argument('--self-test', action='store_true')
    ap.add_argument('--base', help='compare against REV instead of the ledger base; every ledgered file must be '
                                   'byte-identical there to the ledger base (otherwise the ledger is re-cut)')
    a = ap.parse_args()
    edits = json.load(open(EDITS, encoding='utf-8'))
    if a.build_ledger:
        base = tree_of(edits['drafting_base'])
        led = build_ledger(edits, base)
        open(LEDGER, 'w', encoding='utf-8').write(json.dumps(led, indent=1, ensure_ascii=False) + '\n')
        print('ledger: %d splices in %d files at %s; sha256 %s' % (len(led['splices']), len(led['files']), led['base'][:12],
                                                                  sha(open(LEDGER, 'rb').read())))
        return
    led = json.load(open(LEDGER, encoding='utf-8'))
    base = tree_of(a.base or led['base'])
    bad = validate_ledger(led, base)
    print('ledger: %d splices in %d files at %s; sha256 %s; %d validation findings'
          % (len(led['splices']), len(led['files']), led['base'][:12], sha(open(LEDGER, 'rb').read()), len(bad)))
    for x in bad:
        print('  LEDGER ' + x)
    if a.verify_ledger:
        re_led = build_ledger(edits, base)
        same = re_led['splices'] == led['splices'] and re_led['files'] == led['files'] and re_led['edits_sha256'] == led['edits_sha256']
        print('ledger re-derived from edits.json: %s' % ('identical' if same else 'DIFFERENT'))
        ok = same and not bad
    elif a.self_test:
        ok = self_test(led, base) and not bad
    else:
        cand = tree_of(a.commit) if a.commit else tree_dir(a.tree)
        fails, derived = compare(led, base, cand)
        print('candidate: %d findings; derived paths changed (checked by their recipe): %d' % (len(fails), len(derived)))
        for x in fails:
            print('  FAIL ' + x)
        for x in derived:
            print('  DERIVED ' + x)
        ok = not fails and not bad
    print('RESULT ' + ('PASS' if ok else 'FAIL'))
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
