#!/usr/bin/env python3
"""Render MATRIX.md, the human-readable claim-to-proof matrix, from matrix.json.

Usage: python3 matrix/scripts/render_matrix.py [--check]

Reads matrix.json and inventory/claims.json from the audit directory (two levels above this
script) and writes MATRIX.md beside them. With --check it writes nothing and exits 1 if the
checked-in MATRIX.md differs from what the data renders, so the table cannot drift from the data.

Every count, table cell and dependency block is computed from the JSON. The only hand-written
content is the list of multi-step results that get a dependency block (BLOCKS) and the object
descriptions in HEADER_OBJECTS.
"""
import json
import re
import sys
from collections import Counter, OrderedDict
from pathlib import Path

AUDIT = Path(__file__).resolve().parents[2]
MATRIX_JSON = AUDIT / "matrix.json"
CLAIMS_JSON = AUDIT / "inventory" / "claims.json"
OUT = AUDIT / "MATRIX.md"

