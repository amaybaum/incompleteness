STATUS_ORDER = ["unsupported", "open", "conjecture", "conditional", "numerical", "calibration",
                "exhaustive-exact", "proved-paper", "proved-kernel"]
LINK_STATUS_ORDER = ["refuted", "unsupported", "open", "conditional", "proved"]
LAYER_ORDER = ["none", "conjecture", "numerical", "literature", "paper-derivation", "exhaustive-computation",
               "exact-algebra", "kernel"]
VERDICT_ORDER = ["OVERCLAIM", "UNSUPPORTED", "UNDERCLAIM", "MISCITED", "IMPRECISE", "FAITHFUL"]
CONSISTENT = re.compile(r"^(same claim, consistent|consistent|not a contradiction|same convention difference; "
                        r"not a contradiction)", re.I)


def key(rid):
    m = re.match(r"I-(\d+)(?:\.([a-z]))?$", rid)
    return (int(m.group(1)), m.group(2) or "")


def cell(s):
    if s is None:
        return ""
    s = str(s).replace("\r", " ").replace("\n", " ")
    return s.replace("|", "\\|").strip()


def short_site(site):
    """papers/Main.md:16@eae01647 (title) -> Main:16; lean:OIBridge/X.lean:12:decl -> X:12."""
    s = site.split(" (")[0]
    s = re.sub(r"@[0-9a-f]{7,40}", "", s)
    m = re.match(r"lean:(?:OIBridge/)?([A-Za-z0-9_]+)\.lean:(\d+)", s)
    if m:
        return f"{m.group(1)}:{m.group(2)}"
    s = re.sub(r"^papers/", "", s)
    s = re.sub(r"^book/", "", s)
    s = re.sub(r"\.md(?=:)", "", s)
    s = re.sub(r"^verification/programmes/black-hole-information/", "BH/", s)
    return s


def claim_texts():
    rows = json.loads(CLAIMS_JSON.read_text())
    out = {}
    for r in rows:
        out[r["id"]] = r["claim"]
        d = r.get("direction") or {}
        for sc in d.get("sub_claims", []):
            out[sc["id"]] = f"[{sc.get('label', '')}] {sc['claim']}"
    return out


def contradiction_sites(r):
    sites = []
    for c in r.get("contradictions") or []:
        if CONSISTENT.match(c.get("nature", "").strip()):
            continue
        s = short_site(c["site"])
        if s not in sites:
            sites.append(s)
    return sites


def render(data, claims):
    rows = sorted(data["rows"], key=lambda r: key(r["id"]))
    byid = {r["id"]: r for r in rows}
    verdicts = Counter(r["verdict"] for r in rows)
    statuses = Counter(r["proof_status"] for r in rows)
    # Control: the counts recorded by the merge must equal the counts of the rows themselves.
    if dict(verdicts) != data["verdicts"] or dict(statuses) != data["proof_status"]:
        raise SystemExit("control failed: matrix.json summary counts disagree with its rows")
    levels = Counter(r.get("evidence_level") for r in rows)
    if dict(levels) != data.get("evidence_levels"):
        raise SystemExit("control failed: matrix.json evidence-level counts disagree with its rows")
    # Control: every row's level and basis must equal evidence.json's (E4_aggregate.py), row by row.
    ev = json.loads((MATRIX_JSON.parent / "evidence.json").read_text())["claims"]
    drift = [r["id"] for r in rows if (r.get("evidence_level"), r.get("evidence_basis"))
             != (ev.get(r["id"], {}).get("evidence_level"), ev.get(r["id"], {}).get("basis"))]
    if drift or set(ev) != set(byid):
        raise SystemExit(f"control failed: matrix.json evidence levels disagree with evidence.json: {drift[:10]}")
    missing_claims = [r["id"] for r in rows if r["id"] not in claims]
    if missing_claims:
        raise SystemExit(f"control failed: rows without a claim text: {missing_claims}")
    for _, title, ids, _ in BLOCKS:
        for i in ids:
            if i not in byid:
                raise SystemExit(f"control failed: block {title!r} names unknown row {i}")

    sections = OrderedDict()
    for r in rows:
        sections.setdefault(r["section"], []).append(r)

    L = []
    L.append("# Claim-to-proof matrix: `papers/Introduction.md`")
    L.append("")
    for h in HEADER_OBJECTS:
        L.append(f"- {h}")
    L.append("")
    L.append(f"**Rows:** {len(rows)} ({sum(1 for r in rows if '.' not in r['id'])} claims and "
             f"{sum(1 for r in rows if '.' in r['id'])} directional sub-claims). "
             f"Merge: {len(data.get('duplicates', []))} duplicate rows dropped "
             f"({', '.join(d['id'] + ' kept from ' + d['kept'] for d in data.get('duplicates', []))}); "
             f"missing {len(data.get('missing', []))}, extra {len(data.get('extra', []))}.")
    L.append("")
    L.append("| Verdict | Rows |")
    L.append("|---|--:|")
    for v in VERDICT_ORDER:
        L.append(f"| {v} | {verdicts.get(v, 0)} |")
    L.append(f"| **Total** | **{len(rows)}** |")
    L.append("")
    L.append("| Proof status (weakest link) | Rows |")
    L.append("|---|--:|")
    for s in reversed(STATUS_ORDER):
        L.append(f"| {s} | {statuses.get(s, 0)} |")
    L.append("")
    L.append("| Evidence level (step 7, `EVIDENCE.md`) | Rows |")
    L.append("|---|--:|")
    for lv in ("reproduced", "certificate-checked", "traced-only", "failed"):
        L.append(f"| {lv} | {levels.get(lv, 0)} |")
    L.append("")
    L.append("Verdicts by section (*Rows* counts every row of the section; the other columns count its "
             "non-FAITHFUL verdicts):")
    L.append("")
    L.append("| Section | Rows | " + " | ".join(v for v in VERDICT_ORDER if v != "FAITHFUL") + " |")
    L.append("|---|--:|" + "--:|" * (len(VERDICT_ORDER) - 1))
    for sec, rs in sections.items():
        c = Counter(r["verdict"] for r in rs)
        L.append(f"| {sec} | {len(rs)} | " + " | ".join(str(c.get(v, 0) or "") for v in VERDICT_ORDER
                                                        if v != "FAITHFUL") + " |")
    L.append("")
    L.append("**Columns.** *Claim* is the normalized statement of `inventory/claims.json` (the verbatim span is in "
             "`matrix.json`). *Strongest verified source* is the mapper's `strongest_verified_source`. "
             "*Assumptions* are the row's `required_assumptions`, with `conditional_on` prefixed when present. "
             "*Proof status* is the weakest link of the row's chain. *Contradictions* lists the corpus sites in the "
             "row's `contradictions` whose recorded nature is not 'consistent' (short form `file:line` at `eae01647`, "
             "`Module:line` for Lean). Non-FAITHFUL verdicts are in bold. Status levels: proved-kernel, proved-paper, "
             "conditional, calibration, exhaustive-exact (an exhaustive enumeration in exact arithmetic over a stated finite domain), "
             "numerical (floating-point or otherwise inexact evidence), conjecture, open, unsupported (PLAN.md, step 3). "
             "*Evidence* is the row's step-7 evidence level: reproduced, certificate-checked, traced-only or failed, "
             "by the rule in `EVIDENCE.md`.")
    L.append("")
    L.append("Dependency blocks follow the table of the section that states each multi-step result. Each block "
             "states the proof status of every row it covers and names the weakest, which governs the result as the "
             "Introduction states it, and the hypotheses the rows are conditional on. It then lists every distinct "
             "link of those rows with its source, layer, status and hypotheses, ordered from the weakest support to "
             "the strongest. A chain can list alternative supports for one step (a paper proof beside a kernel "
             "proof, or a special case beside the general form), so the first line is the weakest support recorded, "
             "not necessarily a step the result needs; the governing status is the weakest row status.")
    L.append("")

    blocks_by_sec = OrderedDict()
    for b in BLOCKS:
        blocks_by_sec.setdefault(b[0], []).append(b)

    for sec, rs in sections.items():
        L.append(f"## {sec}")
        L.append("")
        L.append("| id | line | claim | strongest verified source | assumptions | proof status | verdict | "
                 "contradictions | evidence |")
        L.append("|---|--:|---|---|---|---|---|---|---|")
        for r in rs:
            assum = list(r.get("required_assumptions") or [])
            cond = r.get("conditional_on")
            if cond:
                assum = [f"conditional on: {'; '.join(cond)}"] + assum
            line = str(r["line"]) + (f"–{r['line_end']}" if r.get("line_end") else "")
            v = r["verdict"]
            v = v if v == "FAITHFUL" else f"**{v}**"
            L.append("| " + " | ".join([
                r["id"], line, cell(claims[r["id"]]), cell(r.get("strongest_verified_source")),
                cell("; ".join(assum)), r["proof_status"], v, cell(", ".join(contradiction_sites(r))),
                r["evidence_level"]]) + " |")
        L.append("")
        for _, title, ids, scope in blocks_by_sec.get(sec, []):
            L.extend(render_block(title, ids, scope, byid))
    return "\n".join(L).rstrip() + "\n"


def render_block(title, ids, scope, byid):
    L = [f"### Dependency block: {title}", ""]
    if scope:
        L.append(scope)
        L.append("")
    rstat = [(i, byid[i]["proof_status"], byid[i]["verdict"]) for i in ids]
    weakest = min(rstat, key=lambda t: STATUS_ORDER.index(t[1]))[1]
    L.append("Rows: " + "; ".join(f"{i} {s}" + ("" if v == "FAITHFUL" else f" ({v})") for i, s, v in rstat) + ".")
    L.append(f"Weakest row status, which governs: **{weakest}** "
             f"({', '.join(i for i, s, _ in rstat if s == weakest)}).")
    conds = []
    for i in ids:
        for c in byid[i].get("conditional_on") or []:
            if c not in conds:
                conds.append(c)
    if conds:
        L.append("Conditional on: " + "; ".join(conds) + ".")
    L.append("")
    links = OrderedDict()
    for i in ids:
        for c in byid[i]["chain"]:
            k = (c["source"], c["link"])
            e = links.setdefault(k, {"c": c, "rows": [], "hyp": []})
            e["rows"].append(i)
            for h in c.get("hypotheses") or []:
                if h not in e["hyp"]:
                    e["hyp"].append(h)

    def strength(e):
        c = e["c"]
        ls = c["link_status"] if c["link_status"] in LINK_STATUS_ORDER else "open"
        ly = c["layer"] if c["layer"] in LAYER_ORDER else "none"
        return (LINK_STATUS_ORDER.index(ls), LAYER_ORDER.index(ly))

    ordered = sorted(links.values(), key=strength)
    L.append("| # | link | source | layer | status | hypotheses | rows |")
    L.append("|--:|---|---|---|---|---|---|")
    for n, e in enumerate(ordered, 1):
        c = e["c"]
        st = c["link_status"] if c["link_status"] == "proved" else f"**{c['link_status']}**"
        L.append("| " + " | ".join([str(n), cell(c["link"]), cell(c["source"]), c["layer"], st,
                                    cell("; ".join(e["hyp"])), ", ".join(e["rows"])]) + " |")
    L.append("")
    return L


def main():
    data = json.loads(MATRIX_JSON.read_text())
    text = render(data, claim_texts())
    if "--check" in sys.argv[1:]:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("MATRIX.md differs from the rendering of matrix.json")
            sys.exit(1)
        print("MATRIX.md matches matrix.json")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(AUDIT)}: {len(data['rows'])} rows, {len(BLOCKS)} dependency blocks")


if __name__ == "__main__":
    main()
