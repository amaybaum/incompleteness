"""Independent exact checks for mc2 (SymPy). Own constructions; nothing imported from the node's probes."""
import sys, itertools
import sympy as sp
from sympy import Matrix, I, sqrt, cos, sin, exp, eye, zeros, Rational, symbols, pi
R = []
def chk(n, ok): R.append((n, bool(ok))); print(('PASS ' if ok else 'FAIL ') + n)
def z(M): return all(sp.simplify(sp.expand(sp.expand_complex(x))) == 0 for x in M)
def kr(A, B): return Matrix(sp.kronecker_product(A, B))
def E(d, a, b): M = zeros(d, d); M[a, b] = 1; return M
def Xab(d, a, b): return eye(d) - E(d, a, a) - E(d, b, b) + E(d, a, b) + E(d, b, a)
phi = symbols('phi', real=True)
# 1. phase gadget, own order (data first, ancilla second): data-controlled ancilla flip on subset s
d = 3; s = [0, 2]
pI = Matrix([1, I]) / sqrt(2); w = Matrix([cos(phi), sin(phi)]); wp = Matrix([-sin(phi), cos(phi)])
C = zeros(2 * d, 2 * d)
for x in range(d):
    for a in (0, 1):
        a2 = a ^ (1 if x in s else 0); C[2 * x + a2, 2 * x + a] = 1
att = kr(eye(d), pI)
Bw = kr(eye(d), w.T) * C * att; Bwp = kr(eye(d), wp.T) * C * att
D = sp.diag(*[(I * exp(-2 * I * phi)) if x in s else 1 for x in range(d)])
Zs = sp.diag(*[-1 if x in s else 1 for x in range(d)])
chk('G1 phase gadget (d=3, s={0,2}): branch w = e^{i phi}/sqrt2 * D_s(phi), D_s = diag(1 off s, i e^{-2i phi} on s)',
    z(Bw - exp(I * phi) / sqrt(2) * D))
chk('G2 branch w_perp = i e^{i phi}/sqrt2 * Z_s D_s(phi)', z(Bwp - I * exp(I * phi) / sqrt(2) * Zs * D))
chk('G3 at phi = 1 the relative phase is pi/2 - 2; at phi = pi/4 (X basis) D_s = I',
    z(D.subs(phi, pi / 4) - eye(d)) and sp.simplify(sp.arg(D[0, 0].subs(phi, 1)) - (pi / 2 - 2)) == 0)
# 2. A6: corrected gadget channel and its distance; mixture of unitaries
n = symbols('n', positive=True, integer=True); p = 2 ** (-n)
Xs = Matrix(d, d, symbols('x0:%d' % (d * d)))
Ad = lambda U: U * Xs * U.H
lhs = Ad(D) / 2 + (((1 - p) * Ad(Zs * Zs * D) + p * Ad(Zs * D))) / 2
chk('G4 heralded D-branch + (Z_s D-branch followed by Phi_n[Z_s]) = (1-2^{-n-1}) Ad D + 2^{-n-1} Ad(Z_s D)',
    z(lhs - ((1 - p / 2) * Ad(D) + p / 2 * Ad(Zs * D))))
# 3. Lie algebra generated by {i X_ab} U {i P_c}, own closure (real dimension), d = 2..6; and {i X_ab} alone
def vec(M):  # real coordinates
    return [sp.re(x) for x in M] + [sp.im(x) for x in M]
def liedim(gens, dd):
    basis = []; mat = Matrix(0, 2 * dd * dd, [])
    def add(M):
        nonlocal mat
        v = Matrix([vec(M)])
        m2 = mat.col_join(v)
        if m2.rank() > mat.rank():
            mat = m2; basis.append(M); return True
        return False
    for g in gens: add(g)
    changed = True
    while changed:
        changed = False
        for A, B in itertools.combinations(list(basis), 2):
            if add(sp.expand(A * B - B * A)): changed = True
    return len(basis)
for dd in (2, 3, 4, 5, 6):
    gx = [I * Xab(dd, a, b) for a, b in itertools.combinations(range(dd), 2)]
    gp = [I * E(dd, c, c) for c in range(dd)]
    d1 = liedim(gx, dd); d2 = liedim(gx + gp, dd)
    chk('G5 d=%d: Lie{iX_ab} real dim %d (= (d-1)^2 + [d>2 ? 0] check), Lie{iX_ab, iP_c} real dim %d = d^2' % (dd, d1, d2),
        d2 == dd * dd)
# with only ONE phase generator (single configuration) -- is that already enough? (relevant to what the dense step needs)
for dd in (2, 3, 4):
    gx = [I * Xab(dd, a, b) for a, b in itertools.combinations(range(dd), 2)]
    print('    info d=%d: Lie{iX_ab, iP_0} real dim %d' % (dd, liedim(gx + [I * E(dd, 0, 0)], dd)))
# 4. identities for d up to 7
ok = True
for dd in range(2, 8):
    for a, b in itertools.permutations(range(dd), 2):
        Pa = E(dd, a, a); X = Xab(dd, a, b)
        ok &= z(Pa * X - X * Pa - (E(dd, a, b) - E(dd, b, a)))
        ok &= z(X - sum((E(dd, c, c) for c in range(dd) if c not in (a, b)), zeros(dd, dd)) - (E(dd, a, b) + E(dd, b, a)))
chk('G6 [P_a, X_ab] = E_ab - E_ba and X_ab - sum_{c!=a,b} P_c = E_ab + E_ba, d = 2..7, all ordered pairs', ok)
# 5. Choi order step of the word lemma, exact on a 2x2 instance with a symbolic K
k = symbols('k0:4'); K = Matrix(2, 2, k); V = Matrix([[1, 0], [0, -1]])
v = Matrix([1, 0, 0, -1])                      # |V>> (row-stacked)
kv = Matrix(list(K))
# A <= lam |v><v| with A = |kv><kv| PSD forces kv in span(v): take x = component of kv orthogonal to v
x = kv - (v.H * kv)[0] / 2 * v
val = (x.H * (2 * v * v.H - kv * kv.H) * x)[0]   # = -|<x|kv>|^2 = -||x||^4
chk('G7 order step: <x|(lam|v><v| - |K>><<K|)|x> = -||x||^4 for x the part of vec K orthogonal to vec V (lam arbitrary)',
    sp.simplify(sp.expand(val + ((x.H * x)[0]) ** 2)) == 0)
fails = [m for m, o in R if not o]
print('SUMMARY', len(R) - len(fails), 'PASS', len(fails), 'FAIL'); sys.exit(1 if fails else 0)
