# ---- first-light layer sweep on the 3D lattice (generic, any source set on the radius-T shell) ----
def Hv(a,b,d): return b,d,a^(b&d)
def sweep(n,T,srcs):
    vs,full=vars_tt(n); W=len(full)
    layer={}
    for pos,f,(const,vset) in srcs:
        assert sum(map(abs,pos))==T
        val=full.copy() if const else np.zeros(W,np.uint64)
        for j in vset: val^=vs[j]
        cell=layer.setdefault(pos,[np.zeros(W,np.uint64) for _ in range(3)]); cell[f]^=val
    for l in range(T-1,-1,-1):
        acc={}
        for y,v in layer.items():
            for k in range(3):
                for s in (-1,1):
                    z=list(y); z[k]+=s; z=tuple(z)
                    if sum(map(abs,z))==l:
                        a=acc.setdefault(z,[np.zeros(W,np.uint64) for _ in range(3)])
                        for f in range(3): a[f]^=v[f]
        layer={z:list(Hv(*v)) for z,v in acc.items()}
        layer={z:v for z,v in layer.items() if any(x.any() for x in v)}
    out=layer.get((0,0,0),[np.zeros(W,np.uint64)]*3)
    want=full.copy()
    for v in vs: want&=v
    return bool(np.array_equal(out[2],want)),degree(out[2],n)[0]
# ---- rank of the input -> source map ----
def rank_inputs(srcs,n):
    rows=[sum(1<<j for j in vset) for pos,f,(c,vset) in srcs]
    piv={}
    for v in rows:
        while v:
            h=v.bit_length()-1
            if h in piv: v^=piv[h]
            else: piv[h]=v; break
    return len(piv)
