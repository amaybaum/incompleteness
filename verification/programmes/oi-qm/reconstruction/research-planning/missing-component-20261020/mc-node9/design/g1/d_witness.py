# ERT relative to other elementary bases: basis B of V; the value-0 lifts of B fixed by a dictionary; a
# generator relation (Z_j for reads/initial state) gets its value-0 lift as the product of commuting basis lifts.
def express(u, B):
    for c in range(16):
        s = 0
        for i in range(4):
            if (c >> i) & 1: s ^= B[i]
        if s == u: return [B[i] for i in range(4) if (c >> i) & 1]
from itertools import combinations
for m in (2, 4):
    E = Ext(n, m, bilinear_beta(n, m, real_pauli_coeff(n, m//2)))
    stats = Counter(); qm_bases = []
    for B in combinations(range(1, 16), 4):
        # independence
        span = {0}
        for b in B: span |= {x ^ b for x in span}
        if len(span) != 16: continue
        if any(not E.involution_lifts(b) for b in B): stats["basis has a non-recordable element"] += 1; continue
        good_any = False; amb = False
        for choice in product(*[E.involution_lifts(b) for b in B]):
            dB = dict(zip(B, choice))
            def prodlift(u):
                fs = [dB[b] for b in express(u, list(B))]
                if any(E.mul[x][y] != E.mul[y][x] for x in fs for y in fs): return None
                p = 0
                for x in fs: p = E.mul[p][x]
                return p
            # full dictionary on the standard generators derived from B
            dic = {g: prodlift(g) for g in [1 << i for i in range(4)]}
            if any(v is None or E.sq(v) != 0 for v in dic.values()): amb = True; break
            L = {}
            for nm, S in R.items():
                imgs = [prodlift(S[b]) for b in B]
                if any(v is None for v in imgs): amb = True; break
                # automorphism with phi(dB[b]) = imgs
                gi = {}
                ok = True
                # build via the standard-generator dictionary: phi(dic[e]) = prod over basis expression of images
                imgs_std = []
                for e in [1 << i for i in range(4)]:
                    fs = express(e, list(B)); p = 0
                    for bb in fs: p = E.mul[p][imgs[list(B).index(bb)]]
                    imgs_std.append(p)
                phi = lift_from_dict_images(E, S, dic, imgs_std)
                if phi is None or any(phi[dB[b]] != imgs[i] for i, b in enumerate(B)): amb = True; break
                L[nm] = phi
            if amb: break
            T = ExtTheory(E, dic, ext_theory_ops(E, dic, L))
            if equivalent(T, qm, ALPH_FULL)[0]: good_any = True
            else: stats["ERT well-defined, theory != QM"] += 1; good_any = None; break
        if amb: stats["ERT ill-defined (ambiguous / not an automorphism / dictionary)"] += 1
        elif good_any: stats["ERT well-defined, = QM for every dictionary"] += 1; qm_bases.append(B)
    names = {XB(0): "XA", ZB(0): "ZA", XB(1): "XB", ZB(1): "ZB"}
    def lab(u): return "*".join(names[1 << i] for i in range(4) if (u >> i) & 1)
    print("C=Z%d: elementary-basis choices (840 unordered bases of V): %s" % (m, dict(stats)))
    print("      bases on which ERT is well-defined and gives QM:", [[lab(b) for b in B] for B in qm_bases])

# (d5) the 4 QM-equivalent lift triples are the ERT triple conjugated by the record-value twists that fix the
# preparation and the readouts (flipp_A^a flipp_B^b <-> Z_A^a Z_B^b).
for m in (2, 4):
    E = Ext(n, m, bilinear_beta(n, m, real_pauli_coeff(n, m//2))); d = default_dict(E)
    ert = [ert_lift(E, R[nm], d)[0] for nm in ("swap0", "swap1", "couple")]
    def conj(t, phi):
        tinv = [0]*E.size
        for g in range(E.size): tinv[t[g]] = g
        return tuple(t[phi[tinv[g]]] for g in range(E.size))
    conjs = set()
    for a, b in product((0, 1), repeat=2):
        w = (ZB(0) if a else 0) ^ (ZB(1) if b else 0); t = value_twist(E, w)
        conjs.add(tuple(conj(t, p) for p in ert))
    L = {nm: E.lifts(S, 1) for nm, S in R.items()}
    qmlike = set()
    for p0, p1, pc in product(L["swap0"], L["swap1"], L["couple"]):
        T = ExtTheory(E, d, ext_theory_ops(E, d, {"swap0": p0, "swap1": p1, "couple": pc}))
        if equivalent(T, qm, ALPH_FULL)[0]: qmlike.add((p0, p1, pc))
    print("C=Z%d: QM-equivalent triples == {ERT conjugated by Z_A^a Z_B^b value twists}: %s (%d)" % (m, qmlike == conjs, len(conjs)))
