from collections import Counter
n = 2; R = card_relmaps(n)
card = CardTheory(n); qm = QMTheory(n)
def fmt(d): return "{" + ",".join("%d:%s" % (o, p) for o, p in sorted(d.items())) + "}"
def outcome_class(d):
    if d == {1: 1}: return "QM(1 certain)"
    if d == {0: 1}: return "cards(0 certain)"
    return "other " + fmt(d)

for m in (2, 4):
    print("=" * 100); print("C = Z%d" % m)
    for eps, b in reps(n, m):
        E = Ext(n, m, b); tag = "".join(map(str, eps))
        d = default_dict(E)
        if tag not in ("0000", "0001"): continue
        Ls = {nm: E.lifts(S, 1) for nm, S in R.items()}
        print("-- class %s: lifts swap0/swap1/couple = %d/%d/%d ; elementary relations without an involutive lift: %s"
              % (tag, len(Ls["swap0"]), len(Ls["swap1"]), len(Ls["couple"]),
                 [k for k, v in d.items() if v is None]))
        if any(v is None for v in d.values()):
            print("   -> no record state can hold z_B: initial state q_A=q_B=0 and the read of q_B are undefined; class excluded by (c)")
            continue
        # (d1) witnesses over every (swap0 lift, couple lift)
        for cact_set, label in (((1,), "trivial on C"), ((1, -1), "trivial or inverting on C")):
            if m == 2 and cact_set != (1,): continue
            L0 = [p for c in cact_set for p in E.lifts(R["swap0"], c)]
            LC = [p for c in cact_set for p in E.lifts(R["couple"], c)]
            cnt6 = Counter(); cnt67 = Counter()
            for p0, pc in product(L0, LC):
                T = ExtTheory(E, d, ext_theory_ops(E, d, {"swap0": p0, "couple": pc}))
                o6 = outcome_class(run_word(T, W6, "read1")); o7 = outcome_class(run_word(T, W7, "read1"))
                cnt6[o6] += 1; cnt67[(o6, o7)] += 1
            print("   witnesses over %d x %d (swap_A, couple) lifts [%s]:" % (len(L0), len(LC), label))
            for k, v in sorted(cnt67.items()): print("      W6=%-18s W7=%-18s : %d" % (k[0], k[1], v))
        # (d2) complete transition table over every (swap0, swap1, couple) lift triple
        for cact_set, label in (((1,), "trivial on C"), ((1, -1), "trivial or inverting on C")):
            if m == 2 and cact_set != (1,): continue
            L = {nm: [p for c in cact_set for p in E.lifts(S, c)] for nm, S in R.items()}
            res = Counter(); qmlike = []
            for p0, p1, pc in product(L["swap0"], L["swap1"], L["couple"]):
                T = ExtTheory(E, d, ext_theory_ops(E, d, {"swap0": p0, "swap1": p1, "couple": pc}))
                eq = equivalent(T, qm, ALPH_FULL)
                if eq[0]: res["= QM (full alphabet)"] += 1; qmlike.append((p0, p1, pc)); continue
                ec = equivalent(T, card, ALPH_FULL)
                res["= cards" if ec[0] else "other"] += 1
            print("   full transition table over %d lift triples [%s]: %s" % (
                len(L["swap0"])*len(L["swap1"])*len(L["couple"]), label, dict(res)))
            if qmlike and cact_set == (1,):
                ert = {nm: ert_lift(E, S, d)[0] for nm, S in R.items()}
                print("   the QM-equivalent triple(s) equal the ERT lifts:", [(a == ert["swap0"], b_ == ert["swap1"], c == ert["couple"]) for a, b_, c in qmlike])
        # (d3) the closure (generated operation group) is lift-independent once flips are in the family
        if m == 2:
            def gen_group(gens):
                G = {tuple(range(E.size))}; frontier = list(G)
                while frontier:
                    nf = []
                    for g in frontier:
                        for h in gens:
                            k = tuple(h[g[x]] for x in range(E.size))
                            if k not in G: G.add(k); nf.append(k)
                    frontier = nf
                return frozenset(G)
            flips = [value_twist(E, w) for w in (XB(0), XB(1), ZB(0), ZB(1))]
            ref = None; same = 0; tot = 0
            for p0, p1, pc in product(Ls["swap0"], Ls["swap1"], Ls["couple"]):
                if (tot % 273) == 0 or tot < 3:
                    G = gen_group([p0, p1, pc] + flips)
                    if ref is None: ref = G
                    same += (G == ref)
                tot += 1
            print("   group generated by (lifts + card flips): |G| = %d; identical for %d of %d sampled triples (every 273rd of %d)"
                  % (len(ref), same, (tot + 272)//273 + 2, tot))

