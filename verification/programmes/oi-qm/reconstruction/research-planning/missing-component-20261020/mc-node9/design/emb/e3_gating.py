"""E3: external selection of which couplings act at each step (exact, F2).  This is AP-2 (contact
timing) supplied as an external control resource; nothing here is generated by the lattice.

Operation class.  At every step an external controller picks an edge subset S of a base graph
and the displayed update runs with adjacency S (an idle site, with no active edge, maps
(u, v) -> (v, u)).  Every such step is symplectic.  The selection is open-loop (a fixed word):
an adaptive selection would need an external memory of readings, i.e. K-EXTHIST.  No free visible
permutations.  Memory = the final visible configuration only, unless a line says K-EXTHIST.

Part 1: exhaustive words up to a depth bound on small arenas (distinct products per depth).
Part 2: W4 expressed in E3 with one reused pointer and embedded memory sites.
"""
import sys
import time
from itertools import combinations
from collections import Counter
from emb_core import lattice_update, vis_coords, mask_of, post_rank, prior_rank
from f2 import compose, identity, rank

TCAP = float(sys.argv[1]) if len(sys.argv) > 1 else 900.0
T_START = time.time()


def gens(n, base):
    out = []
    for k in range(len(base) + 1):
        for S in combinations(base, k):
            out.append((S, lattice_update(n, S)))
    return out


def evaluate(P, n, R, toy):
    vc = vis_coords(n, R)
    um = ((1 << (2 * n)) - 1) & ~mask_of(vc)
    F = [P[c] for c in vc]
    T = [P[toy], P[n + toy]]
    return 2 ** post_rank(F, T, um), prior_rank(T, um)


def arena(label, n, base, cases, depth, budget):
    G = gens(n, base)
    level = {identity(2 * n): ()}
    best = {c: (5, None, None) for c in cases}   # (support, depth, word) of the best learning hit
    minsup = {c: 4 for c in cases}
    t0 = time.time()
    done = 0
    for d in range(1, depth + 1):
        new = {}
        for P, w in level.items():
            for S, Mg in G:
                Q = compose(Mg, P)
                if Q not in new:
                    new[Q] = w + (S,)
            if time.time() - t0 > budget or time.time() - T_START > TCAP:
                break
        else:
            level = new
            for Q, w in level.items():
                for c in cases:
                    R, toy = c
                    s, pr = evaluate(Q, n, R, toy)
                    minsup[c] = min(minsup[c], s)
                    if s == 1 and pr == 2 and best[c][1] is None:
                        best[c] = (1, d, w)
            done = d
            print(f"  [{label}] depth {d}: {len(level)} distinct products", flush=True)
            continue
        print(f"  [{label}] depth {d}: NOT COMPLETED (budget)", flush=True)
        break
    return done, minsup, best


