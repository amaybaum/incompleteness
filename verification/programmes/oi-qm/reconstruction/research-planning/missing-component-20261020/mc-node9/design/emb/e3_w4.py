"""E3 Part 2: W4 expressed in E3 (external timing, AP-2), one reused pointer, embedded memory.
(e3_gating.py's own Part 2 searched only for an exact even-length site exchange and found none:
the edge-on/edge-off words on two sites generate a group of 12 elements.  Here the store word is
the shortest even-length word whose two-site map is block anti-diagonal: the pointer pair goes
into the memory pair and the memory's clean pair into the pointer, each by an invertible map.)
Every stopping time (every prefix of the word, R1) is evaluated; the conditioning is on every
visible cell present (pointer and all memory sites, R2).
"""
from emb_core import lattice_update, vis_coords, mask_of, post_rank, prior_rank
from f2 import compose, identity

E2 = lattice_update(2, ((0, 1),))
O2 = lattice_update(2, ())
fr = {identity(4): ()}
seen = dict(fr)
for d in range(1, 15):
    nf = {}
    for P, w in fr.items():
        for lab, Mg in (("E", E2), ("O", O2)):
            Q = compose(Mg, P)
            nf.setdefault(Q, w + (lab,))
    fr = nf
    for Q, w in fr.items():
        seen.setdefault(Q, w)
m0, m1 = (1 << 0) | (1 << 2), (1 << 1) | (1 << 3)
cands = sorted((len(w), w) for Q, w in seen.items() if len(w) % 2 == 0
               and all((Q[i] & m0) == 0 for i in (0, 2)) and all((Q[i] & m1) == 0 for i in (1, 3)))
store = cands[0][1]
print(f"  two-site group generated by edge-on/edge-off: {len(seen)} elements")
print("  store word (block anti-diagonal pointer <-> memory, even length):", "".join(store))


def run_word(n, word, R, toy, mem_only):
    vc = vis_coords(n, R)
    um = ((1 << (2 * n)) - 1) & ~mask_of(vc)
    P = identity(2 * n)
    H = [P[c] for c in vc]
    prof = []
    for S in word:
        P = compose(lattice_update(n, S), P)
        F = [P[c] for c in vc]
        H += F
        T = [P[toy], P[n + toy]]
        Fm = [P[c] for c in vis_coords(n, mem_only)]
        prof.append((2 ** post_rank(F, T, um), 2 ** prior_rank(T, um), 2 ** post_rank(Fm, T, um),
                     2 ** post_rank(H, T, um)))
    return prof, P


def w4(fresh, stores=True, reads=True):
    """sites: toy 0, pointer 1, memories 2, 3, 4, bath 5 (fresh: baths 5, 6, 7)."""
    n = 8 if fresh else 6
    baths = [5, 6, 7] if fresh else [5, 5, 5]
    word = []
    for i in range(3):
        word.append(((0, 1), (0, baths[i])) if reads else ())
        for lab in store:
            word.append(((1, 2 + i),) if (lab == "E" and stores) else ())
    return n, word


for fresh in (False, True):
    for stores, reads, label in ((True, True, "W4: read, store, read, store, read, store"),
                                 (False, True, "non-copying: same reads, store steps idle"),
                                 (False, False, "background: every step idle")):
        n, word = w4(fresh, stores, reads)
        prof, P = run_word(n, word, (1, 2, 3, 4), 0, (2, 3, 4))
        fin = prof[-1]
        print(f"  [{'fresh bath per read' if fresh else 'one bath reused'}] {label}: {len(word)} steps")
        print(f"     at the end: toy prior {fin[1]}; support given all visible cells {fin[0]};"
              f" given the 3 memory sites only {fin[2]}; K-EXTHIST {fin[3]}")
        print("     every stopping time t=1..%d, support given all visible cells: %s" % (len(prof), " ".join(str(p[0]) for p in prof)))
        print("     every stopping time, prior support of the current toy:        %s" % " ".join(str(p[1]) for p in prof))
        print("     every stopping time, K-EXTHIST:                               %s" % " ".join(str(p[3]) for p in prof))
# W4 reads in the abstract sense: which toy functional each read writes into the pointer
