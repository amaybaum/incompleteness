P = identity(2 * n)
names = [f"u{i}" for i in range(n)] + [f"v{i}" for i in range(n)]
fmt = lambda r: " + ".join(names[j] for j in range(2 * n) if (r >> j) & 1) or "0"
k = 0
for S in word:
    P = compose(lattice_update(n, S), P)
    if S == ((0, 1), (0, 5)):
        k += 1
        print(f"   read {k}: pointer u1 = {fmt(P[1])}   (toy initial (u0, v0) = (p, q) by convention)")
for i in (2, 3, 4):
    print(f"   memory {i}: u{i} = {fmt(P[i])}; v{i} = {fmt(P[n + i])}")
print(f"   toy: u0 = {fmt(P[0])}; v0 = {fmt(P[n])}")

# --- W4 skeleton search ----------------------------------------------------------------------
# The fixed word above does not reproduce W4's point mass even with K-EXTHIST, so it is not a
# faithful W4.  Skeleton: [pad_i idle steps, one read step, one store word] x 3, with pad_i in
# 0..3 (idle steps swap the toy's u and v, selecting which coordinate the next read reads), the
# store word any block anti-diagonal two-site word of length <= 6 (odd lengths allowed: idle
# sites end relabelled), one reused bath or a fresh bath per read.  Every prefix is a stopping
# time.  W4 control (green iff some skeleton word reaches a point mass under K-EXTHIST); the
# embedded verdict is the minimum support given all visible cells at any stopping time.
from itertools import product as _prod
stores = sorted({w for (l, w) in sorted((len(w), w) for Q, w in seen.items()
                 if len(w) <= 6 and all((Q[i] & m0) == 0 for i in (0, 2)) and all((Q[i] & m1) == 0 for i in (1, 3)))})
print(f"\nW4 skeleton search: {len(stores)} store words {[''.join(s) for s in stores]}")
for fresh in (False, True):
    n = 8 if fresh else 6
    baths = [5, 6, 7] if fresh else [5, 5, 5]
    best_h = best_e = (5, None)
    best_e_learn = None
    count = 0
    for pads in _prod(range(4), repeat=3):
        for sw in _prod(range(len(stores)), repeat=3):
            word = []
            for i in range(3):
                word += [()] * pads[i]
                word.append(((0, 1), (0, baths[i])))
                for lab in stores[sw[i]]:
                    word.append(((1, 2 + i),) if lab == "E" else ())
            prof, P = run_word(n, word, (1, 2, 3, 4), 0, (2, 3, 4))
            count += 1
            mh = min(p[3] for p in prof)
            me = min(p[0] for p in prof)
            if mh < best_h[0]:
                best_h = (mh, (pads, [''.join(stores[k]) for k in sw]))
            if me < best_e[0]:
                best_e = (me, (pads, [''.join(stores[k]) for k in sw]))
            if best_e_learn is None and any(p[0] == 1 and p[1] == 4 for p in prof):
                best_e_learn = (pads, [''.join(stores[k]) for k in sw])
    print(f"  [{'fresh bath per read' if fresh else 'one bath reused'}] {count} skeleton words:"
          f" W4 control (K-EXTHIST) min support {best_h[0]} e.g. pads/stores {best_h[1]}  -> {'GREEN' if best_h[0] == 1 else 'RED'};"
          f" embedded (all visible cells, every stopping time) min support {best_e[0]} e.g. {best_e[1]};"
          f" embedded learning (support 1, prior 4): {best_e_learn if best_e_learn else 'none'}")

