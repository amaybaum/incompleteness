# background subtraction for W-E3: same timing, (a) store steps idle (non-copying), (b) every step idle
for lab2, keep_reads, keep_stores in (("non-copying (stores idle)", True, False), ("background (all idle)", False, False)):
    w2 = []
    for i, sw in enumerate(("EEEO", "EEE", "EEE")):
        w2.append(((0, 1), (0, 5)) if keep_reads else ())
        for lab in sw:
            w2.append(((1, 2 + i),) if (lab == "E" and keep_stores) else ())
    pr2, P2 = run_word(n, w2, (1, 2, 3, 4), 0, (2, 3, 4))
    D = [P[0] ^ P2[0], P[n] ^ P2[n]]
    um = ((1 << (2 * n)) - 1) & ~mask_of(vis_coords(n, (1, 2, 3, 4)))
    Fu = [P[c] & um for c in vis_coords(n, (1, 2, 3, 4))]
    from f2 import rank as _rank
    cls = ("none" if all(d == 0 for d in D) else "known" if all(d & um == 0 for d in D)
           else "in memory" if _rank(Fu + [d & um for d in D]) == _rank(Fu) else "not in memory")
    print(f"  W-E3 {lab2}: support given all visible cells t=1..13: {' '.join(str(p[0]) for p in pr2)};"
          f" final toy difference D = ({fmt(D[0])}, {fmt(D[1])}): {cls}")
