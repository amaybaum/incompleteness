#!/usr/bin/env python3
"""p4_ones_fixing_lie.py -- exact Lie-closure computation over Q(sqrt3)(i), standard library only.
Research only; decides no round.

Candidate E4 / stroboscopic time on the configuration carrier: every native pair bijection P is the
time-one map of its principal-logarithm flow exp(t log P).  Question: does the real Lie algebra
generated by the 24 principal logarithms on C^4 leave the uniform ray u = (1,1,1,1) invariant (the
uniform-ray invariant of gate G4)?  Generators are scaled by 1/pi (a real scalar: spans unchanged).
Controls:
  POS adding the native-local phase generator log(S(x)I) must reach all of u(4) (dimension 16);
  NEG the uniform-ray test must be able to fail: it is applied to the POS algebra and must report
      a non-ones-fixing element;
  KNOB the other logarithm branch for eigenvalue -1 gives a different half-period flow of CNOT
      (G7: the branch must be fixed in the statement), while both are ones-fixing.
"""
from fractions import Fraction as Fr
from itertools import permutations

class R3:  # a + b*sqrt(3), a, b rational
    __slots__ = ('a', 'b')
    def __init__(s, a=0, b=0): s.a = Fr(a); s.b = Fr(b)
    def __add__(s, o): return R3(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return R3(s.a - o.a, s.b - o.b)
    def __mul__(s, o): return R3(s.a*o.a + 3*s.b*o.b, s.a*o.b + s.b*o.a)
    def __neg__(s): return R3(-s.a, -s.b)
    def inv(s):
        d = s.a*s.a - 3*s.b*s.b; return R3(s.a/d, -s.b/d)
    def iszero(s): return s.a == 0 and s.b == 0
    def __eq__(s, o): return s.a == o.a and s.b == o.b
class C3:  # x + i y, x, y in R3
    __slots__ = ('x', 'y')
    def __init__(s, x=None, y=None): s.x = x or R3(); s.y = y or R3()
    def __add__(s, o): return C3(s.x + o.x, s.y + o.y)
    def __sub__(s, o): return C3(s.x - o.x, s.y - o.y)
    def __mul__(s, o): return C3(s.x*o.x - s.y*o.y, s.x*o.y + s.y*o.x)
    def iszero(s): return s.x.iszero() and s.y.iszero()
    def __eq__(s, o): return s.x == o.x and s.y == o.y
def c(a=0, b=0, ai=0, bi=0): return C3(R3(a, b), R3(ai, bi))
N = 4
def mz(): return [[c() for _ in range(N)] for _ in range(N)]
def mmul(A, B):
    R = mz()
    for i in range(N):
        for j in range(N):
            s = c()
            for k in range(N): s = s + A[i][k]*B[k][j]
            R[i][j] = s
    return R
def madd(A, B): return [[A[i][j] + B[i][j] for j in range(N)] for i in range(N)]
def msc(z, A): return [[z*A[i][j] for j in range(N)] for i in range(N)]
def eye():
    M = mz()
    for i in range(N): M[i][i] = c(1)
    return M
def comm(A, B): return madd(mmul(A, B), msc(c(-1), mmul(B, A)))
def pmat(p):
    M = mz()
    for col, row in enumerate(p): M[row][col] = c(1)
    return M
# m-th roots of unity, m in {1,2,3,4}: exact
ROOT = {1: [c(1)], 2: [c(1), c(-1)], 4: [c(1), c(0, 0, 1), c(-1), c(0, 0, -1)],
        3: [c(1), c(Fr(-1, 2), 0, 0, Fr(1, 2)), c(Fr(-1, 2), 0, 0, Fr(-1, 2))]}
def conjc(z): return C3(z.x, -z.y)
def order(p):
    q = list(range(4)); k = 0
    while True:
        q = [p[x] for x in q]; k += 1
        if q == list(range(4)): return k
def plog(p, branch=+1):
    """(1/pi) * principal log of the permutation matrix; branch=-1 takes arg(-1) = -pi."""
    P = pmat(p); m = order(p); w = ROOT[m]
    pows = [eye()]
    for _ in range(m - 1): pows.append(mmul(pows[-1], P))
    L = mz()
    for j in range(m):
        Pi = mz()
        for k in range(m):
            Pi = madd(Pi, msc(conjc(w[(j*k) % m]), pows[k]))
        Pi = msc(c(Fr(1, m)), Pi)
        th = Fr(2*j, m)                        # arg / pi in [0, 2)
        if th > 1: th -= 2                     # principal: (-1, 1]
        if th == 1 and branch == -1: th = Fr(-1)
        L = madd(L, msc(c(0, 0, th), Pi))     # i * th * Pi
    return L
def vec(A):  # real coordinates over Q(sqrt3): 32 entries of R3
    v = []
    for i in range(N):
        for j in range(N): v += [A[i][j].x, A[i][j].y]
    return v
def reduce_into(basis, v):
    """basis: list of (pivot, vector) in echelon form over Q(sqrt3); returns reduced v."""
    v = list(v)
    for piv, bv in basis:
        if not v[piv].iszero():
            f = v[piv]
            v = [v[k] - f*bv[k] for k in range(len(v))]
    return v
def add_vec(basis, mats, A):
    v = reduce_into(basis, vec(A))
    for k, x in enumerate(v):
        if not x.iszero():
            f = x.inv(); v = [y*f for y in v]
            nb = []
            for piv, bv in basis:
                if not bv[k].iszero():
                    g = bv[k]; bv = [bv[t] - g*v[t] for t in range(len(v))]
                nb.append((piv, bv))
            basis[:] = nb + [(k, v)]; mats.append(A); return True
    return False
def lie_closure(gens):
    basis, mats = [], []
    for g in gens: add_vec(basis, mats, g)
    changed = True
    while changed:
        changed = False
        cur = list(mats)
        for i in range(len(cur)):
            for j in range(i + 1, len(cur)):
                if add_vec(basis, mats, comm(cur[i], cur[j])): changed = True
    return mats
def ones_fixing(A):
    w = [sum((A[i][j] for j in range(N)), c()) for i in range(N)]
    return all(w[i] == w[0] for i in range(N))
def skew(A): return all((A[i][j] + conjc(A[j][i])).iszero() for i in range(N) for j in range(N))

ok = True
gens = [plog(p) for p in permutations(range(4))]
ok &= all(skew(g) for g in gens)
alg = lie_closure(gens)
d = len(alg); of = all(ones_fixing(A) for A in alg)
print('native-permutation principal-log algebra: real dimension %d of 16; every element ones-fixing: %s' % (d, of))
# POS: add log(S (x) I) / pi = i * diag(0,0,1/2,1/2)
S = mz(); S[2][2] = c(0, 0, Fr(1, 2)); S[3][3] = c(0, 0, Fr(1, 2))
alg2 = lie_closure(gens + [S]); d2 = len(alg2); of2 = all(ones_fixing(A) for A in alg2)
print('POS with the native-local phase generator: dimension %d of 16; ones-fixing: %s' % (d2, of2))
ok &= (d2 == 16) and (not of2)
# KNOB: CNOT half-period flow under the two branches.  CNOT^(1/2) = P0 + P1 (x) [(I+X)/2 + e^{+-i pi/2}(I-X)/2]
cn = (0, 1, 3, 2)
L1, L2 = plog(cn, +1), plog(cn, -1)
print('KNOB: branch logs differ: %s; both ones-fixing: %s' % (not all(L1[i][j] == L2[i][j] for i in range(N) for j in range(N)),
      ones_fixing(L1) and ones_fixing(L2)))
alg3 = lie_closure([plog(p, -1) for p in permutations(range(4))])
print('KNOB: other-branch algebra dimension %d; ones-fixing: %s' % (len(alg3), all(ones_fixing(A) for A in alg3)))
if not ok:
    print('VERDICT VOID (a control failed)')
else:
    print('VERDICT E4-SCREEN: the stroboscopic-time algebra of the 24 native pair bijections has dimension %d and is %s; '
          'the positive control reaches dimension %d.' % (d, 'ones-fixing (uniform-ray invariant held: G4 fails)' if of
          else 'NOT ones-fixing (uniform-ray invariant broken)', d2))
