def lie_closure_dim(gens, maxit=12):
    """Real Lie algebra generated by anti-Hermitian matrices; return dimension."""
    basis = []

    def add(X):
        v = np.concatenate([X.real.ravel(), X.imag.ravel()])
        if not basis:
            if np.linalg.norm(v) > 1e-9:
                basis.append(v / np.linalg.norm(v))
                return True
            return False
        B = np.array(basis)
        r = v - B.T @ (B @ v)
        if np.linalg.norm(r) > 1e-7 * max(1, np.linalg.norm(v)):
            basis.append(r / np.linalg.norm(r))
            return True
        return False
    mats = []
    for g in gens:
        if add(g):
            mats.append(g)
    for _ in range(maxit):
        new = []
        for A in mats:
            for B in list(mats) + list(gens):
                Cm = A @ B - B @ A
                if add(Cm):
                    new.append(Cm)
        if not new:
            break
        mats += new
    return len(basis)


def principal_log_unitary(U):
    w, V = np.linalg.eig(U)
    # unitary => normal; orthonormalize eigenvectors via Schur for safety
    from scipy.linalg import schur
    T, Q = schur(U, output='complex')
    ang = np.angle(np.diag(T))
    return Q @ np.diag(1j * ang) @ Q.conj().T


