# Density criterion (W): (i) some g has infinite order modulo scalars; (ii) Ad(G) acts
# irreducibly on sl(4), i.e. the commutant of {g (x) conj(g)} on M_4 has dimension 2.
# Then the closure's Lie algebra meets su(4) nontrivially and is Ad(G)-invariant, so contains su(4).
# (i) is certified numerically up to the degree bound: entries lie in Q(zeta_8) (degree 4), so
# eigenvalue ratios have degree <= 256 over Q; a ratio that is a root of unity of order n has
# phi(n) <= 256, hence n <= 2*256^2 = 131072.  We check all n up to that bound.


def ratio_not_root_of_unity(U, nmax=131072):
    ev = np.linalg.eigvals(U)
    best = None
    for i in range(len(ev)):
        for j in range(len(ev)):
            if i == j:
                continue
            th = np.angle(ev[i] / ev[j]) / (2 * np.pi)
            n = np.arange(1, nmax + 1)
            dist = np.abs(n * th - np.round(n * th))
            # tolerance grows with n; float64 angle error ~1e-15
            if np.all(dist > n * 1e-13):
                return True, (i, j, th)
    return False, None


