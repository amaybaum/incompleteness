def weyl_ops(q, N):
    """Symmetric Weyl operators W(x, xi) on C^{q^N}, positions = registered values."""
    d = q ** N
    om = np.exp(2j * np.pi / q)
    inv2 = pow(2, -1, q)
    pts = list(itertools.product(range(q), repeat=N))
    idx = {p: i for i, p in enumerate(pts)}

    def X(a):
        U = np.zeros((d, d), complex)
        for p in pts:
            U[idx[tuple((np.array(p) + a) % q)], idx[p]] = 1
        return U

    def Z(b):
        return np.diag([om ** (int(np.dot(b, p)) % q) for p in pts])

    def W(x, xi):
        x = np.array(x) % q
        xi = np.array(xi) % q
        return om ** ((-inv2 * int(np.dot(xi, x))) % q) * (Z(xi) @ X(x))
    return W, pts, idx


def weil_unitary(q, N, Lmat):
    """Solve U W(z) = W(L z) U on generators; return U (unitary) or None if no solution."""
    W, pts, idx = weyl_ops(q, N)
    d = q ** N
    rows = []
    for k in range(2 * N):
        z = np.zeros(2 * N, int)
        z[k] = 1
        Lz = (Lmat @ z) % q
        A = W(z[:N], z[N:])
        B = W(Lz[:N], Lz[N:])
        # U A - B U = 0  <=>  (A^T kron I - I kron B) vec(U) = 0  (column-major vec)
        rows.append(np.kron(A.T, np.eye(d)) - np.kron(np.eye(d), B))
    Mbig = np.vstack(rows)
    u, s, vh = np.linalg.svd(Mbig)
    null = vh[np.abs(s) < 1e-8] if len(s) == d * d else None
    nnull = int(np.sum(s < 1e-8))
    if nnull == 0:
        return None, 0
    U = vh[-1].conj().reshape(d, d, order='F')
    U = U / np.sqrt(np.real(np.trace(U.conj().T @ U)) / d)
    return U, nnull


def leap_matrix(q, M):
    """Leap on z = (x, xi) = (cur, prev): x' = M x - xi, xi' = x."""
    N = M.shape[0]
    L = np.zeros((2 * N, 2 * N), int)
    L[:N, :N] = M % q
    L[:N, N:] = (-np.eye(N, dtype=int)) % q
    L[N:, :N] = np.eye(N, dtype=int)
    return L % q


