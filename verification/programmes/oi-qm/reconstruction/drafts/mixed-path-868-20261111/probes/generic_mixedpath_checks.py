#!/usr/bin/env python3
"""Generic exact checks for MIXED-PATH-1 Stage 1.  GENERIC MATHEMATICS ONLY.

No OI rule, lattice update, stencil simulation or native object is encoded or run.
W1-W3: integer norm arithmetic for the window.   L1-L3: abstract Z_q-linear response
models with random integer matrices (Theorem L).  X1: a Z_4 table with a non-coset prior.
P1: uniform-measure no-signalling <=> multiset equality (PAD), random response tables.
Exact integers / Fractions only.  Exit 0 iff every check passes.
"""
import itertools, random, sys
from fractions import Fraction as Fr
from math import isqrt, factorial
from collections import Counter

ok = True
def check(name, cond, info=""):
    global ok
    ok &= bool(cond)
    print(f"{'PASS' if cond else 'FAIL'}  {name}  {info}")

# ---------- W: window arithmetic -------------------------------------------------
def in_window(n, k):                       # ||n||_1 <= k  and  k^2 < 3 ||n||_2^2
    l1 = sum(abs(c) for c in n); l2sq = sum(c*c for c in n)
    return l1 <= k and k*k < 3*l2sq
R = 6
pts = [n for n in itertools.product(range(-R, R+1), repeat=3) if any(n)]
# W1: window ticks for n are exactly the integers in [||n||_1, sqrt(3)||n||_2); empty iff |nx|=|ny|=|nz|
w1 = True
for n in pts:
    l1 = sum(map(abs, n)); l2sq = sum(c*c for c in n)
    ks = [k for k in range(0, 4*R) if in_window(n, k)]
    kmax = isqrt(3*l2sq - 1)               # largest k with k^2 < 3 l2sq
    w1 &= ks == list(range(l1, kmax+1))
    diag = len({abs(c) for c in n}) == 1
    w1 &= (len(ks) == 0) == diag           # Cauchy-Schwarz equality case
check("W1 window = [l1, sqrt3*l2) ; empty iff body diagonal", w1, f"{len(pts)} vectors")
# W2: l1^2 = 3 l2^2 cos^2(theta), theta = angle to nearest body diagonal (exact, squared form)
w2 = all(sum(map(abs, n))**2 * 3 == 3 * max(abs(sum(s*c for s, c in zip(sg, n))) for sg in itertools.product((1,-1), repeat=3))**2
         for n in pts)
check("W2 ||n||_1 = max_diag |n.s| (so ratio cone/wave = 1/cos theta)", w2)
# W3: small table used in the text
tab = {D: [k for k in range(1, 40) if in_window((D,0,0), k)] for D in (1,2,3,4,5,6)}
check("W3 axis windows", tab == {1:[1], 2:[2,3], 3:[3,4,5], 4:[4,5,6], 5:[5,6,7,8], 6:[6,7,8,9,10]}, str(tab))
check("W3b face diagonal (2,2,0): window", [k for k in range(1,40) if in_window((2,2,0),k)] == [4], "k=4 only")
# W4: cap fraction 4(1-1/m) < 1 needs m < 4/3 for disjoint caps; orientation fractions as exact rationals
check("W4 cap fraction at m=21/20", 4*(1-Fr(20,21)) == Fr(4,21))

# ---------- L: Theorem L on abstract Z_q-linear response models ---------------------
def span(cols, q, dim):
    """subgroup of Z_q^dim generated by cols (brute force closure)."""
    S = {tuple([0]*dim)}
    frontier = [tuple([0]*dim)]
    while frontier:
        x = frontier.pop()
        for c in cols:
            y = tuple((a+b) % q for a, b in zip(x, c))
            if y not in S:
                S.add(y); frontier.append(y)
    return S
def matvec(M, x, q):
    return tuple(sum(a*b for a, b in zip(row, x)) % q for row in M)
def cols_of(M):
    return [tuple(row[j] for row in M) for j in range(len(M[0]))]

rng = random.Random(8681)
nL = dict(cases=0, ns=0, sig=0, nodep=0, masked_dep=0)
l1 = l2 = l3 = True
for trial in range(400):
    q = rng.choice([2, 3, 4])
    nw, dA, dB = rng.choice([2, 3]), rng.choice([1, 2]), rng.choice([1, 2])
    MA = [[rng.randrange(q) for _ in range(nw)] for _ in range(dA)]
    MB = [[rng.randrange(q) for _ in range(nw)] for _ in range(dB)]
    # setting translations: c_a in Z_q (one generator coordinate each wing), menu = 2 values
    vA  = [rng.randrange(q) for _ in range(dA)]   # own-setting column at A
    vAp = [rng.randrange(q) for _ in range(dA)]   # remote (b) column at A
    wB  = [rng.randrange(q) for _ in range(dB)]   # remote (a) column at B
    wBp = [rng.randrange(q) for _ in range(dB)]   # own-setting column at B
    if trial % 2 == 0:                            # force masking half the time: columns in the pad image
        d1 = [rng.randrange(q) for _ in range(nw)]; d2 = [rng.randrange(q) for _ in range(nw)]
        vAp = list(matvec(MA, d1, q)); wB = list(matvec(MB, d2, q))
    menu = [0, 1]
    Om = list(itertools.product(range(q), repeat=nw))
    def hA(o, a, b): return tuple((x + a*y + b*z) % q for x, y, z in zip(matvec(MA, o, q), vA, vAp))
    def hB(o, a, b): return tuple((x + a*y + b*z) % q for x, y, z in zip(matvec(MB, o, q), wB, wBp))
    table = {(a, b): Counter((hA(o, a, b), hB(o, a, b)) for o in Om) for a in menu for b in menu}
    margA = {(a, b): Counter(hA(o, a, b) for o in Om) for a in menu for b in menu}
    margB = {(a, b): Counter(hB(o, a, b) for o in Om) for a in menu for b in menu}
    nsA = all(margA[(a, 0)] == margA[(a, 1)] for a in menu)
    nsB = all(margB[(0, b)] == margB[(1, b)] for b in menu)
    imA, imB = span(cols_of(MA), q, dA), span(cols_of(MB), q, dB)
    critA, critB = tuple(x % q for x in vAp) in imA, tuple(x % q for x in wB) in imB
    l1 &= (nsA == critA) and (nsB == critB)       # (i) masking criterion, both directions
    nL["cases"] += 1
    depA = any(hA(o, a, 0) != hA(o, a, 1) for o in Om for a in menu)
    depB = any(hB(o, 0, b) != hB(o, 1, b) for o in Om for b in menu)
    if not (depA or depB): nL["nodep"] += 1
    if nsA and nsB:
        nL["ns"] += 1
        if depA or depB: nL["masked_dep"] += 1
        # (ii) explicit local model: Omega' = Omega + a*dB_ + b*dA_ ; fA(O',a), fB(O',b)
        dA_ = next(o for o in Om if matvec(MA, o, q) == tuple(x % q for x in vAp))   # M_A dA_ = vAp
        dB_ = next(o for o in Om if matvec(MB, o, q) == tuple(x % q for x in wB))    # M_B dB_ = wB
        def fA(op, a):   # h_A as a function of (Omega', a)
            base = matvec(MA, op, q); corr = matvec(MA, dB_, q)
            return tuple((x - a*c + a*y) % q for x, c, y in zip(base, corr, vA))
        def fB(op, b):
            base = matvec(MB, op, q); corr = matvec(MB, dA_, q)
            return tuple((x - b*c + b*y) % q for x, c, y in zip(base, corr, wBp))
        loc = {(a, b): Counter((fA(o, a), fB(o, b)) for o in Om) for a in menu for b in menu}
        l2 &= loc == table
    else:
        nL["sig"] += 1
        l3 &= not (critA and critB)
check("L1 NS at a wing <=> remote-setting column in pad image (400 random Z_q-linear models)", l1, str(nL))
check("L2 NS at both wings => table equals an explicit local model with uniform Omega'", l2,
      f"{nL['ns']} NS cases, {nL['masked_dep']} with pointwise remote dependence")
check("L3 non-vacuity: signalling cases and masked-dependence cases both occur", nL["sig"] > 20 and nL["masked_dep"] > 20)

# ---------- X1: additive settings + NON-coset prior can be NS and Bell-nonlocal -------
q = 4
sigma = {0: 1, 1: 0, 2: 2, 3: 3}                 # a non-affine permutation of Z_4
prior = [(p, sigma[p]) for p in range(q)]        # uniform on the graph of sigma (not a coset of Z_4^2)
T = {(a, b): Counter(((p + b) % q, (pp + a) % q) for p, pp in prior) for a in (0, 1) for b in (0, 1)}
nsA = all(Counter(x for (x, y), c in T[(a, 0)].items() for _ in range(c)) ==
          Counter(x for (x, y), c in T[(a, 1)].items() for _ in range(c)) for a in (0, 1))
nsB = all(Counter(y for (x, y), c in T[(0, b)].items() for _ in range(c)) ==
          Counter(y for (x, y), c in T[(1, b)].items() for _ in range(c)) for b in (0, 1))
# deterministic local strategies compatible with the support of all four contexts
compat = [(x0, x1, y0, y1) for x0, x1, y0, y1 in itertools.product(range(q), repeat=4)
          if all(T[(a, b)][((x0, x1)[a], (y0, y1)[b])] > 0 for a in (0, 1) for b in (0, 1))]
check("X1a non-coset example is no-signalling", nsA and nsB)
check("X1b exactly one support-compatible deterministic strategy, so the table (uniform marginals) is not Bell-local",
      len(compat) == 1, str(compat))
# explicit CHSH violation by binary coarse-graining (brute force over +-1 maps of the 4-letter alphabets)
best = Fr(0)
maps = list(itertools.product((1, -1), repeat=q))
for f0 in maps:
    for f1 in maps:
        f = (f0, f1)
        # for fixed f the optimum over g0,g1 is separable per letter
        val = Fr(0)
        for b in (0, 1):
            for y in range(q):
                coef = Fr(0)
                for a in (0, 1):
                    s = -1 if (a, b) == (1, 1) else 1
                    for (x, yy), c in T[(a, b)].items():
                        if yy == y: coef += s * f[a][x] * Fr(c, q)
                val += abs(coef)
        best = max(best, val)
check("X1c max CHSH over binary coarse-grainings exceeds 2", best > 2, f"max = {best}")
# countercontrol: the same construction with a coset prior (sigma = identity) is local
T0 = {(a, b): Counter(((p + b) % q, (p + a) % q) for p in range(q)) for a in (0, 1) for b in (0, 1)}
compat0 = [(x0, x1, y0, y1) for x0, x1, y0, y1 in itertools.product(range(q), repeat=4)
           if all(T0[(a, b)][((x0, x1)[a], (y0, y1)[b])] > 0 for a in (0, 1) for b in (0, 1))]
mix = {k: Counter() for k in T0}
for (x0, x1, y0, y1) in compat0:
    for a in (0, 1):
        for b in (0, 1): mix[(a, b)][((x0, x1)[a], (y0, y1)[b])] += 1
check("X1d countercontrol: coset prior (sigma=id) table is the uniform mixture of its compatible strategies",
      len(compat0) == q and mix == T0)

# ---------- P1: uniform measure: NS <=> PAD (multiset equality) ----------------------
p1 = True
rng = random.Random(8682)
for trial in range(300):
    nlam, nh = rng.choice([4, 6, 8]), rng.choice([2, 3])
    h0 = [rng.randrange(nh) for _ in range(nlam)]
    h1 = h0[:] ; rng.shuffle(h1)
    if trial % 3 == 0: h1[rng.randrange(nlam)] = rng.randrange(nh)   # may break equality
    ns = Counter(h0) == Counter(h1)
    # PAD: exists a bijection s with h1[s(l)] = h0[l]  (greedy matching by value)
    pools = {}
    for i, v in enumerate(h1): pools.setdefault(v, []).append(i)
    pad = True
    for v in h0:
        if pools.get(v): pools[v].pop()
        else: pad = False; break
    p1 &= ns == pad
check("P1 uniform prior: equal history laws <=> a relabelling bijection exists", p1)

print("ALL PASS" if ok else "SOME FAIL")
sys.exit(0 if ok else 1)
