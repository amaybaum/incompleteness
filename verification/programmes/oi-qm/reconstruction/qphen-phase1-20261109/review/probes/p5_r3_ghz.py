"""Probe P5-GHZ (QPHEN Phase 1 r3, writer's checks). Exact Gaussian-integer arithmetic; no import from p1-p4.

(1) Conventional GHZ |GHZ> = (|000> + |111>)/sqrt2: <XXX> = +1, <XYY> = <YXY> = <YYX> = -1,
    Mermin XXX - XYY - YXY - YYX = 4; local maximum 2 (exhaustive over 2^6 = 64 assignments of x_i, y_i).
    X/Z content: every Pauli string over {I, X, Z} with nonzero expectation, and one local assignment that
    satisfies all of them with their signs (no all-versus-nothing contradiction from X/Z reads).
(2) Triangle graph state CZ12 CZ13 CZ23 |+++>: <XZZ> = <ZXZ> = <ZZX> = +1, <XXX> = -1;
    XZZ + ZXZ + ZZX - XXX = 4; local maximum 2 (exhaustive over 64 assignments of x_i, z_i).
(3) A local-Clifford map from |GHZ> to the triangle graph state (search over single-qubit Cliffords
    generated by H and S, 24 mod phase, on each qubit), checked up to a global phase.
"""
import itertools
import numpy as np

I2 = np.eye(2, dtype=complex); X = np.array([[0, 1], [1, 0]], dtype=complex)
Y = np.array([[0, -1j], [1j, 0]]); Z = np.diag([1, -1]).astype(complex)
P = {'I': I2, 'X': X, 'Y': Y, 'Z': Z}
def op(s):
    M = np.array([[1]], dtype=complex)
    for ch in s:
        M = np.kron(M, P[ch])
    return M
def ev(psi, s):
    v = psi.conj() @ op(s) @ psi
    r = complex(np.round(v, 12))
    assert abs(r.imag) < 1e-12
    return int(round(r.real)) if abs(r.real - round(r.real)) < 1e-12 else r.real

ghz = np.zeros(8, dtype=complex); ghz[0] = ghz[7] = 1 / np.sqrt(2)
plus = np.ones(8, dtype=complex) / np.sqrt(8)
CZ = lambda i, j: np.diag([(-1) ** (((k >> (2 - i)) & 1) * ((k >> (2 - j)) & 1)) for k in range(8)]).astype(complex)
tri = CZ(0, 1) @ CZ(0, 2) @ CZ(1, 2) @ plus

def lhv_max(terms):
    """terms: list of (sign, string over two local labels); exhaustive over +-1 values per qubit and label"""
    labels = sorted({c for _, s in terms for c in s})
    best = -99
    for vals in itertools.product((1, -1), repeat=3 * len(labels)):
        v = {(q, l): vals[q * len(labels) + k] for q in range(3) for k, l in enumerate(labels)}
        tot = sum(sg * np.prod([v[(q, c)] for q, c in enumerate(s)]) for sg, s in terms)
        best = max(best, tot)
    return best, 2 ** (3 * len(labels))

if __name__ == '__main__':
    g = {s: ev(ghz, s) for s in ('XXX', 'XYY', 'YXY', 'YYX', 'ZZZ')}
    M = g['XXX'] - g['XYY'] - g['YXY'] - g['YYX']
    lm, n = lhv_max([(1, 'XXX'), (-1, 'XYY'), (-1, 'YXY'), (-1, 'YYX')])
    print('(1) GHZ:', g, '| Mermin =', M, '| local max =', lm, 'over', n, 'assignments')
    xz = {s: ev(ghz, s) for s in (''.join(t) for t in itertools.product('IXZ', repeat=3)) if s != 'III'}
    nz = {s: v for s, v in xz.items() if v != 0}
    full = [s for s in nz if 'I' not in s]
    ok = all(np.prod([1 for c in s if c != 'I']) == v for s, v in nz.items())   # assignment x_i = z_i = +1
    print('    nonzero X/Z strings on GHZ:', nz, '| full-weight ones:', full,
          '| all satisfied by x_i = z_i = +1:', ok)
    t = {s: ev(tri, s) for s in ('XZZ', 'ZXZ', 'ZZX', 'XXX')}
    W = t['XZZ'] + t['ZXZ'] + t['ZZX'] - t['XXX']
    lm2, n2 = lhv_max([(1, 'XZZ'), (1, 'ZXZ'), (1, 'ZZX'), (-1, 'XXX')])
    print('(2) triangle graph state:', t, '| XZZ + ZXZ + ZZX - XXX =', W, '| local max =', lm2, 'over', n2, 'assignments')
    # (3) local-Clifford search
    H = np.array([[1, 1], [1, -1]]) / np.sqrt(2); S = np.diag([1, 1j])
    words = {'': I2}
    frontier = ['']
    def key(U):
        k = np.flatnonzero(np.abs(U.ravel()) > 1e-9)[0]; ph = U.ravel()[k] / abs(U.ravel()[k])
        return tuple(np.round(U.ravel() / ph, 8))
    seen = {key(I2): ''}
    while frontier:
        nf = []
        for w in frontier:
            for name, g1 in (('H', H), ('S', S)):
                U = g1 @ words[w]; k = key(U)
                if k not in seen:
                    seen[k] = w + name; words[w + name] = U; nf.append(w + name)
        frontier = nf
    cl1 = [(seen[k], words[seen[k]]) for k in seen]
    hits = []
    for (n1, U1), (n2, U2), (n3, U3) in itertools.product(cl1, repeat=3):
        v = np.kron(np.kron(U1, U2), U3) @ ghz
        if abs(abs(np.vdot(tri, v)) - 1) < 1e-9:
            hits.append((n1 or 'I', n2 or 'I', n3 or 'I'))
    hits.sort(key=lambda h: sum(len(x) for x in h))
    print('(3) single-qubit Cliffords (mod phase):', len(cl1), '| LC maps GHZ -> triangle found:', len(hits),
          '| shortest (a word lists gates in the order they act: "HS" is the operator S.H):', hits[:3])
