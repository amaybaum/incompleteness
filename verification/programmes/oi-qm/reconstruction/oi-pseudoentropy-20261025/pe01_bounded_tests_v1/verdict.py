"""PE-01 verdict, generated from the measurement JSON alone (PLAN.md §6).

  python3 -I -B verdict.py MEASUREMENTS.json --out DIR      writes DIR/verdict.json and DIR/verdict.txt
  python3 -I -B verdict.py MEASUREMENTS.json --check        regenerates and runs the VG self-test only

Every number in the text is read from the measurements. VOID takes precedence: if any checkpoint
failed or was not evaluated, the text names the failed checkpoints and prints nothing else. The VG
self-test regenerates the verdict and compares, flips each control flag in a copy (each must yield
VOID naming it), and requires the text check to fail on a text without the resource-model
limitation sentence.
"""
import copy
import json
import os
import sys
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pe01 import cx  # noqa: E402  (standard library only)

LIMITATION = ("The horizon bound K < 2^(n-m) (theta = n+1) is a consequence of the selected resource model: "
              "memory + clock + output <= theta. It is not a limit OI imposes on observers.")
D8, D4 = Fraction(1, 8), Fraction(1, 4)
SCOPE = {
    "emb_m1_all": "all 16 observers with m = 1, every F",
    "emb_m1_passive": "the 4 passive observers with m = 1, every F",
    "emb_m2_all": "all 9216 observers with m = 2, every F",
    "emb_m2_passive": "the 576 passive observers with m = 2, every F",
    "emb_m3_passive": "passive observers with m = 3 up to simultaneous conjugacy fixing v_0 (306432 canonical forms)",
    "lin_m1": "linear-filter observers with m = 1 (read as passive, open item LF-A)",
    "lin_m2": "linear-filter observers with m = 2 (read as passive, open item LF-A)",
    "lin_m3": "linear-filter observers with m = 3 (read as passive, open item LF-A)",
    "lin_m4": "linear-filter observers with m = 4 (read as passive, open item LF-A)",
}


def ex(s):
    return cx.exact(s)


def check_exact_tree(obj, path="$"):
    """EX3 on the read side: no float outside display_* keys."""
    if isinstance(obj, float):
        raise ValueError("EX3: float at %s" % path)
    if isinstance(obj, dict):
        for k, v in obj.items():
            if not (isinstance(k, str) and k.startswith("display_")):
                check_exact_tree(v, path + "." + str(k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            check_exact_tree(v, "%s[%d]" % (path, i))


def check_text(text):
    """A verdict text that is not VOID must carry the limitation sentence of §7."""
    if text.startswith("VOID"):
        return True
    return LIMITATION in text


def horizons(values):
    vals = [ex(v) for v in values]
    kz = -1
    for K, v in enumerate(vals):
        if v == 0:
            kz = K
        else:
            break
    kd = {}
    for d, nm in ((D8, "1/8"), (D4, "1/4")):
        kd[nm] = next((K for K, v in enumerate(vals) if v >= d), None)
    return kz, kd, len(vals) - 1


def fmt_h(kz, kd, cap, det=None):
    s = "K_zero=%d, K_1/8=%s, K_1/4=%s (scope K <= %d)" % (kz, kd["1/8"], kd["1/4"], cap)
    if det is not None and not all(det):
        s += " [lower bounds in part of the range: horizons are bounds]"
    return s


def tag_for(cname, gname, n, rec):
    """Productivity tag (§6 item 5), mechanical part. candidate-NEW is never assigned here: it
    requires the §9 literature check, which this run does not perform."""
    if cname in ("U", "U_bayes"):
        return "COVERED-corpus (support bound, Structure.md:1256)"
    if cname.startswith("B4") and rec.get("K_first") is not None and rec["K_first"] >= rec.get("counting_horizon", 10 ** 9):
        return "COVERED-corpus (B4 at or beyond its counting horizon)"
    if cname == "B1" and gname in ("G_lin", "G_lin_sib") and rec["K_zero"] == n:
        return "COVERED-literature (B1 K1 fires on G_lin at K = n+1)"
    if cname.startswith("B4") and rec.get("K_first") is not None and rec["K_first"] == rec.get("counting_horizon"):
        return "COVERED-literature (the B4 counting bound)"
    if gname == "G_dec":
        return "control"
    return "untagged: eligible for candidate-NEW review only after the §9 literature check"


def generate(meas):
    """Return (verdict_class, text)."""
    check_exact_tree(meas)
    ctl = meas["controls"]
    scope = meas["control_scope"]
    failed = sorted(k for k in scope if ctl[k]["pass"] is not True)
    if failed or not meas["controls_green"]:
        return "VOID", "VOID: failed checkpoint(s): %s" % ", ".join(failed or ["controls_green"])
    smoke = meas["mode"] != "result"
    L = []
    if smoke:
        L.append("SMOKE OUTPUT: NOT A RESULT. Local smoke scope only; checkpoints outside it were not evaluated.")
    L.append("PE-01 verdict, generated by verdict.py from measurements.json. Every number below is read from it.")
    L.append("Run commit %s; PLAN.md blob %s; A1 blob %s." % (meas["commit"], meas["plan_blob"], meas["a1_blob"]))
    L.append("theta = n+1: %s. K_LP(n): %s. Passive m = 3 scope: option (%s), caps %s." % (
        meas["theta_by_n"], meas["K_LP_by_n"], meas["m3_passive_scope"], meas["m3_passive_K_cap"]))
    L.append("Checkpoints green: %s." % ", ".join("%s(%d)" % (k, ctl[k]["checks"]) for k in scope))
    not_done = {k: v["status"] for k, v in meas["shards"].items() if v["status"] != "complete"}
    if not_done:
        L.append("Shards not complete (no verdict for their cells): %s." % ", ".join("%s: %s" % kv for kv in sorted(not_done.items())))
    if meas.get("pending"):
        L.append("Open plan items (not computed, or computed under a named reading): %s." % ", ".join(sorted(meas["pending"])))
    # ---- horizons
    L.append("")
    L.append("1. Horizons. PROVED (exhaustive finite): each statement quantifies only over the named class, "
             "knowledge level, generator, n and the stated K scope. Embedded distinguishing curves (optimal F) are "
             "measurements bearing on the second clause of book/ch18-beyond.md:114; they are not COUNTEREXAMPLEs.")
    for sid, r in sorted(meas["results"].items(), key=lambda kv: kv[0]):
        if "classes" not in r:
            continue
        n = r.get("n")
        for cname in sorted(r["classes"]):
            for gname in sorted(r["classes"][cname]):
                rec = r["classes"][cname][gname]
                kz, kd, cap = horizons(rec["values"])
                L.append("  [%s] %s K1 on %s, n=%s: %s. Tag: %s." % (sid, cname, gname, n, fmt_h(kz, kd, cap, rec.get("exact")),
                                                                   tag_for(cname, gname, n, rec)))
        for cname in sorted(r.get("k0", {})):
            rec = r["k0"][cname]
            if "pending" in rec:
                L.append("  [%s] %s K0: not computed (open item %s)." % (sid, cname, rec["pending"]))
                continue
            for form in ("worst", "average"):
                fr = rec[form]
                if "lower" in fr:
                    lo, hi = fr["lower"], fr["upper"]
                    kz1, kd1, cap1 = horizons(lo["values"])
                    kz2, kd2, cap2 = horizons(hi["values"])
                    nex = sum(1 for e in fr["exact"] if e)
                    L.append("  [%s] %s K0 %s: interval; lower end %s; upper end %s; exact at %d of %d K." % (
                        sid, cname, form, fmt_h(kz1, kd1, cap1), fmt_h(kz2, kd2, cap2), nex, len(fr["exact"])))
                else:
                    kz, kd, cap = horizons(fr["values"])
                    note = " (deterministic tests: a lower bound on the randomized worst case)" if form == "worst" and cname.startswith("emb_m") and "_m3" not in cname else ""
                    L.append("  [%s] %s K0 %s: %s%s." % (sid, cname, form, fmt_h(kz, kd, cap, fr.get("exact")), note))
            if "randomized" in rec:
                rz = rec["randomized"]
                kz, kd, cap = horizons(rz["values"])
                kza, kda, _ = horizons(rz["all_positive"])
                L.append("  [%s] %s K0 randomized worst case (exact LP, K <= K_LP = %d): %s; all-positive pattern: K_zero=%d, K_1/8=%s." % (
                    sid, cname, rz["K_LP"], fmt_h(kz, kd, cap), kza, kda["1/8"]))
    # ---- witnesses
    L.append("")
    L.append("2. Prediction witnesses (§6 item 4), per (generator, n, observer subclass); never pooled.")
    th = meas["theta_by_n"]
    green = meas["controls_green"] and not smoke
    combos = {}
    for w in meas["witnesses"]:
        combos.setdefault((w["generator"], w["n"], w["subclass"]), []).append(w)
    counter = []
    for sid, r in sorted(meas["results"].items()):
        for sub, win in sorted(r.get("windows", {}).items()):
            gname = {"lin": "G_lin", "filt": "G_filt", "clk": "G_clk"}[r["family"]]
            key = (gname, r["n"], sub)
            ws = combos.get(key, [])
            if not ws:
                L.append("  %s n=%d %s: no witness within the enumerated scope at any footprint (%s; K <= %s)." % (
                    gname, r["n"], sub, SCOPE.get(sub, sub), r.get("K_max", r.get("K_cap"))))
                continue
            kinds = []
            for w in sorted(ws, key=lambda x: x["K"]):
                kind, fails = cx.classify(w, th, green)
                kinds.append(kind)
                L.append("  %s n=%d %s, K=%d: %s (failed: %s); adv_pred at K'=%s: %s; footprint %d (theta %d); "
                         "table size %d bits; K_cx=%d; K0 status: %s; %s." % (
                             gname, r["n"], sub, w["K"], kind, ",".join(fails) or "none", w["window"],
                             ", ".join(w["adv_pred"]), w["footprint"], th[str(r["n"])], w["table_size_bits"],
                             w["K_cx"], "witness on every phi of the family" if w["K0_status"] else "not family-wide",
                             w["realization"]))
                if kind == "COUNTEREXAMPLE":
                    counter.append(w)
            if "COUNTEREXAMPLE" not in kinds:
                if "unrestricted-footprint witness" in kinds:
                    L.append("    Attribution: unpredictability in this combination is attributed to resources; "
                             "a limitation of the resource model (§7).")
                else:
                    L.append("    Attribution: no witness within the enumerated scope at any footprint meeting (a)-(e).")
    # ---- limitation and region
    L.append("")
    L.append("3. " + LIMITATION)
    ar = meas.get("AR") or {}
    reg = ar.get("region", {}).get("n+1", {})
    L.append("   Admissible region for theta = n+1, recomputed from the measured Z(phi) and K_cx(phi) "
             "(cells G_lin | G_filt | G_clk; '-' empty):")
    for n in sorted(reg, key=int):
        cells = []
        for m, row in enumerate(reg[n], start=1):
            cells.append("m=%d: %s" % (m, " | ".join("-" if c is None else "[%d,%d]" % tuple(c) for c in row)))
        L.append("     n=%s  %s" % (n, "; ".join(cells)))
    L.append("   Z(phi) measured: %s; K_cx(phi): %s." % (ar.get("Z"), ar.get("K_cx")))
    L.append("   Where a region cell is empty, 'no admissible witness' there is a fact about the resource model, "
             "not a measurement. The fixed clock charge can overcharge an observer whose memory already keeps "
             "time, so (f) is conservative toward the claim under audit.")
    # ---- outcome
    L.append("")
    if counter:
        L.append("4. Stage outcome: COUNTEREXAMPLE to the universal form of book/ch18-beyond.md:114, by %d witness(es) "
                 "meeting (a)-(f). It refutes only the universal form; it says nothing about the realization of the "
                 "actual world, nor about the 10^-32 statement." % len(counter))
    else:
        L.append("4. Stage outcome: no COUNTEREXAMPLE within the enumerated scope. COVERED findings are tagged above; "
                 "bounded theorems need a written proof under independent review. Otherwise OPEN.")
    L.append("   No finite result here establishes the universal form. No asymptotic, circuit-security, "
             "cryptographic-security or quantum-reproduction claim is made.")
    return ("SMOKE" if smoke else ("COUNTEREXAMPLE" if counter else "NO-COUNTEREXAMPLE")), "\n".join(L) + "\n"


def vg_selftest(meas, text):
    out = {"regenerated_identical": generate(meas)[1] == text, "flips": {}, "text_check": {}}
    for k in meas["control_scope"]:
        m2 = copy.deepcopy(meas)
        m2["controls"][k]["pass"] = not m2["controls"][k]["pass"] if m2["controls"][k]["pass"] is not None else False
        cls, t2 = generate(m2)
        out["flips"][k] = cls == "VOID" and k in t2
    out["text_check"]["accepts_generated"] = check_text(text)
    out["text_check"]["rejects_without_sentence"] = not check_text(text.replace(LIMITATION, ""))
    out["pass"] = (out["regenerated_identical"] and all(out["flips"].values())
                   and out["text_check"]["accepts_generated"] and out["text_check"]["rejects_without_sentence"])
    return out


def main(argv):
    src = argv[0]
    meas = json.load(open(src))
    cls, text = generate(meas)
    vg = vg_selftest(meas, text)
    if not vg["pass"]:
        cls, text = "VOID", "VOID: failed checkpoint(s): VG\n"
    if "--check" in argv:
        print(json.dumps({"class": cls, "VG": vg}, indent=1, sort_keys=True))
        return 0 if vg["pass"] else 1
    out = argv[argv.index("--out") + 1]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "verdict.json"), "w") as f:
        json.dump({"class": cls, "text": text, "VG": vg, "measurements_commit": meas["commit"]}, f, sort_keys=True, indent=1)
        f.write("\n")
    with open(os.path.join(out, "verdict.txt"), "w") as f:
        f.write(text)
    print(cls)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
