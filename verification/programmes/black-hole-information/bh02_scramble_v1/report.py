    w("")
    w("- **C1.** `P_π|x⟩ = |π(x)⟩`. A configuration basis vector is a tensor product of one basis")
    w("  vector per coordinate, so for any aligned `R` its `d_R × d_B` amplitude matrix has one")
    w("  nonzero entry: Schmidt rank 1, `S(R) = 0`. Powers of `π` are permutations, so this holds at")
    w("  every step.")
    w("- **C2(i).** `(P_π ψ)_y = ψ_{π⁻¹(y)}`: the amplitudes are relabelled, so their multiset and")
    w("  the support size are invariant; the amplitude matrix has at most `|supp ψ_0|` nonzero")
    w("  entries, hence rank `≤ |supp ψ_0|` and `S(R) ≤ ln|supp ψ_0|`.")
    w("- **C2(ii).** The configuration-basis diagonal of `ρ_R` is the marginal `p_R`; the diagonal")
    w("  is majorized by the spectrum, so `S(ρ_R) ≤ H(p_R)`; likewise `S(ρ_B) ≤ H(p_B)` and")
    w("  `S(ρ_R) = S(ρ_B)`. `H(p_R) ≤ H(p_t) = H(p_0)` because a marginal has at most the joint")
    w("  entropy and `p_t` is a relabelling of `p_0`.")
    w("- **C2(iii).** `P_π^†|+^n⟩ = |+^n⟩`, so `F = |⟨+^n|ψ_t⟩|²` is conserved. `|+^n⟩ =")
    w("  |+_R⟩⊗|+_B⟩` is a product state and the largest overlap of `ψ` with a product state is")
    w("  `λ_max(ρ_R)`, so `λ_max ≥ F`, `S_∞ ≤ −ln F`, `S_2 = −ln Σλ² ≤ −2 ln λ_max ≤ −2 ln F`.")
    w("- **C2 tightness.** A CNOT network (a permutation) maps `|+⟩^k|0⟩^{n−k}` to `k` Bell pairs")
    w("  across the cut; exact rank `2^k` with exact purity `2^{−k}` forces a flat spectrum, so")
    w("  `S = k ln 2 = H(p_0)`.")
    w("- **C4.** For a classical distribution, `H(p_{R_t}) ≤ H(p_t) = H(p_0)`, and at full emission")
    w("  the marginal is the joint: the curve ends at its maximum.")
